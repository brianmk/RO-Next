/// Data file path inside the client archive (`data\client\...`).
const DATA_PATH: &str = "data\\client\\weapons.ron";
/// Fallback copy of the same file, compiled into the client.
const FALLBACK: &str = include_str!("../../archive/data/client/weapons.ron");

/// Weapon kind (the weapon's sprite family / attack behaviour class).
///
/// The variants mirror the rAthena `enum weapon_type` names; the dual-wield
/// display values have their own kinds so the combined weapon sprite is used.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Deserialize)]
pub enum WeaponKind {
    Fist,
    Dagger,
    OneHandedSword,
    TwoHandedSword,
    OneHandedSpear,
    TwoHandedSpear,
    OneHandedAxe,
    TwoHandedAxe,
    Mace,
    TwoHandedMace,
    Staff,
    TwoHandedStaff,
    Bow,
    Knuckle,
    MusicalInstrument,
    Whip,
    Book,
    Katar,
    Revolver,
    Rifle,
    Gatling,
    Shotgun,
    Grenade,
    Huuma,
    DoubleDagger,
    DoubleSword,
    DoubleAxe,
    DaggerSword,
    DaggerAxe,
    SwordAxe,
    /// A weapon value that is not part of the data table.
    Unknown,
}

/// Ammo kind required by a weapon (`enum e_ammo_type` in rAthena).
///
/// This is the semantic ammo the server expects; only [`ProjectileKind`]s with
/// verified flying sprites spawn a visual auto-attack projectile.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Deserialize)]
pub enum AmmoKind {
    Arrow,
    Bullet,
    Shell,
    Grenade,
    Shuriken,
    Kunai,
    Cannonball,
    ThrowWeapon,
    Dagger,
}

/// Visual projectile spawned on an auto attack.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Deserialize)]
pub enum ProjectileKind {
    Arrow,
}

/// One step of the candidate path construction order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
enum CandidateStep {
    /// `per_job` template with the numeric weapon value as variant.
    PerJobNumeric,
    /// `per_job` template with every sprite family variant of the kind.
    PerJobVariant,
    /// `classic_weapon` template with the numeric weapon value.
    ClassicNumeric,
    /// `classic_weapon` template with every sprite family variant of the kind.
    ClassicVariant,
}

/// Sprite path templates (`{folder}`, `{prefix}`, `{sex}` and `{variant}`
/// placeholders).
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct PathTemplates {
    per_job: String,
    classic_weapon: String,
}

/// Sex suffixes used by the sprite file naming.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct SexSuffixes {
    male: String,
    female: String,
}

/// Candidate construction order for the three weapon value classes.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct FallbackChains {
    server_type: Vec<CandidateStep>,
    item_view: Vec<CandidateStep>,
    unknown: Vec<CandidateStep>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct ServerTypeRow {
    value: u32,
    kind: WeaponKind,
    name: String,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct KindRow {
    kind: WeaponKind,
    #[allow(dead_code)]
    subtype: String,
    variants: Vec<String>,
    range: u8,
    ammo: Option<AmmoKind>,
    projectile: Option<ProjectileKind>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct ItemRangeRow {
    kind: WeaponKind,
    start: u32,
    end: u32,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct ItemViewRow {
    view: u32,
    kind: WeaponKind,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct ProjectileRow {
    kind: ProjectileKind,
    assets: Vec<String>,
    fallback_assets: Vec<String>,
    flight_ms: u32,
}

/// The parsed data file.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct WeaponFile {
    #[allow(dead_code)]
    provenance: String,
    #[allow(dead_code)]
    version: u32,
    paths: PathTemplates,
    sex_suffix: SexSuffixes,
    fallbacks: FallbackChains,
    server_types: Vec<ServerTypeRow>,
    kinds: Vec<KindRow>,
    item_ranges: Vec<ItemRangeRow>,
    item_views: Vec<ItemViewRow>,
    projectiles: Vec<ProjectileRow>,
}

/// Runtime profile of one weapon kind.
#[derive(Debug, Clone)]
pub struct WeaponProfile {
    kind: WeaponKind,
    subtype: String,
    variants: Vec<String>,
    attack_range: u8,
    ammo: Option<AmmoKind>,
    projectile: Option<ProjectileKind>,
}

impl WeaponProfile {
    /// Weapon kind of the profile.
    pub fn kind(&self) -> WeaponKind {
        self.kind
    }

    /// rAthena `SubType` name of the kind (provenance/debug only).
    pub fn subtype(&self) -> &str {
        &self.subtype
    }

    /// Ordered classic client sprite family names of the kind.
    pub fn sprite_variants(&self) -> &[String] {
        &self.variants
    }

    /// Authoritative weapon attack range in tiles (rAthena `Range`).
    pub fn attack_range(&self) -> u8 {
        self.attack_range
    }

    /// Ammo kind the server expects for this weapon.
    pub fn ammo(&self) -> Option<AmmoKind> {
        self.ammo
    }

    /// Visual projectile kind spawned on auto attacks, if any.
    pub fn projectile(&self) -> Option<ProjectileKind> {
        self.projectile
    }
}

/// Runtime profile of one flying projectile.
#[derive(Debug, Clone)]
pub struct ProjectileProfile {
    kind: ProjectileKind,
    assets: Vec<String>,
    fallback_assets: Vec<String>,
    flight_ms: u32,
}

impl ProjectileProfile {
    /// Projectile kind.
    pub fn kind(&self) -> ProjectileKind {
        self.kind
    }

    /// Sprite paths of the preferred projectile sprites (relative to
    /// `data\sprite\`, without extension), most preferred first.
    pub fn assets(&self) -> &[String] {
        &self.assets
    }

    /// Sprite paths of last-resort fallback sprites (large skill-effect
    /// sprites; only used when none of the preferred sprites exist).
    pub fn fallback_assets(&self) -> &[String] {
        &self.fallback_assets
    }

    /// Flight time from caster to target in seconds.
    pub fn flight_seconds(&self) -> f32 {
        self.flight_ms as f32 / 1000.0
    }
}

struct ItemRange {
    start: u32,
    end: u32,
    kind: usize,
}

struct ItemView {
    view: u32,
    kind: usize,
}

/// Lookup result for a weapon value.
enum Resolution {
    /// The value is a server `W_*` weapon type.
    ServerType(usize),
    /// The value is an item view id.
    ItemView(usize),
    /// The value is not in the table.
    Unknown,
}

/// The parsed and validated weapon data table.
struct WeaponRegistry {
    paths: PathTemplates,
    sex_suffix: SexSuffixes,
    fallbacks: FallbackChains,
    /// Sorted by `value`.
    server_types: Vec<(u32, usize)>,
    /// Highest known `W_*` value; smaller values are server weapon types.
    max_server_value: u32,
    kinds: Vec<WeaponProfile>,
    /// Sorted by `start`, disjoint.
    ranges: Vec<ItemRange>,
    /// Sorted by `view`.
    views: Vec<ItemView>,
    projectiles: Vec<ProjectileProfile>,
    projectile_by_kind: HashMap<ProjectileKind, usize>,
    unknown: WeaponProfile,
}

static COMPILED: OnceLock<WeaponRegistry> = OnceLock::new();
static ARCHIVE: OnceLock<WeaponRegistry> = OnceLock::new();

fn compiled() -> &'static WeaponRegistry {
    COMPILED.get_or_init(|| match parse(FALLBACK) {
        Ok(registry) => registry,
        Err(error) => {
            crate::logging::log_warn!("weapons: compiled fallback is invalid ({error})");
            WeaponRegistry::empty()
        }
    })
}

fn registry() -> &'static WeaponRegistry {
    ARCHIVE.get().unwrap_or_else(compiled)
}

impl WeaponRegistry {
    /// Minimal registry used when even the compiled data file is unreadable.
    ///
    /// It knows no weapon, which makes candidates empty and the weapon layer
    /// absent, but it can never panic or draw wrong sprites.
    fn empty() -> Self {
        let unknown = WeaponProfile {
            kind: WeaponKind::Unknown,
            subtype: String::new(),
            variants: Vec::new(),
            attack_range: 1,
            ammo: None,
            projectile: None,
        };

        Self {
            paths: PathTemplates {
                per_job: String::new(),
                classic_weapon: String::new(),
            },
            sex_suffix: SexSuffixes {
                male: String::new(),
                female: String::new(),
            },
            fallbacks: FallbackChains {
                server_type: Vec::new(),
                item_view: Vec::new(),
                unknown: Vec::new(),
            },
            server_types: Vec::new(),
            max_server_value: 0,
            kinds: Vec::new(),
            ranges: Vec::new(),
            views: Vec::new(),
            projectiles: Vec::new(),
            projectile_by_kind: HashMap::new(),
            unknown,
        }
    }

    fn profile_of(&self, kind_index: usize) -> &WeaponProfile {
        self.kinds.get(kind_index).unwrap_or(&self.unknown)
    }

    fn resolve(&self, weapon: u32) -> Resolution {
        if let Ok(index) = self.server_types.binary_search_by_key(&weapon, |(value, _)| *value) {
            return Resolution::ServerType(self.server_types[index].1);
        }

        // Values in the server weapon type range (including the unused
        // `MAX_WEAPON_TYPE` marker) are never item view ids.
        if weapon <= self.max_server_value {
            return Resolution::Unknown;
        }

        if let Ok(index) = self.views.binary_search_by_key(&weapon, |view| view.view) {
            return Resolution::ItemView(self.views[index].kind);
        }

        let range_index = self.ranges.binary_search_by(|range| match weapon {
            value if value < range.start => std::cmp::Ordering::Greater,
            value if value > range.end => std::cmp::Ordering::Less,
            _ => std::cmp::Ordering::Equal,
        });

        match range_index {
            Ok(index) => Resolution::ItemView(self.ranges[index].kind),
            Err(_) => Resolution::Unknown,
        }
    }

    fn projectile(&self, kind: ProjectileKind) -> Option<&ProjectileProfile> {
        let index = self.projectile_by_kind.get(&kind)?;
        self.projectiles.get(*index)
    }
}

/// Parse and validate the data file.
fn parse(content: &str) -> Result<WeaponRegistry, String> {
    let file: WeaponFile = ron::from_str(content).map_err(|error| format!("schema error: {error}"))?;
    build(file)
}

fn build(file: WeaponFile) -> Result<WeaponRegistry, String> {
    if file.kinds.is_empty() {
        return Err("the data file contains no weapon kinds".to_owned());
    }
    if file.server_types.is_empty() {
        return Err("the data file contains no server weapon types".to_owned());
    }
    if file.projectiles.is_empty() {
        return Err("the data file contains no projectiles".to_owned());
    }

    let mut kinds = Vec::with_capacity(file.kinds.len());
    let mut kind_by_id = HashMap::with_capacity(file.kinds.len());

    for row in file.kinds {
        if kind_by_id.contains_key(&row.kind) {
            return Err(format!("duplicate weapon kind {:?}", row.kind));
        }
        if row.range == 0 {
            return Err(format!("weapon kind {:?} has a zero attack range", row.kind));
        }

        kind_by_id.insert(row.kind, kinds.len());
        kinds.push(WeaponProfile {
            kind: row.kind,
            subtype: row.subtype,
            variants: row.variants,
            attack_range: row.range,
            ammo: row.ammo,
            projectile: row.projectile,
        });
    }

    let mut server_types = Vec::with_capacity(file.server_types.len());
    for row in file.server_types {
        let kind = kind_by_id
            .get(&row.kind)
            .copied()
            .ok_or_else(|| format!("server type {:?} refers to unknown kind {:?}", row.name, row.kind))?;
        server_types.push((row.value, kind));
    }
    server_types.sort_by_key(|(value, _)| *value);
    for pair in server_types.windows(2) {
        if pair[0].0 == pair[1].0 {
            return Err(format!("duplicate server weapon type value {}", pair[0].0));
        }
    }
    let max_server_value = server_types.last().map(|(value, _)| *value).unwrap_or(0);

    let mut ranges = Vec::with_capacity(file.item_ranges.len());
    for row in file.item_ranges {
        if row.start > row.end || row.start == 0 {
            return Err(format!("invalid item id range {}..={}", row.start, row.end));
        }
        let kind = kind_by_id
            .get(&row.kind)
            .copied()
            .ok_or_else(|| format!("item range {}..={} refers to unknown kind {:?}", row.start, row.end, row.kind))?;
        ranges.push(ItemRange {
            start: row.start,
            end: row.end,
            kind,
        });
    }
    ranges.sort_by_key(|range| range.start);
    for pair in ranges.windows(2) {
        if pair[1].start <= pair[0].end {
            return Err(format!(
                "overlapping item id ranges {}..={} and {}..={}",
                pair[0].start, pair[0].end, pair[1].start, pair[1].end
            ));
        }
    }

    let mut views = Vec::with_capacity(file.item_views.len());
    for row in file.item_views {
        if row.view == 0 {
            return Err("item view override with view id 0".to_owned());
        }
        let kind = kind_by_id
            .get(&row.kind)
            .copied()
            .ok_or_else(|| format!("item view {} refers to unknown kind {:?}", row.view, row.kind))?;
        views.push(ItemView { view: row.view, kind });
    }
    views.sort_by_key(|view| view.view);
    for pair in views.windows(2) {
        if pair[0].view == pair[1].view {
            return Err(format!("duplicate item view override {}", pair[0].view));
        }
    }

    let mut projectiles = Vec::with_capacity(file.projectiles.len());
    let mut projectile_by_kind = HashMap::with_capacity(file.projectiles.len());
    for row in file.projectiles {
        if row.assets.is_empty() {
            return Err(format!("projectile {:?} has no assets", row.kind));
        }
        if row.flight_ms == 0 {
            return Err(format!("projectile {:?} has a zero flight time", row.kind));
        }
        if projectile_by_kind.insert(row.kind, projectiles.len()).is_some() {
            return Err(format!("duplicate projectile {:?}", row.kind));
        }
        projectiles.push(ProjectileProfile {
            kind: row.kind,
            assets: row.assets,
            fallback_assets: row.fallback_assets,
            flight_ms: row.flight_ms,
        });
    }

    // A kind that declares a visual projectile must have a projectile profile.
    for profile in &kinds {
        if let Some(projectile) = profile.projectile
            && !projectile_by_kind.contains_key(&projectile)
        {
            return Err(format!(
                "weapon kind {:?} uses undefined projectile {:?}",
                profile.kind, projectile
            ));
        }
    }

    let unknown = WeaponProfile {
        kind: WeaponKind::Unknown,
        subtype: String::new(),
        variants: Vec::new(),
        attack_range: 1,
        ammo: None,
        projectile: None,
    };

    Ok(WeaponRegistry {
        paths: file.paths,
        sex_suffix: file.sex_suffix,
        fallbacks: file.fallbacks,
        server_types,
        max_server_value,
        kinds,
        ranges,
        views,
        projectiles,
        projectile_by_kind,
        unknown,
    })
}

/// Loads the weapon table from the client archive (or keeps the compiled
/// fallback).
///
/// Returns the number of loaded weapon kinds. A malformed data file is reported
/// and the compiled fallback is used instead, so a bad override can never leave
/// the client without a usable weapon table.
pub(crate) fn load(game_file_loader: &GameFileLoader) -> usize {
    let from_archive = game_file_loader
        .get(DATA_PATH)
        .ok()
        .map(|bytes| String::from_utf8_lossy(&bytes).into_owned());

    let Some(content) = from_archive.as_deref() else {
        let count = compiled().kinds.len();
        crate::logging::log_debug!("weapons: loaded {count} kinds from the compiled fallback");
        return count;
    };

    match parse(content) {
        Ok(registry) => {
            let count = registry.kinds.len();
            let _ = ARCHIVE.set(registry);
            crate::logging::log_debug!("weapons: loaded {count} kinds from {DATA_PATH}");
            count
        }
        Err(error) => {
            crate::logging::log_warn!("weapons: invalid {DATA_PATH} ({error}), using the compiled fallback");
            compiled().kinds.len()
        }
    }
}

/// Returns the weapon profile of a weapon value.
///
/// The value follows the server: a rAthena `W_*` weapon type (the value in the
/// entity-appear `weapon` field / `LOOK_WEAPON`) or, for population shells and
/// custom servers, an item view id. Values that are not in the table return the
/// generic [`WeaponKind::Unknown`] profile.
pub fn profile(weapon: u32) -> &'static WeaponProfile {
    let registry = registry();
    match registry.resolve(weapon) {
        Resolution::ServerType(index) | Resolution::ItemView(index) => registry.profile_of(index),
        Resolution::Unknown => &registry.unknown,
    }
}

/// Builds the ordered sprite candidate paths for a player entity's weapon.
///
/// The candidates come from the templates and fallback order in the data file:
///
/// 1. per-job weapon variant next to the body sprite (numeric weapon value
///    first for item view ids, then the classic sprite family names),
/// 2. the classic job-independent weapon layer (`data\sprite\인간족\무기\...`).
///
/// Missing candidates are skipped by the animation loader, so the returned list
/// is an attempt order, not a guarantee. Unarmed entities (`weapon == 0`) and
/// weapon values without any sprite family (e.g. the unused two-handed mace
/// slot) produce no candidates.
pub(crate) fn part_candidates(job_id: JobId, sex: Sex, weapon: u32) -> Vec<EntityPartFile> {
    if weapon == 0 {
        return Vec::new();
    }

    let registry = registry();
    let resolution = registry.resolve(weapon);

    let (steps, variants): (&[CandidateStep], &[String]) = match &resolution {
        Resolution::ServerType(index) => (&registry.fallbacks.server_type, registry.profile_of(*index).sprite_variants()),
        Resolution::ItemView(index) => (&registry.fallbacks.item_view, registry.profile_of(*index).sprite_variants()),
        Resolution::Unknown => {
            // The unused `MAX_WEAPON_TYPE` style value has no sprite family.
            if weapon <= registry.max_server_value {
                return Vec::new();
            }
            (&registry.fallbacks.unknown, &[] as &[String])
        }
    };

    let (weapon_folder, weapon_prefix) = jobs::weapon_sprite(job_id);
    let sex_suffix = match sex {
        Sex::Female => registry.sex_suffix.female.as_str(),
        _ => registry.sex_suffix.male.as_str(),
    };
    let numeric = weapon.to_string();

    let mut candidates = Vec::new();
    let mut seen = HashSet::new();

    let mut push = |template: &str, variant: &str| {
        let path = expand_template(template, weapon_folder, weapon_prefix, sex_suffix, variant);
        if seen.insert(path.clone()) {
            candidates.push(EntityPartFile::new(path));
        }
    };

    for step in steps {
        match step {
            CandidateStep::PerJobNumeric => push(&registry.paths.per_job, &numeric),
            CandidateStep::PerJobVariant => {
                for variant in variants {
                    push(&registry.paths.per_job, variant);
                }
            }
            CandidateStep::ClassicNumeric => push(&registry.paths.classic_weapon, &numeric),
            CandidateStep::ClassicVariant => {
                for variant in variants {
                    push(&registry.paths.classic_weapon, variant);
                }
            }
        }
    }

    candidates
}

/// Expands a candidate path template with the per-entity values.
fn expand_template(template: &str, folder: &str, prefix: &str, sex_suffix: &str, variant: &str) -> String {
    template
        .replace("{folder}", folder)
        .replace("{prefix}", prefix)
        .replace("{sex}", sex_suffix)
        .replace("{variant}", variant)
}

/// Returns the projectile profile (sprite candidates + flight time) of a
/// projectile kind.
pub(crate) fn projectile(kind: ProjectileKind) -> Option<&'static ProjectileProfile> {
    registry().projectile(kind)
}

/// Returns the flying projectile of a weapon, if it has one.
///
/// Only weapons with a verified projectile sprite family (currently bows,
/// instruments and whips — the rAthena arrow-ammo weapons) return `Some`.
pub(crate) fn projectile_for_weapon(weapon: u32) -> Option<&'static ProjectileProfile> {
    let registry = registry();
    let kind_index = match registry.resolve(weapon) {
        Resolution::ServerType(index) | Resolution::ItemView(index) => index,
        Resolution::Unknown => return None,
    };
    let projectile = registry.profile_of(kind_index).projectile()?;
    registry.projectile(projectile)
}

/// Whether the weapon animation has at least one drawable frame.
///
/// Some trimmed data sets ship weapon ACTs whose sprite clips are all `-1`
/// placeholders (`sprite_number == usize::MAX`). Such an animation must not be
/// kept: it would never draw anything and would only waste the weapon layer.
pub(crate) fn animation_is_drawable(animation_data: &AnimationData) -> bool {
    animation_data
        .animations
        .iter()
        .flat_map(|animation| animation.frames.iter())
        .any(|frame| frame.frame_parts.iter().any(|part| part.sprite_number != usize::MAX))
}

/// Attack action (`ST_ATTACK` = 80..87 or `ST_ATTACK2` = 88..95) of the
/// equipped weapon ACT.
///
/// The player attack animations are split into two blocks. A weapon ACT only
/// animates one of them (e.g. knight swords use 80..87 while knight spears and
/// hunter bows use 88..95; some animate both), so the entity plays the block
/// that actually contains drawable frames. Defaults to `ST_ATTACK` when the
/// weapon is not loaded yet or animates both blocks.
pub(crate) fn attack_action(animation_data: &AnimationData) -> super::AnimationActionType {
    use super::AnimationActionType;

    const ATTACK_BLOCK: usize = 10;
    const ATTACK2_BLOCK: usize = 11;

    if !animation_data.action_is_drawable(ATTACK_BLOCK) && animation_data.action_is_drawable(ATTACK2_BLOCK) {
        AnimationActionType::Attack3
    } else {
        AnimationActionType::Attack2
    }
}

