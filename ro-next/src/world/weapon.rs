//! Data-driven weapon handling.
//!
//! Weapon appearance and attack behaviour used to be scattered over the entity
//! layer, the client loop and the async loader: a hard-coded
//! `weapon type -> Korean sprite suffix` match, a hard-coded bow item-view-id
//! range, hard-coded arrow sprite candidates and five copies of the weapon
//! animation load. This module is now the **single** source of truth:
//!
//! * [`profile`] maps a weapon value to a [`WeaponProfile`] (kind, sprite
//!   family variants, attack range, ammo/projectile kind),
//! * [`part_candidates`] builds the ordered sprite candidate paths for an
//!   entity from the path templates in the data file (no match arms in Rust),
//! * [`projectile_for_weapon`] returns the flying projectile (sprites, flight
//!   time) of a ranged weapon,
//! * [`animation_is_drawable`] is the shared gate for the weapon animation
//!   layer (some trimmed data sets ship weapon ACTs whose clips are all
//!   placeholders).
//!
//! The table lives in `archive/data/client/weapons.ron` (generated by
//! `tools/gen_weapons.py` from rAthena's pre-renewal item database and the
//! CondaRO client archives). It is embedded with `include_str!` as the compiled
//! fallback and can be overridden at runtime through the client archive
//! (`data\client\weapons.ron`), so a server with custom weapon items/ids can
//! adjust the table without rebuilding the client.
//!
//! ## What the data file contains
//!
//! * `server_types`: rAthena `enum weapon_type` value (the value the server
//!   sends in the entity `weapon` field / `LOOK_WEAPON`, e.g. `W_BOW = 11`) to
//!   [`WeaponKind`]. The dual-wield display values (`W_DOUBLE_*`) map to their
//!   own kinds so dual wielders get the combined weapon sprite.
//! * `item_ranges` / `item_views`: pre-renewal weapon item ids (and explicit
//!   `View:` overrides) to kind. Used when the weapon value carries an item
//!   view id instead of a server weapon type (population shells, custom
//!   servers).
//! * `kinds`: ordered classic sprite family variants per kind (e.g. `양손검`
//!   then `검`), the authoritative rAthena attack range and the ammo/projectile
//!   kind.
//! * `paths`/`fallbacks`: how candidate paths are built and in which order.
//! * `projectiles`: flying projectile sprite candidates and flight time.
//!
//! ## Attack action selection
//!
//! The RO ACT layout puts the basic attack motion at the same action index for
//! every job/weapon (the weapon ACT mirrors the body ACT indices), so the only
//! weapon-dependent part of an auto attack is the projectile. The caster
//! animation stays in [`crate::world::AnimationState`]; the projectile decision
//! is centralised here.
//!
//! ## Actor action blocks used by the weapon layer
//!
//! The CondaRO client archives contain **no** classic job-independent weapon
//! layer (`data\sprite\인간족\무기\*`); the per-job weapon variants
//! (`data\sprite\인간족\<job>\<job>_<sex>_<variant>`) carry the real weapon
//! graphics. Their ACT data does **not** animate the classic neutral idle block
//! (`0..7`); the armed stand pose lives in the ready-fight block (`32..39`) and
//! the swing in the `ST_ATTACK` (`80..87`) or `ST_ATTACK2` (`88..95`) block,
//! depending on the job/weapon pair (some also animate the skill block
//! `96..103`).
//!
//! The official renderer does not draw the weapon layer during the neutral
//! idle: `IsReadyOrAttackAction` (`Player.cpp:1835`) only accepts the
//! ready-fight (`32..39`) and attack (`80..95`) actions, and
//! `SpriteLayerRenderer::ShouldDrawLayer` (`SpriteLayerDrawing.cpp:716-731`)
//! hides the weapon (layer 5), weapon-effect (layer 6) and shield (layer 7)
//! layers for every other action. The entity layer therefore idles in the
//! neutral `ST_STAND` block (`0..7`) with the weapon hidden, shows it in the
//! ready-fight stance and picks the attack block with [`attack_action`]. No
//! item/skill icon is drawn in the world as a substitute; the
//! equipment/inventory UI already shows the item icon.

