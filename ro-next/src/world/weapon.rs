    /// A synthetic animation with drawable frames: the "visible fake fixture"
    /// used to test the weapon layer gate without the (placeholder-only) game
    /// assets.
    fn fake_animation(sprite_number: usize) -> AnimationData {
        // `Matrix4::identity` is a trait method; the fields only exist in debug
        // builds, so the import must be gated as well.
        #[cfg(feature = "debug")]
        use cgmath::SquareMatrix;

        let part = AnimationFramePart {
            sprite_number,
            ..Default::default()
        };
        let frame = AnimationFrame {
            event: None,
            offset: cgmath::Vector2::new(0, 0),
            top_left: cgmath::Vector2::new(0, 0),
            size: cgmath::Vector2::new(1, 1),
            frame_parts: vec![part],
            #[cfg(feature = "debug")]
            horizontal_matrix: cgmath::Matrix4::identity(),
            #[cfg(feature = "debug")]
            vertical_matrix: cgmath::Matrix4::identity(),
        };
        AnimationData {
            animation_pair: Vec::new(),
            animations: vec![Animation { frames: vec![frame] }],
            delays: vec![4.0],
            entity_type: EntityType::Player,
        }
    }

    /// A synthetic player weapon animation with `drawable_actions` as full ACT
    /// action indices; every other action is a hidden placeholder.
    fn fake_block_animation(drawable_actions: &[usize]) -> AnimationData {
        #[cfg(feature = "debug")]
        use cgmath::SquareMatrix;

        let hidden = AnimationFrame {
            event: None,
            offset: cgmath::Vector2::new(0, 0),
            top_left: cgmath::Vector2::new(0, 0),
            size: cgmath::Vector2::new(1, 1),
            frame_parts: vec![AnimationFramePart::default()],
            #[cfg(feature = "debug")]
            horizontal_matrix: cgmath::Matrix4::identity(),
            #[cfg(feature = "debug")]
            vertical_matrix: cgmath::Matrix4::identity(),
        };
        let visible = AnimationFrame {
            frame_parts: vec![AnimationFramePart {
                sprite_number: 0,
                ..Default::default()
            }],
            ..hidden.clone()
        };

        AnimationData {
            animation_pair: Vec::new(),
            animations: (0..104)
                .map(|action| Animation {
                    frames: vec![if drawable_actions.contains(&action) {
                        visible.clone()
                    } else {
                        hidden.clone()
                    }],
                })
                .collect(),
            delays: vec![4.0; 104],
            entity_type: EntityType::Player,
        }
    }

    #[test]
    fn placeholder_only_weapon_animations_are_rejected() {
        // A weapon ACT whose clips are all hidden (`sprite_number ==
        // usize::MAX`) must not be kept as a layer.
        assert!(!animation_is_drawable(&fake_animation(usize::MAX)));

        // A data set with real weapon pixels passes the gate.
        assert!(animation_is_drawable(&fake_animation(0)));

        // Degenerate animation data must not panic.
        let empty = AnimationData {
            animation_pair: Vec::new(),
            animations: Vec::new(),
            delays: Vec::new(),
            entity_type: EntityType::Player,
        };
        assert!(!animation_is_drawable(&empty));
    }

    #[test]
    fn attack_action_follows_the_drawable_weapon_attack_block() {
        // Knight sword / archer bow files animate ST_ATTACK (action block 80).
        let attack = fake_block_animation(&[32, 80]);
        assert_eq!(attack_action(&attack), AnimationActionType::Attack2);

        // Knight spear / hunter bow files animate ST_ATTACK2 (action block 88).
        let attack2 = fake_block_animation(&[32, 88]);
        assert_eq!(attack_action(&attack2), AnimationActionType::Attack3);

        // A weapon that animates both blocks keeps the primary (ST_ATTACK).
        let both = fake_block_animation(&[32, 80, 88]);
        assert_eq!(attack_action(&both), AnimationActionType::Attack2);

        // A weapon layer that is still loading falls back to ST_ATTACK.
        assert_eq!(attack_action(&fake_animation(0)), AnimationActionType::Attack2);
    }

    #[test]
    fn player_with_weapon_idles_neutral_and_swings_in_the_visible_attack_block() {
        // Knight sword / archer bow data: the weapon draws block 32..39 (armed
        // stance) and block 80..87 (swing), every other block is a placeholder.
        let weapon = fake_block_animation(&[32, 80]);

        // At peace the player uses the official neutral `ST_STAND` block 0.
        // `IsReadyOrAttackAction` rejects it, so the weapon layer stays hidden
        // even though the weapon ACT is loaded.
        let mut state = AnimationState::new(EntityType::Player, ClientTick(0));
        assert_eq!(state.action_index(), 0);
        assert_eq!(state.action_index() * 8, 0);
        assert!(!state.shows_weapon_layer());

        // The attack plays the block the weapon ACT actually animates and the
        // official rule keeps the weapon visible while it does.
        let action = attack_action(&weapon);
        assert_eq!(action, AnimationActionType::Attack2);
        state.attack(EntityType::Player, 100, action, ClientTick(10));
        assert_eq!(state.action_index(), 10);
        assert_eq!(state.action_index() * 8, 80);
        assert!(state.shows_weapon_layer());
    }
