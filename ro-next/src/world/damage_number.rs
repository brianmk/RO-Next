fn parse(content: &str) -> Result<DamageNumbers, String> {
    let file: DamageNumbersFile = ron::from_str(content).map_err(|error| error.to_string())?;

    if file.version < 2 {
        return Err(format!("unsupported version {}", file.version));
    }
    if file.timeline.frame_ms == 0 || file.timeline.step_ms == 0 || file.timeline.multi_hit_interval_ms == 0 {
        return Err("timeline values must be positive".to_owned());
    }
    if file.atlas.cell_scale_x <= 0.0 || file.atlas.cell_scale_y <= 0.0 {
        return Err("atlas cell scale must be positive".to_owned());
    }
    if file.layout.unit <= 0 || file.layout.extended_step <= 0 {
        return Err("layout unit/extended step must be positive".to_owned());
    }
    if file.extended.million_divisor == 0 || file.extended.hundred_million_divisor == 0 {
        return Err("extended divisors must be positive".to_owned());
    }
    if file.miss.cell_scale_x <= 0.0 || file.miss.cell_scale_y <= 0.0 {
        return Err("miss cell scale must be positive".to_owned());
    }

    let backing = &file.critical_backing;
    if style_from_name(&backing.number_style) != Some(DamageNumberStyle::Critical) {
        return Err(format!(
            "critical backing must belong to the critical style, not {:?}",
            backing.number_style
        ));
    }
    if backing.sprite.is_empty() || backing.action.is_empty() {
        return Err("critical backing must name a sprite and an action".to_owned());
    }
    if backing.image < 0 || backing.width == 0 || backing.height == 0 {
        return Err("critical backing has an invalid image".to_owned());
    }
    if backing.motion_count == 0 || backing.motion_offsets_x.len() != backing.motion_count {
        return Err("critical backing motion count does not match its offsets".to_owned());
    }
    if backing.motion_rate <= 0.0 {
        return Err("critical backing motion rate must be positive".to_owned());
    }
    if backing.cell_scale_x <= 0.0 || backing.cell_scale_y <= 0.0 || backing.base_scale <= 0.0 {
        return Err("critical backing cell/scale must be positive".to_owned());
    }
    if backing.min_scale > backing.base_scale {
        return Err("critical backing min_scale is above base_scale".to_owned());
    }
    if backing.scale_step < 0.0 || backing.alpha_step < 0.0 || backing.spawn_offset < 0.0 || backing.lifetime_frames <= 0.0 {
        return Err("critical backing has an invalid timeline constant".to_owned());
    }
    if backing.depth_layer >= backing.digit_depth_layer {
        return Err("critical backing must be drawn behind the digits".to_owned());
    }

    let mut seen_digits = [false; MAX_DIGITS];
    for row in &file.digits {
        let digit = usize::from(row.digit);
        if digit >= MAX_DIGITS {
            return Err(format!("digit {} out of range", row.digit));
        }
        if seen_digits[digit] {
            return Err(format!("duplicate digit row {}", row.digit));
        }
        seen_digits[digit] = true;
        if row.width == 0 || row.height == 0 {
            return Err(format!("digit {} has an empty image size", row.digit));
        }
    }
    for digit in 0..10 {
        if !seen_digits[digit] {
            return Err(format!("missing digit row {digit}"));
        }
    }

    let mut seen_styles = [false; 6];
    for row in &file.styles {
        let Some(style) = style_from_name(&row.name) else {
            return Err(format!("unknown style {:?}", row.name));
        };
        let index = DamageNumberStyle::ALL
            .iter()
            .position(|candidate| *candidate == style)
            .expect("style_from_name only returns declared styles");
        if seen_styles[index] {
            return Err(format!("style {style:?} must be declared exactly once"));
        }
        seen_styles[index] = true;

        if row.lifetime_frames <= 0.0 {
            return Err(format!("style {style:?} has an invalid lifetime"));
        }
        if row.spawn_offset < 0.0 || row.vertical_speed < 0.0 || row.scale_step < 0.0 || row.scale_growth < 0.0 {
            return Err(format!("style {style:?} has a negative constant"));
        }
        if row.min_scale > row.max_scale || row.base_scale < row.min_scale {
            return Err(format!("style {style:?} has inconsistent scale bounds"));
        }
        if color_from_name(&row.color).is_none() {
            return Err(format!("style {style:?} references the unknown colour {:?}", row.color));
        }
    }
    if seen_styles.iter().any(|seen| !seen) {
        return Err("not every damage-number style is declared".to_owned());
    }

    let mut seen_colors = [false; 14];
    for row in &file.colors {
        let Some(color) = color_from_name(&row.name) else {
            return Err(format!("unknown colour {:?}", row.name));
        };
        let index = DamageColor::ALL
            .iter()
            .position(|candidate| *candidate == color)
            .expect("color_from_name only returns declared colours");
        if seen_colors[index] {
            return Err(format!("colour {color:?} must be declared exactly once"));
        }
        seen_colors[index] = true;
    }
    if seen_colors.iter().any(|seen| !seen) {
        return Err("not every damage-number colour is declared".to_owned());
    }

    let colors = file
        .colors
        .iter()
        .map(|row| (color_from_name(&row.name).expect("validated above"), argb_color(row.argb)))
        .collect();

    let styles = file
        .styles
        .into_iter()
        .map(|row| DamageNumberStyleData {
            name: style_from_name(&row.name).expect("validated above"),
            type_id: row.type_id,
            lifetime_frames: row.lifetime_frames,
            spawn_offset: row.spawn_offset,
            vertical_curve: row.vertical_curve,
            vertical_speed: row.vertical_speed,
            horizontal_drift: row.horizontal_drift,
            base_scale: row.base_scale,
            min_scale: row.min_scale,
            max_scale: row.max_scale,
            scale_step: row.scale_step,
            scale_growth: row.scale_growth,
            alpha_start: row.alpha_start,
            alpha_step: row.alpha_step,
            fade_start: row.fade_start,
            fade_step: row.fade_step,
            color: color_from_name(&row.color).expect("validated above"),
        })
        .collect();

    Ok(DamageNumbers {
        timeline: file.timeline,
        digits: file.digits,
        atlas: file.atlas,
        layout: file.layout,
        extended: file.extended,
        miss: file.miss,
        critical_backing: file.critical_backing,
        styles,
        colors,
    })
}

fn style_from_name(name: &str) -> Option<DamageNumberStyle> {
    match name {
        "normal" => Some(DamageNumberStyle::Normal),
        "critical" => Some(DamageNumberStyle::Critical),
        "half" => Some(DamageNumberStyle::Half),
        "total" => Some(DamageNumberStyle::Total),
        "simple" => Some(DamageNumberStyle::Simple),
        "miss" => Some(DamageNumberStyle::Miss),
        _ => None,
    }
}

fn color_from_name(name: &str) -> Option<DamageColor> {
    match name {
        "white" => Some(DamageColor::White),
        "player_red" => Some(DamageColor::PlayerRed),
        "critical_yellow" => Some(DamageColor::CriticalYellow),
        "blue_damage" => Some(DamageColor::BlueDamage),
        "heal_green" => Some(DamageColor::HealGreen),
        "sp_blue" => Some(DamageColor::SpBlue),
        "status_green" => Some(DamageColor::StatusGreen),
        "status_blue" => Some(DamageColor::StatusBlue),
        "status_red" => Some(DamageColor::StatusRed),
        "status_purple" => Some(DamageColor::StatusPurple),
        "status_black" => Some(DamageColor::StatusBlack),
        "status_white" => Some(DamageColor::StatusWhite),
        "status_yellow" => Some(DamageColor::StatusYellow),
        "status_pink" => Some(DamageColor::StatusPink),
        _ => None,
    }
}

fn argb_color(argb: u32) -> Color {
    let alpha = ((argb >> 24) & 0xFF) as u8;
    let red = ((argb >> 16) & 0xFF) as u8;
    let green = ((argb >> 8) & 0xFF) as u8;
    let blue = (argb & 0xFF) as u8;
    Color::rgba_u8(red, green, blue, alpha)
}

