/// The `MET_CRITICAL_EFFECT` sprite drawn behind a critical number.
///
/// The official client spawns one extra `CMsgEffect` of type 15 from
/// `AM_MAKE_CRITICAL_EFFECT` (`GameObject.cpp:1632-1636`); that message is
/// sent only by the `id == 148` `DMG_MULTI_HIT_CRITICAL` branch
/// (`GameObject.cpp:1917-1924`, `CombatTypes.h:16`). `MAKETYPE_CRITICAL_EFFECT`
/// (`WorldObjects.cpp:1176-1182`) loads it from the damage skin's message
/// sprite (`g_session.GetDamageSpriteName()`, i.e. `이팩트\msg` for the default
/// skin, `ClientTiming.cpp:784-806`) and plays ACT action 2
/// (`숫자.spr`/`msg.spr` are two different files; the numbers use
/// `이팩트\숫자`).
///
/// `AM_SETPOS` (`MsgEffect.cpp:1825-1835`) gives it the same origin as the
/// digits (`position.y -= 12`) but scale 3.0 and `depthLayer` -5 (digits:
/// -2, `MsgEffect.cpp:1772`), and the `OnProcess` cue
/// (`MsgEffect.cpp:377-395`) shrinks it to 1.0, steps its 15 motions at
/// `g_depthAverageHalf` (0.5) per elapsed frame and fades its alpha from 255
/// by 3.45 per frame over 70 frames.
#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct CriticalBackingRow {
    /// Must be `critical`: only critical numbers request the backing.
    #[allow(dead_code)] // validated in `parse`; kept for the data/documentation tests
    pub(crate) number_style: String,
    pub(crate) sprite: String,
    pub(crate) action: String,
    pub(crate) action_index: usize,
    pub(crate) image: i32,
    pub(crate) width: u32,
    pub(crate) height: u32,
    pub(crate) cell_y: i32,
    pub(crate) cell_scale_x: f32,
    pub(crate) cell_scale_y: f32,
    pub(crate) motion_count: usize,
    /// Per-motion cell x of `msg.act` action 2 (the burst shakes horizontally).
    pub(crate) motion_offsets_x: Vec<i32>,
    /// `AM_SETPOS` starts at motion 1 (`MsgEffect.cpp:1829`); recorded for
    /// provenance, the first computed motion is 0 either way.
    #[allow(dead_code)]
    pub(crate) motion_start: i32,
    /// `g_depthAverageHalf` (`MapSkyMgr.cpp:27`): motions per elapsed frame.
    pub(crate) motion_rate: f32,
    pub(crate) base_scale: f32,
    pub(crate) min_scale: f32,
    /// `0.24 * 0.6` per frame (`MsgEffect.cpp:382`).
    pub(crate) scale_step: f32,
    /// `AM_SETPOS` `position.y -= 12`, the same offset as the digits.
    pub(crate) spawn_offset: f32,
    /// `-5` (`MsgEffect.cpp:1832`); the digits use -2 (`:1772`).
    pub(crate) depth_layer: i32,
    pub(crate) digit_depth_layer: i32,
    /// `render.color = 0xFFAAAAAA` (`MsgEffect.cpp:1834`).
    argb: u32,
    pub(crate) alpha_start: f32,
    pub(crate) alpha_step: f32,
    pub(crate) lifetime_frames: f32,
    /// `DMG_MULTI_HIT_CRITICAL` trigger provenance
    /// (`GameObject.cpp:1917-1924`).
    #[allow(dead_code)]
    pub(crate) trigger_message: i32,
    #[allow(dead_code)]
    pub(crate) trigger_damage_type: i32,
}

impl CriticalBackingRow {
    /// `OnProcess` scale step (`MsgEffect.cpp:381-385`): stateful, so the
    /// previous value decides between the shrink and the 1.0 floor.
    pub(crate) fn next_scale(&self, current: f32, elapsed: f32) -> f32 {
        if current > self.min_scale {
            self.base_scale - elapsed * self.scale_step
        } else if current < self.min_scale {
            self.min_scale
        } else {
            current
        }
    }

    /// `curMotion = int(elapsed * g_depthAverageHalf) % frames`
    /// (`MsgEffect.cpp:387-390`).
    pub(crate) fn motion_at(&self, elapsed: f32) -> usize {
        if self.motion_count == 0 {
            return 0;
        }
        let motion = (elapsed * self.motion_rate) as i32;
        usize::try_from(motion.max(0)).unwrap_or(0) % self.motion_count
    }

    /// Cell x of the current motion.
    pub(crate) fn cell_x_at(&self, elapsed: f32) -> i32 {
        self.motion_offsets_x.get(self.motion_at(elapsed)).copied().unwrap_or(0)
    }

    /// `SetColor(255 - elapsed * 3.45, ...)` (`MsgEffect.cpp:391`), with the
    /// official float-to-int truncation.
    pub(crate) fn alpha_at(&self, elapsed: f32) -> u8 {
        (self.alpha_start - elapsed * self.alpha_step) as i32 as u8
    }

    /// The `0xFFAAAAAA` tint of `AM_SETPOS`, as RGB.
    pub(crate) fn tint(&self) -> Color {
        argb_color(self.argb)
    }
}

