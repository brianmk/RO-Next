/// One official damage/heal/miss number.
pub struct DamageNumber {
    entity_id: Option<EntityId>,
    /// Spawn anchor (already `spawn_offset` above the target) used when the
    /// owner is not in the entity list (out of sight, dead, benchmark).
    position: Point3<f32>,
    direction: Direction,
    style: DamageNumberStyle,
    color: Color,
    digits: Vec<u8>,
    value: u64,
    extended_layout: bool,
    /// Official `m_baseY` converted to the port's y-up world: the number's
    /// vertical origin (`AM_SETPOS2` `position.y -= offset + 12`, `:1731`).
    base_y: f32,
    /// Official `m_drift.y` (y-down). The official `MsgEffectDriftHeight`
    /// writes `height / (height * 3 * 0.25)` into it after every frame
    /// (`MsgEffect.cpp:176-187`), which is a constant `4/3`; kept as a field
    /// so the quirk can be tested.
    drift_y: f32,
    /// Vertical offset from `base_y` in the port's y-up world.
    vertical_offset: f32,
    /// Whether this number draws the [`DamageLayer::CriticalBacking`] sprite.
    /// Only the critical style requests it (see [`CriticalBackingRow`]).
    critical_backing: bool,
    /// Stateful `MET_CRITICAL_EFFECT` scale: the official code compares the
    /// *previous* value to the 1.0 floor (`MsgEffect.cpp:381-385`), so it has
    /// to be stepped rather than recomputed from `elapsed`.
    backing_scale: f32,
    scale: f32,
    alpha: u8,
    elapsed_ms: u64,
    step_accumulator_ms: f32,
    delay_remaining_ms: f32,
    finished: bool,
}

impl DamageNumber {
    /// Spawns `value` in `style` with `color`.
    ///
    /// `entity_id` is the owner the number follows (`CMsgEffect::m_owner`);
    /// `None` anchors it at `position`. `delay_ms` staggers the numbers of a
    /// multi-hit packet by `g_multiHitInterval` (200 ms).
    pub fn new(
        entity_id: Option<EntityId>,
        position: Point3<f32>,
        value: u64,
        number_style: DamageNumberStyle,
        number_color: DamageColor,
        direction: Direction,
        delay_ms: u32,
    ) -> Self {
        let style_data = style(number_style);
        let digits = match number_style {
            DamageNumberStyle::Miss => DigitString {
                digits: Vec::new(),
                extended_layout: false,
            },
            _ => decompose_damage(value),
        };

        let base_y = position.y + style_data.spawn_offset;
        // `MET_CRITICAL_EFFECT` is a property of the critical number: the
        // official client only sends `AM_MAKE_CRITICAL_EFFECT` for the
        // `DMG_MULTI_HIT_CRITICAL` message (GameObject.cpp:1917-1924), a
        // distinction the 2019 damage events do not expose to the number, so
        // the port draws the backing on every critical number.
        let critical_backing = number_style == DamageNumberStyle::Critical;
        let backing_scale = match critical_backing {
            true => data().critical_backing.base_scale,
            false => 0.0,
        };

        Self {
            entity_id,
            position: Point3::new(position.x, base_y, position.z),
            direction,
            style: number_style,
            color: color(number_color),
            digits: digits.digits,
            value,
            extended_layout: digits.extended_layout,
            base_y,
            drift_y: 0.0,
            vertical_offset: 0.0,
            critical_backing,
            backing_scale,
            scale: style_data.base_scale,
            alpha: style_data.alpha_start as u8,
            elapsed_ms: 0,
            step_accumulator_ms: 0.0,
            delay_remaining_ms: delay_ms as f32,
            finished: false,
        }
    }

    /// A normal or critical damage number.
    ///
    /// The colour follows the official packet handler: a critical hit is yellow
    /// (`GameObject.cpp:1917-1919`), damage to the local player is red
    /// (`:1931`), everything else is white (`:1924`).
    pub fn damage(
        entity_id: EntityId,
        position: Point3<f32>,
        value: u64,
        is_critical: bool,
        blue_damage: bool,
        target_is_player: bool,
        direction: Direction,
        delay_ms: u32,
    ) -> Self {
        // The blue `blueDamage` override is applied last by the official
        // handler (`GameObject.cpp:1934-1936`), so it also wins over the
        // critical yellow; the timeline still comes from the critical type.
        let style = match is_critical {
            true => DamageNumberStyle::Critical,
            false => DamageNumberStyle::Normal,
        };
        let color = if blue_damage {
            DamageColor::BlueDamage
        } else if is_critical {
            style_color(DamageNumberStyle::Critical)
        } else if target_is_player {
            DamageColor::PlayerRed
        } else {
            style_color(DamageNumberStyle::Normal)
        };

        Self::new(Some(entity_id), position, value, style, color, direction, delay_ms)
    }

    /// A miss (`SpawnDamageMsgEffect`, `WorldObjects.cpp:963-983`).
    ///
    /// `color` is white when the attacker is a monster and red for player
    /// attackers (`GameObject.cpp:1774-1779`).
    pub fn miss(entity_id: EntityId, position: Point3<f32>, color: DamageColor, direction: Direction) -> Self {
        Self::new(Some(entity_id), position, 0, DamageNumberStyle::Miss, color, direction, 0)
    }

    /// A green heal/status number (type 114, `GameModePackets.cpp:1653`).
    pub fn heal(entity_id: EntityId, position: Point3<f32>, value: u64) -> Self {
        Self::new(
            Some(entity_id),
            position,
            value,
            DamageNumberStyle::Simple,
            DamageColor::HealGreen,
            Direction::North,
            0,
        )
    }

    fn style_data(&self) -> &'static DamageNumberStyleData {
        style(self.style)
    }

    /// Whether this number draws the [`DamageLayer::CriticalBacking`] sprite.
    pub fn has_critical_backing(&self) -> bool {
        self.critical_backing
    }

    /// The number's sprite layers in painter order (first = behind).
    pub fn layers(&self) -> &'static [DamageLayer] {
        damage_layers(self.style, self.critical_backing)
    }

    /// Current `MET_CRITICAL_EFFECT` scale (`MsgEffect.cpp:381-385`).
    pub fn critical_backing_scale(&self) -> f32 {
        self.backing_scale
    }

    /// Official elapsed value in 24 ms frames (`GetElapsedFrames`).
    fn elapsed_frames(&self) -> f32 {
        self.elapsed_ms as f32 / timeline().frame_ms as f32
    }

    /// One fixed 16 ms step of `CMsgEffect::OnProcess`.
    fn step(&mut self) {
        let step_ms = timeline().step_ms as u64;
        self.elapsed_ms += step_ms;
        let elapsed = self.elapsed_frames();
        let style = self.style_data();

        // Scale (`MsgEffect.cpp:250-254`, `:289-293`, `:342-346`, `:543-547`).
        if style.scale_growth > 0.0 {
            if self.scale < style.max_scale {
                self.scale = elapsed * style.scale_growth + self.scale;
            } else if self.scale > style.max_scale {
                self.scale = style.max_scale;
            }
        } else if style.scale_step > 0.0 {
            if self.scale > style.min_scale {
                self.scale = style.base_scale - elapsed * style.scale_step;
            } else if self.scale < style.min_scale {
                self.scale = style.min_scale;
            }
        } else {
            self.scale = style.base_scale;
        }

        // `MET_CRITICAL_EFFECT` scale (`MsgEffect.cpp:381-385`). The official
        // branch is stateful: the previous frame's scale decides between the
        // shrink and the 1.0 floor, so it cannot be recomputed from `elapsed`.
        if self.critical_backing {
            let backing = &data().critical_backing;
            self.backing_scale = backing.next_scale(self.backing_scale, elapsed);
        }

        // Alpha: the official code computes the float first and casts to int
        // (`static_cast<int>(250.0f - elapsed * 3.4f)`), so keep the same
        // truncation order.
        let fade = if style.fade_step > 0.0 && elapsed > style.fade_start {
            ((elapsed - style.fade_start) * style.fade_step) as i32
        } else {
            0
        };
        let alpha = (style.alpha_start - elapsed * style.alpha_step - fade as f32) as i32 as u8;
        self.alpha = alpha;

        // Rise. The official y axis points down; the port's points up, so the
        // quadratic height is negated (`MsgEffect.cpp:176-187`, `:324`,
        // `:336`, `:541`).
        match style.vertical_curve {
            VerticalCurve::Quadratic => {
                let official_height = 8.0 - (2.0 - elapsed / 30.0) * elapsed + self.drift_y;
                self.vertical_offset = -official_height;
                // QUIRK: `m_drift.y = height / (height * 3.0f * 0.25f)` is a
                // constant 4/3 for any non-zero height, not an accumulator.
                if official_height != 0.0 {
                    self.drift_y = official_height / (official_height * 3.0 * 0.25);
                }
            }
            VerticalCurve::Linear => {
                self.vertical_offset = elapsed * style.vertical_speed;
            }
        }

        if elapsed > style.lifetime_frames {
            self.finished = true;
        }
    }

    /// Resolves the current world anchor: the owner's x/z (if visible), the
    /// official diagonal drift, and the fixed base height.
    ///
    /// `entities` only contains the live actors. A number whose target died
    /// (the killing blow) therefore falls back to the anchor stored at spawn
    /// (or frozen by [`Particle::owner_removed`]); it is never dropped and
    /// never re-anchored on the attacker.
    fn world_anchor(&self, entities: &[Entity]) -> Point3<f32> {
        let owner_xz = self.entity_id.and_then(|entity_id| {
            entities.iter().find(|entity| entity.get_entity_id() == entity_id).map(|entity| {
                let position = entity.get_position();
                (position.x, position.z)
            })
        });

        self.world_anchor_at(owner_xz)
    }

    /// [`Self::world_anchor`] with the owner's x/z already resolved, so the
    /// follow and the captured-anchor paths can be tested without an entity
    /// list.
    fn world_anchor_at(&self, owner_xz: Option<(f32, f32)>) -> Point3<f32> {
        let mut anchor = self.position;
        if let Some((x, z)) = owner_xz {
            anchor.x = x;
            anchor.z = z;
        }

        let style = self.style_data();
        if style.horizontal_drift {
            let elapsed = self.elapsed_frames();
            let (drift_x, drift_z) = damage_number_drift(self.direction);
            // `dir * (elapsed / 3 + 3)` (`MsgEffect.cpp:189-194`).
            anchor.x += drift_x * (elapsed / 3.0 + 3.0);
            anchor.z += drift_z * (elapsed / 3.0 + 3.0);
        }

        anchor.y = self.base_y + self.vertical_offset;
        anchor
    }

    fn render_color(&self) -> Color {
        Color::rgba(self.color.red, self.color.green, self.color.blue, self.alpha as f32 / 255.0)
    }

    fn render_fallback(&self, renderer: &GameInterfaceRenderer, screen: ScreenPosition, color: Color) {
        let text = match self.style {
            DamageNumberStyle::Miss => "miss".to_owned(),
            _ => self.value.to_string(),
        };
        let scaling = renderer.scaling_factor().max(0.1);
        renderer.render_damage_text(&text, screen, color, FontSize(24.0 / scaling));
    }
}

impl Particle for DamageNumber {
    fn total_owner(&self) -> Option<EntityId> {
        match self.style {
            DamageNumberStyle::Total => self.entity_id,
            _ => None,
        }
    }

    fn culling_position(&self) -> Point3<f32> {
        self.position
    }

    /// The number's owner left the live entity list (it died or despawned) at
    /// `position`.
    ///
    /// The number keeps the owner's last x/z so it keeps rendering where the
    /// actor was last seen for the rest of its lifetime. The official
    /// `FollowOwner` also keeps the spawned base height (`m_baseY`) and only
    /// follows the actor's x/z (`MsgEffect.cpp:1308-1350`), so `base_y` stays
    /// untouched.
    fn owner_removed(&mut self, entity_id: EntityId, position: Point3<f32>) {
        if self.entity_id != Some(entity_id) {
            return;
        }

        self.position.x = position.x;
        self.position.z = position.z;
    }

    fn update(&mut self, delta_time: f32) -> bool {
        if self.finished {
            return false;
        }

        if !delta_time.is_finite() || delta_time <= 0.0 {
            return true;
        }

        let delta_ms = delta_time * 1000.0;

        // Multi-hit stagger: the later numbers of one packet stay hidden until
        // their `g_multiHitInterval` slot arrives.
        if self.delay_remaining_ms > 0.0 {
            self.delay_remaining_ms -= delta_ms;
            if self.delay_remaining_ms > 0.0 {
                return true;
            }
            // Keep the overshoot so the 16 ms clock does not lose time.
            self.step_accumulator_ms = -self.delay_remaining_ms;
            self.delay_remaining_ms = 0.0;
        } else {
            self.step_accumulator_ms += delta_ms;
        }

        let step_ms = timeline().step_ms as f32;
        while self.step_accumulator_ms >= step_ms {
            self.step_accumulator_ms -= step_ms;
            self.step();

            if self.finished {
                return false;
            }
        }

        true
    }

    fn render(&self, renderer: &GameInterfaceRenderer, camera: &dyn Camera, window_size: ScreenSize, entities: &[Entity]) {
        // Multi-hit numbers appear one by one; the later ones stay hidden until
        // their slot arrives.
        if self.finished || self.delay_remaining_ms > 0.0 {
            return;
        }

        let anchor = self.world_anchor(entities);
        let clip_space_position = camera.view_projection_matrix() * anchor.to_homogeneous();
        let screen = camera.clip_to_screen_space(clip_space_position);
        let screen = ScreenPosition {
            left: screen.x * window_size.width,
            top: screen.y * window_size.height,
        };

        let Some(distance_scale) = distance_scale(camera, anchor, window_size) else {
            return;
        };

        let color = self.render_color();
        let Some(font) = damage_font::damage_font() else {
            self.render_fallback(renderer, screen, color);
            return;
        };

        if self.style == DamageNumberStyle::Miss {
            let Some(texture) = font.miss_texture() else {
                self.render_fallback(renderer, screen, color);
                return;
            };

            let table = data();
            let miss = &table.miss;
            let scale = distance_scale * self.scale;
            let adjusted_x = adjusted_cell_position(miss.cell_x, miss.width as f32, miss.cell_scale_x);
            let adjusted_y = adjusted_cell_position(miss.cell_y, miss.height as f32, miss.cell_scale_y);
            let cell_alpha = miss.cell_alpha as f32 / 255.0;
            let color = Color::rgba(color.red, color.green, color.blue, color.alpha * cell_alpha);

            let left = screen.left + adjusted_x * miss.cell_scale_x * scale;
            let top = screen.top + adjusted_y * miss.cell_scale_y * scale;
            let size = ScreenSize {
                width: miss.width as f32 * miss.cell_scale_x * scale,
                height: miss.height as f32 * miss.cell_scale_y * scale,
            };

            renderer.render_sprite(
                texture.clone(),
                ScreenPosition { left, top },
                size,
                ScreenClip::unbound(),
                color,
                false,
            );
            return;
        }

        let table = data();

        // `MET_CRITICAL_EFFECT` (`이팩트\msg` action 2) is drawn first because
        // its depthLayer -5 sits behind the digits' -2 (`MsgEffect.cpp:1832`,
        // `:1772`). It shares the digit anchor (the same `position.y -= 12`
        // spawn offset and drift/rise clock, `MsgEffect.cpp:1827`, `:380`);
        // only its scale, alpha and animation differ.
        for layer in self.layers() {
            match layer {
                DamageLayer::CriticalBacking => {
                    if self.has_critical_backing()
                        && let Some(texture) = font.critical_backing_texture()
                    {
                        self.render_critical_backing(renderer, table, texture.clone(), screen, distance_scale);
                    }
                }
                DamageLayer::Digits => {
                    self.render_digits(renderer, font, table, screen, distance_scale);
                }
            }
        }
    }
}

impl DamageNumber {
    /// Draws the `MET_CRITICAL_EFFECT` backing sprite for one step.
    ///
    /// The caller guarantees the sprite is loaded; if the data set does not
    /// ship it, [`crate::world::damage_font::DamageFont`] logs the exact
    /// missing asset once and no quad is drawn (the digits still render).
    fn render_critical_backing(
        &self,
        renderer: &GameInterfaceRenderer,
        table: &DamageNumbers,
        texture: Arc<Texture>,
        screen: ScreenPosition,
        distance_scale: f32,
    ) {
        let backing = &table.critical_backing;
        let elapsed = self.elapsed_frames();
        let scale = distance_scale * self.critical_backing_scale();
        let cell_x = backing.cell_x_at(elapsed);
        let adjusted_x = adjusted_cell_position(cell_x, backing.width as f32, backing.cell_scale_x);
        let adjusted_y = adjusted_cell_position(backing.cell_y, backing.height as f32, backing.cell_scale_y);
        let tint = backing.tint();
        let color = Color::rgba(tint.red, tint.green, tint.blue, backing.alpha_at(elapsed) as f32 / 255.0);

        let left = screen.left + adjusted_x * backing.cell_scale_x * scale;
        let top = screen.top + adjusted_y * backing.cell_scale_y * scale;
        let size = ScreenSize {
            width: backing.width as f32 * backing.cell_scale_x * scale,
            height: backing.height as f32 * backing.cell_scale_y * scale,
        };

        renderer.render_sprite(texture, ScreenPosition { left, top }, size, ScreenClip::unbound(), color, false);
    }

    fn render_digits(
        &self,
        renderer: &GameInterfaceRenderer,
        font: &damage_font::DamageFont,
        table: &DamageNumbers,
        screen: ScreenPosition,
        distance_scale: f32,
    ) {
        let (cell_scale_x, cell_scale_y) = font.cell_scale();
        let scale = distance_scale * self.scale;
        let count = self.digits.len();
        let color = self.render_color();

        for (index, digit) in self.digits.iter().enumerate() {
            let Some(texture) = font.digit_texture(*digit) else {
                continue;
            };
            let (width, height) = table
                .digits
                .iter()
                .find(|row| row.digit == *digit)
                .map(|row| (row.width as f32, row.height as f32))
                .unwrap_or_else(|| {
                    let size = texture.get_size();
                    (size.width as f32, size.height as f32)
                });

            let adjusted_x = adjusted_cell_position(table.atlas.cell_x, width, cell_scale_x);
            let adjusted_y = adjusted_cell_position(table.atlas.cell_y, height, cell_scale_y);
            let offset = digit_offset(count, index, self.extended_layout);

            // `PrepareSprite` adds `spriteOffsetX * render.scale * distanceScale`
            // to the quad after the cell offset, so the horizontal advance is
            // not multiplied by the cell scale (`ActorGeometry.cpp:84-160`).
            let left = screen.left + (adjusted_x * cell_scale_x + offset) * scale;
            let top = screen.top + adjusted_y * cell_scale_y * scale;
            let size = ScreenSize {
                width: width * cell_scale_x * scale,
                height: height * cell_scale_y * scale,
            };

            renderer.render_sprite(
                texture.clone(),
                ScreenPosition { left, top },
                size,
                ScreenClip::unbound(),
                color,
                false,
            );
        }
    }
}

