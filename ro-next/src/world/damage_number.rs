/// The sprite layers a number draws, in painter order (first = behind).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DamageLayer {
    /// `MET_CRITICAL_EFFECT`, the `이팩트\msg` burst behind a critical number.
    CriticalBacking,
    /// The digits (`이팩트\숫자`).
    Digits,
}

/// Painter order of a number's quads.
///
/// The critical backing comes first because its `depthLayer` is -5 while the
/// digits' is -2 (`MsgEffect.cpp:1832` / `:1772`); the official renderer adds
/// the layer to the reciprocal depth (`ActorGeometry.cpp:146-160`), so -5 is
/// farther away and drawn behind. Only the critical style requests it.
pub fn damage_layers(style: DamageNumberStyle, critical_backing: bool) -> &'static [DamageLayer] {
    match (style, critical_backing) {
        (DamageNumberStyle::Critical, true) => &[DamageLayer::CriticalBacking, DamageLayer::Digits],
        _ => &[DamageLayer::Digits],
    }
}

/// The official multi-hit spacing, `g_multiHitInterval`.
pub const MULTI_HIT_INTERVAL_MS: u32 = 200;

/// Horizontal drift direction of `MsgEffectDriftDirection`
/// (`MsgEffect.cpp:122-174`).
///
/// The port's [`Direction`] is the body angle in 45 degree steps (`0` = 0
/// degrees), so the official `render.angle` ranges map directly onto the eight
/// values:
///
/// * 0..90 -> `(-0.8, +0.8)`
/// * 90..180 -> `(-0.8, -0.8)`
/// * 180..270 -> `(+0.8, -0.8)`
/// * 270..360 -> `(+0.8, +0.8)`
pub fn damage_number_drift(direction: Direction) -> (f32, f32) {
    let angle = u16::from(direction) as u32 * 45;
    match angle {
        0..=89 => (-0.8, 0.8),
        90..=179 => (-0.8, -0.8),
        180..=269 => (0.8, -0.8),
        _ => (0.8, 0.8),
    }
}

/// One number's digit sequence plus the layout variant the official client
/// uses for it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DigitString {
    /// `SpawnDamageDigits` order: units digit first, marker first of all
    /// (`RenderObject.cpp:4779-4794`).
    pub digits: Vec<u8>,
    /// `true` for the hundred-million `m_damageMillionUnit == 2` offsets
    /// (`RenderObject.cpp:4816-4821`).
    pub extended_layout: bool,
}

/// Digits of `value`, following `CGameActor::SpawnDamageDigits`.
pub fn decompose_damage(value: u64) -> DigitString {
    let table = data();
    let extended = &table.extended;
    let markers_available = table
        .digits
        .iter()
        .any(|row| u32::from(row.digit) >= u32::from(extended.million_marker));

    let mut digits = Vec::with_capacity(MAX_DIGITS);
    let mut remaining = value;
    let mut extended_layout = false;

    if EXTENDED_DAMAGE_ENABLED && markers_available && value >= extended.hundred_million_value {
        remaining = value / extended.hundred_million_divisor;
        digits.push(extended.hundred_million_marker);
        extended_layout = true;
    } else if EXTENDED_DAMAGE_ENABLED && markers_available && value >= extended.enabled_value {
        remaining = value / extended.million_divisor;
        digits.push(extended.million_marker);
    } else if !EXTENDED_DAMAGE_ENABLED && value > extended.disabled_cap {
        remaining = extended.disabled_cap;
    }

    loop {
        digits.push((remaining % 10) as u8);
        remaining /= 10;
        if remaining == 0 {
            break;
        }
    }

    DigitString { digits, extended_layout }
}

/// Horizontal offset of digit `index` in pre-`render.scale` sprite pixels.
pub fn digit_offset(count: usize, index: usize, extended_layout: bool) -> f32 {
    let layout = data().layout;
    let count = count as i32;
    let index = index as i32;

    if extended_layout {
        if index == 0 {
            ((count - 1) * layout.extended_base + layout.extended_first_add) as f32
        } else {
            ((count - 1) * layout.extended_base - index * layout.extended_step) as f32
        }
    } else {
        ((count - index * 2) * layout.unit + layout.bias) as f32
    }
}

