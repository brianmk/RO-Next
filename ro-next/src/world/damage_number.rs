    #[test]
    fn a_new_total_number_replaces_the_previous_total_of_the_same_owner() {
        let entity_id = ragnarok_packets::EntityId(7);
        let mut holder = crate::world::ParticleHolder::default();

        let total = |entity_id| {
            DamageNumber::new(
                Some(entity_id),
                Point3::new(0.0, 0.0, 0.0),
                100,
                DamageNumberStyle::Total,
                DamageColor::White,
                Direction::North,
                0,
            )
        };

        holder.spawn_particle(Box::new(total(entity_id)));
        assert_eq!(holder.count(), 1);
        holder.spawn_particle(Box::new(total(entity_id)));
        assert_eq!(holder.count(), 1, "SpawnDamageDigits clears the previous type-22 number");

        holder.spawn_particle(Box::new(total(ragnarok_packets::EntityId(8))));
        assert_eq!(holder.count(), 2, "another actor keeps its own total");

        let normal = DamageNumber::new(
            Some(entity_id),
            Point3::new(0.0, 0.0, 0.0),
            100,
            DamageNumberStyle::Normal,
            DamageColor::White,
            Direction::North,
            0,
        );
        holder.spawn_particle(Box::new(normal));
        assert_eq!(holder.count(), 3, "normal numbers are never replaced");
    }

