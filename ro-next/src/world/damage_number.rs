//! Official damage/heal/miss numbers (`CMsgEffect`, types 13/14/16/21/22/114).
//!
//! The classic client does not draw damage as interface text. `AM_MAKE_NUMBER`
//! (`GameObject.cpp:1304-1316`) calls `CGameActor::SpawnDamageDigits`, which
//! creates one `CMsgEffect` per digit of the value. Each number follows a
//! per-type timeline in `CMsgEffect::OnProcess` (rise, shrink, fade, lifetime)
//! and is drawn from the shared `data\sprite\이팩트\숫자.spr` atlas.
//!
//! This module is the object and timeline of that system:
//!
//! * [`DamageNumber`] - one spawned number. It owns the digit sequence, the
//!   style, the spawn colour and the fixed-step timeline.
//! * [`DamageNumberStyle`] - the six official number types the data file
//!   describes (normal 14, critical 16, half 21, total 22, simple 114, miss
//!   13).
//! * [`DamageColor`] - the official ARGB colours (`GameObject.cpp:1900-1945`,
//!   `GameModePackets.cpp:1653-1665`, `:4683-4698`).
//! * [`CriticalBackingRow`] - the `MET_CRITICAL_EFFECT` sprite the client draws
//!   *behind* a critical number (`data\sprite\이팩트\msg.spr` image 3, ACT
//!   action 2). It is a property of the critical style; the official client
//!   only spawns it for the `DMG_MULTI_HIT_CRITICAL` message
//!   (`GameObject.cpp:1917-1924`).
//! * the data loader for `archive/data/client/damage_numbers.ron` (generated by
//!   `tools/gen_damage_numbers.py`, with a `--check` mode).
//!
//! Timeline:
//!
//! * `CMsgEffect::GetElapsedFrames` is `(timeGetTime() - motionStartTime) /
//!   24.0` (`GameActor.cpp:1107-1109`), so every style value below is in 24 ms
//!   "frames".
//! * The client runs effect state on a **fixed 16 ms step**
//!   (`Timer.cpp:17-26`), so this object accumulates wall time and only
//!   advances on whole 16 ms steps. A 50 ms frame is three steps, exactly like
//!   the ported effect holder.
//!
//! Rendering:
//!
//! * digits are separate screen-space quads placed by `(digits - index * 2) * 4
//!   - 4` pre-scale pixels (`RenderObject.cpp:4823`); the spacing is multiplied
//!   by the current `render.scale` and the camera distance scale, like
//!   `PrepareSprite` (`ActorGeometry.cpp:84-160`).
//! * the sprite ACT stores cell positions at the **centre** of the image;
//!   `CActRes::AdjustCellPosition` turns them into top-left offsets
//!   (`ActionResource.cpp:16-23`), which the shared effect sprite pass already
//!   ports as [`adjusted_cell_position`](crate::world::effect::port::sprite_pass::adjusted_cell_position).
//! * the official draw is `RSF_ALPHA | RSF_DEPTH_SORTED`
//!   (`CMsgEffect::FollowOwner`, `MsgEffect.cpp:1328`) with no separate outline
//!   quad: `DrawPulseOutline` only draws when `render.flags & 8` is set
//!   (`RenderObject.cpp:1964-2005`), which number effects never set; the black
//!   border is part of the digit art itself.
//! * the one extra quad is the critical backing: it is painted **before** the
//!   digits (`depthLayer` -5 vs -2, `MsgEffect.cpp:1832` / `:1772`) at the same
//!   anchor, shrunk to 1.0 and grey-tinted (`AM_SETPOS`, `:1825-1835`).
//! * numbers are screen overlays drawn after the world actors, so they are not
//!   depth-tested against the actor they belong to (the official `depthLayer
//!   -2` is the 2D queue's ordering, `MsgEffect.cpp:1772`).

