static DATA: OnceLock<DamageNumbers> = OnceLock::new();

/// The loaded damage-number tables.
///
/// The compiled fallback is validated by the tests (`compiled_data_is_valid`),
/// so a parse failure here is a build/packaging bug, not a data error.
pub(crate) fn data() -> &'static DamageNumbers {
    DATA.get_or_init(|| parse(FALLBACK).expect("the compiled damage-numbers data has to be valid"))
}

/// Loads `data\client\damage_numbers.ron` from the archive (or the compiled
/// fallback). The archive override wins, like the other data-driven tables.
pub(crate) fn load(game_file_loader: &GameFileLoader) {
    let from_archive = game_file_loader
        .get(DATA_PATH)
        .ok()
        .map(|bytes| String::from_utf8_lossy(&bytes).into_owned());

    let table = match from_archive.as_deref() {
        Some(content) => match parse(content) {
            Ok(table) => {
                crate::logging::log_debug!("damage numbers: loaded {DATA_PATH} from the archive");
                table
            }
            Err(error) => {
                crate::logging::log_warn!("damage numbers: invalid {DATA_PATH} ({error}), using the compiled fallback");
                parse(FALLBACK).expect("the compiled damage-numbers data has to be valid")
            }
        },
        None => parse(FALLBACK).expect("the compiled damage-numbers data has to be valid"),
    };

    let _ = DATA.set(table);
}

/// The style row of a number type.
pub(crate) fn style(style: DamageNumberStyle) -> &'static DamageNumberStyleData {
    data()
        .styles
        .iter()
        .find(|row| row.name == style)
        .expect("every damage-number style is present in the data")
}

/// The default colour of a number type (`CMsgEffect` spawn colour).
pub(crate) fn style_color(style: DamageNumberStyle) -> DamageColor {
    self::style(style).color
}

/// The resolved colour of a named official ARGB value.
pub(crate) fn color(color: DamageColor) -> Color {
    data()
        .colors
        .iter()
        .find(|(name, _)| *name == color)
        .map(|(_, value)| *value)
        .expect("every damage-number colour is present in the data")
}

