//! Status/skill -> official effect launches.
//!
//! `archive/data/client/status_effect_launches.ron` maps a status (`EFST_*`
//! id) or a skill id to the official effect ids the client launches when the
//! state starts. Two independent official switches produce those rows:
//!
//! * `CGameActor::SendMsg`, `case AM_STATUS_CHANGE:`
//!   (`GameObject.cpp:2535-4398`) launches the effect of a status on every
//!   status change, and `CPlayer::ReapplySkillEffects` (`Player.cpp:3180-3850`)
//!   re-launches the same rows when the client rebuilds the actor (map entry,
//!   map property change). A status row is therefore spawned again on every
//!   status (re-)application; `relaunch` records whether the official case
//!   deletes the previous instance first (`while (this->HasId(EF_...))`,
//!   `GameObject.cpp:2686-2688`).
//! * `CGameMode::ApplyActorSkillState` (`GameModePackets.cpp:12868-12897`)
//!   launches the cast-start effect of a skill (`CH_SOULCOLLECT` ->
//!   `EF_PORTAL5`). It runs from `CGameMode::NotifySkillCasting` at
//!   `GameModePackets.cpp:12968`, i.e. only for casts with `delay != 0`.
//!
//! The effect ids are the official `RagEffectID` numeric values; decoding them
//! back into [`EffectId`] is the same wire conversion the effect packets use,
//! so an id the client does not know is a schema error. The spawn path is the
//! ported effect holder (`port::holder::PortedEffectHolder` through
//! `port::visual::PortedVisual`), like every other official effect.
//!
//! The file is generated by `tools/gen_status_effect_launches.py` from
//! `tools/data/status_effect_launches_facts.json` (extracted by
//! `tools/extract_status_effect_launches.py`); the compiled copy is embedded
//! so an archive override and the fallback cannot drift.

use std::sync::OnceLock;

use ragnarok_bytes::{ByteReader, FromBytes};
use ragnarok_packets::{EffectId, SkillId};
use ro_next_loaders::FileLoader;
use serde::Deserialize;

use crate::loaders::GameFileLoader;

const DATA_PATH: &str = "data\\client\\status_effect_launches.ron";
const FALLBACK: &str = include_str!("../../../archive/data/client/status_effect_launches.ron");

/// One status row of the launch table.
#[derive(Debug, Clone, Copy)]
pub struct StatusLaunchSpec {
    /// `EFST_*` status id (`ZC_MSG_STATE_CHANGE`), the id the server sends.
    pub status_index: u16,
    /// Official effects launched when the status is (re-)applied.
    pub effects: &'static [EffectId],
    /// `true` when the official case deletes the previous instance before
    /// launching (`while (this->HasId(EF_...))`); `false` for the guarded
    /// `if (!HasId(...))` launches that keep the running instance.
    pub relaunch: bool,
    /// Decompiled source of the row (`file:line`).
    pub source: &'static str,
}

/// One skill row of the launch table.
#[derive(Debug, Clone, Copy)]
pub struct SkillLaunchSpec {
    /// Skill id of the cast.
    pub skill_id: u16,
    /// Official effects launched when the cast starts.
    pub effects: &'static [EffectId],
    /// Decompiled source of the row (`file:line`).
    pub source: &'static str,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct LaunchFile {
    #[allow(dead_code)]
    provenance: String,
    #[allow(dead_code)]
    version: u32,
    statuses: Vec<StatusLaunchRow>,
    skills: Vec<SkillLaunchRow>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct StatusLaunchRow {
    id: u16,
    effects: Vec<u32>,
    #[serde(default)]
    relaunch: bool,
    source: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct SkillLaunchRow {
    id: u16,
    effects: Vec<u32>,
    source: String,
}

struct LaunchTable {
    statuses: Vec<StatusLaunchSpec>,
    skills: Vec<SkillLaunchSpec>,
}

/// Decodes an official `RagEffectID` value into the client's [`EffectId`].
///
/// This is the same numeric conversion the effect packets use
/// (`EffectId` is `#[numeric_type(u32)]`), so an id that the client cannot
/// represent is rejected instead of silently spawning nothing.
fn decode_effect_id(value: u32) -> Result<EffectId, String> {
    EffectId::from_bytes(&mut ByteReader::without_metadata(&value.to_le_bytes()))
        .map_err(|_| format!("schema error: unknown effect id {value}"))
}

fn parse_effects(row_source: &str, id: u16, effects: Vec<u32>) -> Result<Vec<EffectId>, String> {
    if effects.is_empty() {
        return Err(format!("schema error: id {id} has no effects ({row_source})"));
    }

    let mut decoded = Vec::with_capacity(effects.len());
    for value in effects {
        if decoded.contains(&decode_effect_id(value)?) {
            return Err(format!("schema error: id {id} lists effect {value} twice"));
        }
        decoded.push(decode_effect_id(value)?);
    }

    // The spawn path can only build a ported body; listing an unported effect
    // would make the row silently dead. `ported_ids()` is the same list the
    // ported skill map is pinned to.
    let ported = crate::world::port::registry::ported_ids();
    for effect in &decoded {
        if !ported.contains(effect) {
            return Err(format!("schema error: id {id} lists {effect:?}, which has no ported body"));
        }
    }

    Ok(decoded)
}

fn parse(content: &str) -> Result<LaunchTable, String> {
    let file: LaunchFile = ron::from_str(content).map_err(|error| format!("schema error: {error}"))?;

    let mut statuses = Vec::with_capacity(file.statuses.len());
    for row in file.statuses {
        if row.source.trim().is_empty() {
            return Err(format!("schema error: status {} has no source", row.id));
        }
        if crate::world::status_effect_info(row.id).is_none() {
            return Err(format!(
                "schema error: status {} has no presentation row in status_effects",
                row.id
            ));
        }

        statuses.push(StatusLaunchSpec {
            status_index: row.id,
            effects: Box::leak(parse_effects(&row.source, row.id, row.effects)?.into_boxed_slice()),
            relaunch: row.relaunch,
            source: Box::leak(row.source.into_boxed_str()),
        });
    }

    let mut skills = Vec::with_capacity(file.skills.len());
    for row in file.skills {
        if row.source.trim().is_empty() {
            return Err(format!("schema error: skill {} has no source", row.id));
        }

        skills.push(SkillLaunchSpec {
            skill_id: row.id,
            effects: Box::leak(parse_effects(&row.source, row.id, row.effects)?.into_boxed_slice()),
            source: Box::leak(row.source.into_boxed_str()),
        });
    }

    statuses.sort_by_key(|row| row.status_index);
    if let Some(pair) = statuses.windows(2).find(|pair| pair[0].status_index == pair[1].status_index) {
        return Err(format!("schema error: duplicate status launch id {}", pair[0].status_index));
    }

    skills.sort_by_key(|row| row.skill_id);
    if let Some(pair) = skills.windows(2).find(|pair| pair[0].skill_id == pair[1].skill_id) {
        return Err(format!("schema error: duplicate skill launch id {}", pair[0].skill_id));
    }

    Ok(LaunchTable { statuses, skills })
}

static COMPILED: OnceLock<LaunchTable> = OnceLock::new();
static ARCHIVE: OnceLock<LaunchTable> = OnceLock::new();

fn compiled() -> &'static LaunchTable {
    COMPILED.get_or_init(|| match parse(FALLBACK) {
        Ok(table) => table,
        Err(error) => {
            crate::logging::log_error!("status effect launches: compiled fallback is invalid ({error})");
            LaunchTable {
                statuses: Vec::new(),
                skills: Vec::new(),
            }
        }
    })
}

fn table() -> &'static LaunchTable {
    ARCHIVE.get().unwrap_or_else(compiled)
}

/// Loads the launch table from the client archive (or the compiled fallback)
/// and returns the number of rows.
pub(crate) fn load(game_file_loader: &GameFileLoader) -> usize {
    let from_archive = game_file_loader
        .get(DATA_PATH)
        .ok()
        .map(|bytes| String::from_utf8_lossy(&bytes).into_owned());

    let Some(content) = from_archive.as_deref() else {
        let table = compiled();
        let count = table.statuses.len() + table.skills.len();
        crate::logging::log_info!("status effect launches: loaded {count} rows from the compiled fallback");
        return count;
    };

    match parse(content) {
        Ok(table) => {
            let count = table.statuses.len() + table.skills.len();
            let _ = ARCHIVE.set(table);
            crate::logging::log_info!("status effect launches: loaded {count} rows from the archive override");
            count
        }
        Err(error) => {
            crate::logging::log_warn!("status effect launches: invalid archive override ({error}); using compiled fallback");
            let table = compiled();

            table.statuses.len() + table.skills.len()
        }
    }
}

/// Official effect launch of one status, if the table lists it.
pub fn status_launch(status_index: u16) -> Option<&'static StatusLaunchSpec> {
    let statuses = &table().statuses;

    statuses
        .binary_search_by_key(&status_index, |row| row.status_index)
        .ok()
        .map(|index| &statuses[index])
}

/// Official cast-start effect launch of one skill, if the table lists it.
pub fn skill_launch(skill_id: SkillId) -> Option<&'static SkillLaunchSpec> {
    let skills = &table().skills;

    skills
        .binary_search_by_key(&skill_id.0, |row| row.skill_id)
        .ok()
        .map(|index| &skills[index])
}

/// Every status row, in id order (test/introspection hook).
#[cfg(test)]
pub fn status_launches() -> &'static [StatusLaunchSpec] {
    &table().statuses
}

/// Every skill row, in id order (test/introspection hook).
#[cfg(test)]
pub fn skill_launches() -> &'static [SkillLaunchSpec] {
    &table().skills
}

/// Validates a launch table data file and returns its row count.
#[cfg(test)]
pub fn validate(content: &str) -> Result<usize, String> {
    parse(content).map(|table| table.statuses.len() + table.skills.len())
}

/// Validates the compiled fallback.
#[cfg(test)]
pub fn validate_compiled() -> Result<usize, String> {
    parse(FALLBACK).map(|table| table.statuses.len() + table.skills.len())
}

#[cfg(test)]
mod tests {
    use ragnarok_packets::{EffectId, SkillId};

    use super::{skill_launch, skill_launches, status_launch, status_launches, validate, validate_compiled};

    #[test]
    fn compiled_launch_table_is_valid() {
        let count = validate_compiled().expect("compiled status effect launches");
        assert_eq!(count, 3, "Steel Body, D Barrier and Soul Collect");
    }

    #[test]
    fn steel_body_launches_the_sustoop_sound_body() {
        // `case EFST_STEELBODY: case EFST_DBARRIER:` (`GameObject.cpp:2684-2702`)
        // deletes the old instances and launches `EF_STEELBODY` + `EF_SU_STOOP`;
        // `CPlayer::ReapplySkillEffects` re-launches both (`Player.cpp:3256-3259`).
        // The fan (`EF_STEELBODY`, 254) is already the status-87 persistent
        // aura in `status_effects.ron`, so only `EF_SU_STOOP` (1132, the body
        // that owns `effect\mon_금강불괴.wav`) is launched here.
        for status in [87, 235] {
            let launch = status_launch(status).expect("steel body launch row");
            assert_eq!(launch.effects, [EffectId::SuStoop]);
            assert!(launch.relaunch, "the official case deletes and relaunches");
            assert!(launch.source.contains("GameObject.cpp:"));
            assert!(launch.source.contains("ReapplySkillEffects"));
        }
    }

    #[test]
    fn soul_collect_launches_the_portal_on_cast_start() {
        // `CGameMode::ApplyActorSkillState` (`GameModePackets.cpp:12883-12886`):
        // `case CH_SOULCOLLECT:` -> `LaunchEffect(EF_PORTAL5, ...)`.
        let launch = skill_launch(SkillId(401)).expect("soul collect launch row");
        assert_eq!(launch.effects, [EffectId::Portal5]);
        assert!(launch.source.contains("GameModePackets.cpp:12885"));
        assert!(skill_launch(SkillId(400)).is_none());
    }

    #[test]
    fn every_listed_effect_has_a_ported_body() {
        // `parse` already rejects unported ids; this pins the intent of the
        // whole table so an id swap that happens to stay ported is noticed.
        for row in status_launches() {
            for effect in row.effects {
                assert!(
                    crate::world::port::registry::ported_ids().contains(effect),
                    "{effect:?} has no ported body"
                );
            }
        }
        for row in skill_launches() {
            for effect in row.effects {
                assert!(
                    crate::world::port::registry::ported_ids().contains(effect),
                    "{effect:?} has no ported body"
                );
            }
        }
    }

    #[test]
    fn every_listed_status_has_a_presentation_row() {
        for row in status_launches() {
            assert!(
                crate::world::status_effect_info(row.status_index).is_some(),
                "status {} must exist in status_effects.ron",
                row.status_index
            );
        }
    }

    #[test]
    fn unlisted_statuses_and_skills_have_no_launch() {
        assert!(status_launch(86).is_none());
        assert!(
            status_launch(1053).is_none(),
            "Soul Collect is launched by the skill path, not a status"
        );
        assert!(skill_launch(SkillId(1)).is_none());
    }

    #[test]
    fn malformed_launch_tables_are_rejected() {
        // Unknown effect id.
        let unknown_effect = r#"(
            provenance: "test",
            version: 1,
            statuses: [(id: 87, effects: [99999], relaunch: true, source: "test")],
            skills: [],
        )"#;
        assert!(validate(unknown_effect).is_err());

        // A known but unported effect id (EF_HIT1 = 1 has a body? no: use an
        // id the registry does not spawn). `EF_UNK_800` is not known either;
        // the ported check is covered by `every_listed_effect_has_a_ported_body`
        // and by the generator, so only the empty/duplicate cases are needed
        // here.
        let empty = r#"(
            provenance: "test",
            version: 1,
            statuses: [(id: 87, effects: [], relaunch: true, source: "test")],
            skills: [],
        )"#;
        assert!(validate(empty).is_err());

        let no_source = r#"(
            provenance: "test",
            version: 1,
            statuses: [(id: 87, effects: [1132], relaunch: true, source: "  ")],
            skills: [],
        )"#;
        assert!(validate(no_source).is_err());

        let unknown_status = r#"(
            provenance: "test",
            version: 1,
            statuses: [(id: 60000, effects: [1132], relaunch: true, source: "test")],
            skills: [],
        )"#;
        assert!(validate(unknown_status).is_err());

        let duplicate = r#"(
            provenance: "test",
            version: 1,
            statuses: [
                (id: 87, effects: [1132], relaunch: true, source: "test"),
                (id: 87, effects: [1132], relaunch: false, source: "test"),
            ],
            skills: [],
        )"#;
        assert!(validate(duplicate).is_err());
    }
}
