//! Official auto-attack hit feedback: the impact wave, the defender hit effect
//! and the damage number.
//!
//! The official client produces all three from the **damage message**, not
//! from the attack animation:
//!
//! * `CGameActor::ProcessHitMessage`
//!   (`Source/Contents/Actors/RenderObject.cpp:3693`) fills the delayed
//!   `ActorDamageMessage`: the normal/critical action is
//!   `AM_ATTACKED`/`AM_ATTACKED_CRITICAL` (`:3771-3794`), `hitEffect` is `-1`
//!   for a normal hit and `1` (`EF_HIT2`) for a critical hit (`:3769-3782`),
//!   `effectId` is `0` (`EF_HIT1`) except for the Taekwon/Star job family
//!   (`EF_HITLINE7`, `:3801-3817`) and Violen (`EF_VIOLEN_HIT`, `:3818-3821`),
//!   and a self-hit sets `effectId = -2` (`:3828-3830`).
//! * `CGameActor::SendMsg(AM_ATTACKED, ...)`
//!   (`Source/Contents/Actors/GameObject.cpp:1723-1900`) plays the impact wave
//!   for a non-zero damage value (`:1768`, `:1782-1841`), spawns
//!   `hitEffect`/`effectId` on the defender (`:1843-1888`) and shows the damage
//!   number (`:1890` onward). A miss (`damage == 0`, `:1768`) plays and spawns
//!   neither.
//!
//! ## Impact wave
//!
//! [`auto_attack_hit_feedback`] returns **one** wave per damage message
//! (`g_soundMgr->PlayWave(wave, dx, 0, dz, 250, 40, 1.0f, 0)`,
//! `GameObject.cpp:1840`). `CSession::GetHitWaveName`/`GetWeaponHitWaveName`
//! (`Source/Contents/Sound/HitSounds.cpp:12-74`) select it in this order:
//!
//! 1. the defender is a player job -> the defender's job clothing wave
//!    (`GetHitWaveName`, `HitSounds.cpp:12-30`; table in `InitJobHitWaveNames`,
//!    `:78-222`);
//! 2. no attacker / the attacker has no player weapon (`GetWeapon()` returns
//!    `-1`) -> a random `_enemy_hit_normal{1..4}.wav` (`:37-47`);
//! 3. a bare-handed attacker (`realWeapon == 0`) -> a random
//!    `_hit_fist{1..4}.wav`, unless the display job is Taekwon, which falls
//!    through to the table's Fist row (`_hit_mace.wav`) (`:55-71`);
//! 4. otherwise the official `WeaponHitWaveNameTable` row of the base weapon
//!    class (`:73`).
//!
//! There is **no** target-size, race or critical variation: a critical hit
//! keeps the same wave and only adds the `EF_HIT2` effect. The official splits
//! a damage packet with `hitCount > 1` into one damage message per hit
//! (`RenderObject.cpp:3881-3890`) and therefore plays one wave per hit. A
//! dual-wield attack is also two messages - the main-hand damage and the
//! packet's `damage_amount_2` (`RenderObject.cpp:3856-3877`) - so it plays two
//! waves, the second one after the official stagger
//! ([`dual_wield_hit_delay_ms`]).
//!
//! The table lives in `archive/data/client/hit_feedback.ron`, generated by
//! `tools/gen_hit_feedback.py` from the committed facts
//! (`tools/data/hit_feedback_facts.json`, extracted from the CondaRO client's
//! `weapontable.lub` and the decompilation). It is embedded with
//! `include_str!`; this table has no runtime archive override yet.
//!
//! ## Hit effect
//!
//! The official spawns `effectId` on the defender (`GameObject.cpp:1879`) and
//! `hitEffect` when it is not `-1` (`:1866`), so a normal hit spawns `EF_HIT1`
//! and a critical hit spawns `EF_HIT2` **and** `EF_HIT1` (the critical
//! `hitEffect` is additive). The Taekwon/Star job family replaces `EF_HIT1`
//! with `EF_HITLINE7` (`RenderObject.cpp:3801-3817`). Violen replaces it with
//! `EF_VIOLEN_HIT` (2420, `:3818-3821`; `EffectId::ViolenHit`).
//!
//! ## No hit flash
//!
//! The official does not tint the defender on a normal hit: `SendMsg` sets
//! `render.isSingleColor = true` (`GameObject.cpp:1793`) but leaves
//! `overrideColor` at the `0xFFFF0000` "no override" sentinel that
//! `CRenderObject::PrepareSprite` skips (`ActorGeometry.cpp:194`). Only
//! `AM_ATTACKED_SKILL` assigns a real tint (`GameObject.cpp:1713-1721`). The
//! visible target feedback of an auto attack is therefore the damage number
//! plus the hit effect.
//!
//! ## Known simplification
//!
//! The official checks the *local session's* display job for the bare-hand
//! Taekwon exception (`this->GetDisplayJob()` inside `CSession`,
//! `HitSounds.cpp:55`). This module checks the attacker's job instead, which
//! is identical for the local player's own attacks and classifies a remote
//! attacker by its own job (`GetDisplayJob` is the identity for
//! `JT_TAEKWON`/`JT_TAEKWON_B`, so the two only differ for another actor's
//! bare-hand attack while the local player is a Taekwon).

use std::collections::HashMap;
use std::sync::OnceLock;

use cgmath::Point3;
use ragnarok_packets::{Direction, EffectId, EntityId, JobId};
use serde::Deserialize;

use crate::world::weapon::{self, WeaponKind};

/// Compiled copy of the generated table.
const FALLBACK: &str = include_str!("../../../archive/data/client/hit_feedback.ron");

/// Official default of `m_weaponHitWaves` (`InitWeaponHitWaveNames`,
/// `Source/Client/Session/Session.cpp:3529`) and of unlisted job rows
/// (`InitJobHitWaveNames`, `Source/Contents/Sound/HitSounds.cpp:107-108`).
const DEFAULT_WEAPON_WAVE: &str = "_hit_mace.wav";
const DEFAULT_JOB_WAVE: &str = "player_clothes.wav";

/// `GetHitWaveName` indexes jobs above this value with `job - 3950`
/// (`Source/Contents/Sound/HitSounds.cpp:21-27`): the transcendent/third-job
/// ids share the low table rows.
const JOB_TABLE_SHIFT_BASE: u16 = 3950;

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct WeaponWaveRow {
    kind: WeaponKind,
    wave: String,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct JobWaveRow {
    index: u16,
    wave: String,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct HitFeedbackFile {
    #[allow(dead_code)]
    provenance: String,
    #[allow(dead_code)]
    version: u32,
    weapon_waves: Vec<WeaponWaveRow>,
    fist_waves: Vec<String>,
    enemy_waves: Vec<String>,
    taekwon_jobs: Vec<u16>,
    /// `RenderObject.cpp:3801-3817`: the Taekwon/Star family spawns
    /// `EF_HITLINE7` instead of `EF_HIT1`.
    hitline7_jobs: Vec<u16>,
    /// `RenderObject.cpp:3818-3821`: Violen spawns `EF_VIOLEN_HIT`.
    violen_jobs: Vec<u16>,
    job_default_wave: String,
    job_waves: Vec<JobWaveRow>,
}

/// Parsed hit-feedback tables.
struct HitFeedbackTables {
    weapon_waves: HashMap<WeaponKind, String>,
    fist_waves: Vec<String>,
    enemy_waves: Vec<String>,
    taekwon_jobs: Vec<u16>,
    hitline7_jobs: Vec<u16>,
    violen_jobs: Vec<u16>,
    job_default_wave: String,
    job_waves: HashMap<u16, String>,
}

impl HitFeedbackTables {
    fn empty() -> Self {
        Self {
            weapon_waves: HashMap::new(),
            fist_waves: vec![DEFAULT_WEAPON_WAVE.to_owned()],
            enemy_waves: vec!["_enemy_hit_normal1.wav".to_owned()],
            taekwon_jobs: Vec::new(),
            hitline7_jobs: Vec::new(),
            violen_jobs: Vec::new(),
            job_default_wave: DEFAULT_JOB_WAVE.to_owned(),
            job_waves: HashMap::new(),
        }
    }

    fn parse(content: &str) -> Result<Self, String> {
        let file: HitFeedbackFile = ron::from_str(content).map_err(|error| format!("schema error: {error}"))?;

        if file.weapon_waves.is_empty() {
            return Err("no weapon hit waves".to_owned());
        }
        if file.fist_waves.len() != 4 {
            return Err(format!("expected 4 fist waves, got {}", file.fist_waves.len()));
        }
        if file.enemy_waves.len() != 4 {
            return Err(format!("expected 4 enemy waves, got {}", file.enemy_waves.len()));
        }
        if file.hitline7_jobs.len() != 14 {
            return Err(format!("expected 14 EF_HITLINE7 jobs, got {}", file.hitline7_jobs.len()));
        }
        if file.violen_jobs.len() != 2 {
            return Err(format!("expected 2 EF_VIOLEN_HIT jobs, got {}", file.violen_jobs.len()));
        }

        let mut weapon_waves = HashMap::with_capacity(file.weapon_waves.len());
        for row in file.weapon_waves {
            if weapon_waves.insert(row.kind, row.wave).is_some() {
                return Err(format!("duplicate weapon kind {:?}", row.kind));
            }
        }

        let mut job_waves = HashMap::with_capacity(file.job_waves.len());
        for row in file.job_waves {
            if row.wave == file.job_default_wave {
                return Err(format!("job index {} repeats the default wave", row.index));
            }
            if job_waves.insert(row.index, row.wave).is_some() {
                return Err(format!("duplicate job wave index {}", row.index));
            }
        }

        let taekwon_count = file.taekwon_jobs.len();
        let mut taekwon_jobs = file.taekwon_jobs;
        taekwon_jobs.sort_unstable();
        taekwon_jobs.dedup();
        if taekwon_jobs.len() != taekwon_count {
            return Err("duplicate Taekwon job".to_owned());
        }

        let hitline7_count = file.hitline7_jobs.len();
        let mut hitline7_jobs = file.hitline7_jobs;
        hitline7_jobs.sort_unstable();
        hitline7_jobs.dedup();
        if hitline7_jobs.len() != hitline7_count {
            return Err("duplicate EF_HITLINE7 job".to_owned());
        }
        if taekwon_jobs.iter().any(|job| !hitline7_jobs.contains(job)) {
            return Err("a Taekwon job is missing from the EF_HITLINE7 list".to_owned());
        }

        let violen_count = file.violen_jobs.len();
        let mut violen_jobs = file.violen_jobs;
        violen_jobs.sort_unstable();
        violen_jobs.dedup();
        if violen_jobs.len() != violen_count {
            return Err("duplicate Violen job".to_owned());
        }

        Ok(Self {
            weapon_waves,
            fist_waves: file.fist_waves,
            enemy_waves: file.enemy_waves,
            taekwon_jobs,
            hitline7_jobs,
            violen_jobs,
            job_default_wave: file.job_default_wave,
            job_waves,
        })
    }
}

static TABLES: OnceLock<HitFeedbackTables> = OnceLock::new();

fn tables() -> &'static HitFeedbackTables {
    TABLES.get_or_init(|| match HitFeedbackTables::parse(FALLBACK) {
        Ok(tables) => tables,
        Err(error) => {
            crate::logging::log_warn!("hit feedback: compiled table is invalid ({error})");
            HitFeedbackTables::empty()
        }
    })
}

/// `m_weaponHitWaves[GetRealWeaponId(weapon)]` (`HitSounds.cpp:73-76`).
///
/// The base weapon class is resolved by the data-driven weapon registry, so
/// item view ids and the special 31..102 classes are already folded like
/// `GetRealWeaponId` does. `Unknown` uses the array's `_hit_mace.wav` default.
pub fn weapon_hit_wave(kind: WeaponKind) -> &'static str {
    tables().weapon_waves.get(&kind).map_or(DEFAULT_WEAPON_WAVE, String::as_str)
}

/// The `realWeapon == 0` bare-hand roll (`HitSounds.cpp:61-71`).
pub fn fist_hit_wave(roll: u8) -> &'static str {
    pick(&tables().fist_waves, roll)
}

/// The `realWeapon == -1` enemy roll (`HitSounds.cpp:37-46`).
pub fn enemy_hit_wave(roll: u8) -> &'static str {
    pick(&tables().enemy_waves, roll)
}

/// `GetDisplayJob() == JT_TAEKWON || JT_TAEKWON_B` (`HitSounds.cpp:55-57`).
///
/// This is the bare-hand fist-roll exception of `GetWeaponHitWaveName`; it is
/// *not* the `EF_HITLINE7` list (see [`is_hitline7_job`]).
pub fn is_taekwon_job(job_id: JobId) -> bool {
    tables().taekwon_jobs.contains(&job_id.0)
}

/// The Taekwon/Star job family that replaces `EF_HIT1` with `EF_HITLINE7`
/// (`RenderObject.cpp:3801-3817`).
pub fn is_hitline7_job(job_id: JobId) -> bool {
    tables().hitline7_jobs.contains(&job_id.0)
}

/// Violen jobs, which replace `EF_HIT1` with `EF_VIOLEN_HIT`
/// (`RenderObject.cpp:3818-3821`).
///
/// The official id is `2420` (`EffectTypes.h:2428`); [`EffectId::ViolenHit`]
/// carries exactly that `#[numeric_value]`.
pub fn is_violen_job(job_id: JobId) -> bool {
    tables().violen_jobs.contains(&job_id.0)
}

/// The defender's job clothing wave (`GetHitWaveName`, `HitSounds.cpp:15-32`).
///
/// Jobs above [`JOB_TABLE_SHIFT_BASE`] use `index = job - 3950`; every
/// unlisted index uses `player_clothes.wav`.
pub fn job_hit_wave(job_id: JobId) -> &'static str {
    let tables = tables();
    let index = if job_id.0 > JOB_TABLE_SHIFT_BASE {
        job_id.0 - JOB_TABLE_SHIFT_BASE
    } else {
        job_id.0
    };

    tables
        .job_waves
        .get(&index)
        .map_or(tables.job_default_wave.as_str(), String::as_str)
}

fn pick(waves: &'static [String], roll: u8) -> &'static str {
    if waves.is_empty() {
        return DEFAULT_WEAPON_WAVE;
    }

    &waves[usize::from(roll) % waves.len()]
}

/// Delay of the off-hand damage message of a dual-wield attack, in
/// milliseconds.
///
/// `ProcessHitMessage` sends the main-hand message(s) first and then advances
/// the copied message time by
/// `g_multiHitInterval / 2 + (g_multiHitInterval / 4 + g_multiHitInterval)`
/// before sending the `extraDamage` (off-hand) message
/// (`RenderObject.cpp:3870`); `g_multiHitInterval` is 200 (`:101`), so the
/// second hit is 350 ms late. The official only takes this branch when
/// `extraDamage != 0` and the attacker job passes `IsNpcJob(job) ||
/// job > JT_2004_JOB_BEGIN || job == JT_ASSASSIN` (`:3856`), which every
/// dual-wielding assassin-line attacker does; this client applies the value
/// the server actually sent.
pub fn dual_wield_hit_delay_ms() -> u32 {
    crate::world::MULTI_HIT_INTERVAL_MS / 2 + (crate::world::MULTI_HIT_INTERVAL_MS / 4 + crate::world::MULTI_HIT_INTERVAL_MS)
}

/// The attacker facts the official damage path reads.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HitAttacker {
    pub entity_id: EntityId,
    pub job_id: JobId,
    pub weapon: u32,
    /// `IsPlayerJob(GetEffectiveJob(-1))` of the attacker: only a player actor
    /// has a weapon (`CGameActor::GetWeapon()` returns `-1`,
    /// `Source/Contents/Actors/RenderObject.cpp:2190-2192`).
    pub is_player: bool,
}

/// The defender facts the official damage path reads.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HitDefender {
    pub entity_id: EntityId,
    pub job_id: JobId,
    /// `IsPlayerJob(GetEffectiveJob(-1))` of the defender; selects the
    /// defender's clothing wave instead of the attacker's weapon wave.
    pub is_player: bool,
}

/// The facts of a damage target that the client needs for the damage number,
/// the impact wave and the hit effects.
///
/// The official client produces all three from the damage message
/// (`AM_ATTACKED`/`ProcessHitMessage`) and keeps them independent of the
/// actor's lifetime: the `CMsgEffect`s live in the scene effect list, and the
/// actor still exists while its death animation plays. The port moves a dead
/// monster from `ClientState::entities` to `ClientState::dead_entities` the
/// moment the death packet is handled (`handle_remove_entity`), so a damage
/// message that is dispatched after that packet can no longer resolve the
/// target from the live list. Without a snapshot, the damage number used to
/// be anchored on the attacker and the hit wave/effect were dropped entirely
/// for the killing blow. [`resolve_target`] resolves the target from the live
/// list first and from the dead list second, so both cases keep the target's
/// last known pose.
#[derive(Debug, Clone, Copy)]
pub struct TargetSnapshot {
    pub entity_id: EntityId,
    pub position: Point3<f32>,
    pub direction: Direction,
    pub job_id: JobId,
    /// `IsPlayerJob(GetEffectiveJob(-1))` of the target, classified from the
    /// job id exactly like the rest of the client
    /// (`EntityType::from(job_id) == EntityType::Player`).
    pub is_player: bool,
}

impl TargetSnapshot {
    /// Snapshots a live or dead entity.
    pub fn from_entity(entity: &crate::world::Entity) -> Self {
        let job_id = entity.get_job_id();

        Self {
            entity_id: entity.get_entity_id(),
            position: entity.get_position(),
            direction: entity.get_direction(),
            job_id,
            is_player: crate::world::EntityType::from(job_id) == crate::world::EntityType::Player,
        }
    }

    /// The official actor angle the ported hit effects read as
    /// `runtime.parent_angle`: `render.angle = (direction + 4) * 45`
    /// (`GameObject.cpp:2044`, used by `Hit1`, `RagEffect.cpp:735-743`).
    pub fn parent_angle(&self) -> f32 {
        ((f32::from(u16::from(self.direction)) + 4.0) * 45.0) % 360.0
    }

    /// The defender facts of the hit wave/effect decision.
    pub fn defender(&self) -> HitDefender {
        HitDefender {
            entity_id: self.entity_id,
            job_id: self.job_id,
            is_player: self.is_player,
        }
    }
}

/// Resolves a damage target from the live entities first and from the dead
/// entities second.
///
/// `candidates` is normally
/// `entities.iter().chain(dead_entities).map(TargetSnapshot::from_entity)`, so
/// the first match is the live actor and the fallback is the actor that just
/// died (still in `dead_entities` while its death animation plays). Returns
/// `None` only when the client has never seen the entity; the official client
/// then also has no target and produces no hit feedback
/// (`RenderObject.cpp:3790-3792` returns when `target == nullptr`).
pub fn resolve_target(destination_entity_id: EntityId, candidates: impl IntoIterator<Item = TargetSnapshot>) -> Option<TargetSnapshot> {
    candidates.into_iter().find(|target| target.entity_id == destination_entity_id)
}

/// The feedback of one auto-attack damage message.
///
/// `EffectId` has no `PartialEq` in this client (it only derives the packet
/// conversion), so the plan compares effect ids by their numeric value.
#[derive(Debug, Clone, Copy)]
pub struct AutoAttackHitFeedback {
    /// Impact wave (`GetWeaponHitWaveName`/`GetHitWaveName`), `None` for a
    /// miss or a self-hit.
    pub sound: Option<&'static str>,
    /// Defender effect: `EF_HIT1` normally, `EF_HITLINE7` for the Taekwon/Star
    /// job family and `EF_VIOLEN_HIT` for Violen
    /// (`RenderObject.cpp:3801-3821`). `None` for a miss/self-hit.
    pub hit_effect: Option<EffectId>,
    /// Additional `EF_HIT2` on a critical hit (`RenderObject.cpp:3776-3782`
    /// sets `hitEffect = 1`). `None` on a normal hit.
    pub critical_effect: Option<EffectId>,
}

impl AutoAttackHitFeedback {
    /// The official normal-attack "no feedback" result (miss, self-hit, or a
    /// damage value that never reaches `AM_ATTACKED`).
    pub const NONE: Self = Self {
        sound: None,
        hit_effect: None,
        critical_effect: None,
    };
}

/// Decides the hit sound and hit effects of one auto-attack damage message.
///
/// `damage` is `false` for a miss (`damage == 0`, `GameObject.cpp:1768`):
/// the official client then shows the miss number and plays/spawns nothing.
/// `attacker == None` models an out-of-sight source (`attacker == nullptr` in
/// `GameObject.cpp:1750-1757`), which uses the enemy roll.
///
/// `roll` selects one of the four random wave variants (the official code uses
/// `std::rand() % 4`); the caller derives it deterministically per hit.
pub fn auto_attack_hit_feedback(
    attacker: Option<HitAttacker>,
    defender: HitDefender,
    is_critical: bool,
    damage: bool,
    roll: u8,
) -> AutoAttackHitFeedback {
    if !damage || attacker.is_some_and(|attacker| attacker.entity_id == defender.entity_id) {
        return AutoAttackHitFeedback::NONE;
    }

    let sound = if defender.is_player {
        // `IsPlayerJob(defender job)` -> `GetHitWaveName(defender job)`.
        Some(job_hit_wave(defender.job_id))
    } else {
        match attacker {
            // `attacker == nullptr` -> `GetWeaponHitWaveName(-1)`.
            None => Some(enemy_hit_wave(roll)),
            // Monsters/homunculi/mercenaries return `GetWeapon() == -1`.
            Some(attacker) if !attacker.is_player => Some(enemy_hit_wave(roll)),
            Some(attacker) => {
                let kind = weapon::profile(attacker.weapon).kind();
                if kind == WeaponKind::Fist && !is_taekwon_job(attacker.job_id) {
                    Some(fist_hit_wave(roll))
                } else {
                    Some(weapon_hit_wave(kind))
                }
            }
        }
    };

    // `effectId` (`RenderObject.cpp:3800-3822`): `EF_HIT1` (0) normally,
    // `EF_HITLINE7` (434) for the Taekwon/Star family, `EF_VIOLEN_HIT` (2420)
    // for Violen. The out-of-sight fallback (`attacker == None`) uses the
    // standard `EF_HIT1`.
    let hit_effect = match attacker {
        Some(attacker) if is_violen_job(attacker.job_id) => Some(EffectId::ViolenHit),
        Some(attacker) if is_hitline7_job(attacker.job_id) => Some(EffectId::Hitline7),
        _ => Some(EffectId::Hit1),
    };

    AutoAttackHitFeedback {
        sound,
        hit_effect,
        critical_effect: is_critical.then_some(EffectId::Hit2),
    }
}

