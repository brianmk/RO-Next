use std::sync::Arc;

use ragnarok_packets::{EntityId, TilePosition};
use ro_next_interface::element::StateElement;
use rust_state::RustState;

use crate::graphics::Texture;
use crate::world::MinimapData;

/// Convert a single tile step into a minimap arrow direction index.
///
/// Tile x grows to the right of the generated map image and tile y grows
/// downwards, so index 0 is up/north, 2 is right/east, 4 is down/south and 6
/// is left/west. Returns `None` if the delta is not a valid step.
pub fn direction_index_from_tile_delta(previous: TilePosition, next: TilePosition) -> Option<u8> {
    let delta_x = (next.x as isize - previous.x as isize).clamp(-1, 1);
    let delta_y = (next.y as isize - previous.y as isize).clamp(-1, 1);

    // The minimap texture is generated bottom-up and flipped vertically for
    // display, so a map step that increases tile y (south) is now drawn DOWN and
    // a step that decreases tile y is drawn UP. The arrow direction index is
    // therefore the vertical mirror of the raw tile delta: north<->south.
    match (delta_x, delta_y) {
        (0, -1) => Some(4),
        (1, -1) => Some(3),
        (1, 0) => Some(2),
        (1, 1) => Some(1),
        (0, 1) => Some(0),
        (-1, 1) => Some(7),
        (-1, 0) => Some(6),
        (-1, -1) => Some(5),
        _ => None,
    }
}

/// Which of the map windows is currently shown, used by the `M` key cycle
/// (minimap -> big map -> closed -> minimap ...).
#[derive(Default, Debug, Clone, Copy, PartialEq, Eq)]
pub enum MapWindowCycle {
    /// No map window is shown.
    #[default]
    Closed,
    /// The small minimap window is shown.
    Minimap,
    /// The big map window is shown.
    BigMap,
}

/// One server-placed minimap marker (`ZC_COMPASS`, 0x0144).
#[derive(Debug, Clone, Copy)]
pub struct MinimapMarker {
    pub entity_id: EntityId,
    pub position: TilePosition,
    /// Marker colour (`ColorRGBA` red/green/blue/alpha).
    pub color: [u8; 4],
    /// End tick for `DisplayFor15Seconds` markers, [`None`] for markers that
    /// stay until the map changes.
    pub expires_at: Option<u32>,
}

/// State backing the minimap window.
///
/// The actual minimap image is generated by the map loader (see
/// [`crate::loaders::map`]) and copied in here when a map finishes loading. The
/// player position is refreshed every frame.
#[derive(Default, RustState, StateElement)]
pub struct Minimap {
    /// The generated minimap texture of the current map.
    #[hidden_element]
    texture: Option<Arc<Texture>>,
    /// Name of the current map (without the file extension).
    map_name: String,
    /// Size of the minimap texture in pixels.
    width: u16,
    height: u16,
    /// Size of the map in GAT cells.
    cells_width: u16,
    cells_height: u16,
    /// Current tile of the player, used to place the marker.
    #[hidden_element]
    player_position: Option<TilePosition>,
    /// Direction the player is facing (0 = north, 1 = north-east, ..., 7 =
    /// north-west).
    player_direction: u8,
    /// Pre-rotated arrow textures for the eight directions, generated once at
    /// startup. Empty if the textures could not be created, in which case the
    /// marker falls back to a green square.
    #[hidden_element]
    marker_textures: Vec<Arc<Texture>>,
    /// Server-placed NPC/quest markers (`ZC_COMPASS`).
    #[hidden_element]
    markers: Vec<MinimapMarker>,
}

impl Minimap {
    /// Replace the currently displayed minimap with the one of a newly loaded
    /// map.
    pub fn set_map(&mut self, map_name: &str, minimap: &MinimapData) {
        self.map_name = map_name.to_owned();
        self.texture = Some(minimap.texture.clone());
        self.width = minimap.width;
        self.height = minimap.height;
        self.cells_width = minimap.cells_width;
        self.cells_height = minimap.cells_height;
        self.player_position = None;
        self.markers.clear();
    }

    /// Clear the minimap (e.g. when the map is unloaded or the client returns
    /// to the character selection).
    pub fn clear(&mut self) {
        self.texture = None;
        self.map_name.clear();
        self.width = 0;
        self.height = 0;
        self.cells_width = 0;
        self.cells_height = 0;
        self.player_position = None;
        self.markers.clear();
    }

    /// Update the marker position and facing direction. `None` hides the
    /// marker.
    pub fn set_player_position(&mut self, position: Option<TilePosition>, direction: u8) {
        self.player_position = position;
        self.player_direction = direction;
    }

    /// Add or replace a server-placed marker (same entity id updates in place).
    pub fn add_marker(&mut self, marker: MinimapMarker) {
        match self.markers.iter_mut().find(|existing| existing.entity_id == marker.entity_id) {
            Some(existing) => *existing = marker,
            None => self.markers.push(marker),
        }
    }

    pub fn remove_marker(&mut self, entity_id: EntityId) {
        self.markers.retain(|marker| marker.entity_id != entity_id);
    }

    /// Remove markers whose lifetime expired.
    pub fn prune_markers(&mut self, client_tick: u32) -> bool {
        let previous = self.markers.len();
        self.markers
            .retain(|marker| marker.expires_at.is_none_or(|expires_at| expires_at > client_tick));
        self.markers.len() != previous
    }

    /// Current arrow direction index of the player marker.
    pub fn get_player_direction(&self) -> u8 {
        self.player_direction
    }

    /// Set the pre-rotated marker textures (see
    /// [`crate::loaders::minimap_marker`]). The textures are only generated
    /// once at startup, so this survives map changes.
    pub fn set_marker_textures(&mut self, marker_textures: Vec<Arc<Texture>>) {
        self.marker_textures = marker_textures;
    }

    #[cfg(test)]
    /// Name of the currently displayed map (without the file extension).
    ///
    /// Used by `<NAVI>` links to decide whether the destination is on the
    /// current map and a marker can be placed right away.
    pub fn map_name(&self) -> &str {
        &self.map_name
    }
}
