/// English display name of `status_index`, [`None`] when there is no safe name.
pub(crate) fn status_effect_name(status_index: u16) -> Option<&'static str> {
    STATUS_EFFECT_NAMES
        .binary_search_by_key(&status_index, |(index, _)| *index)
        .ok()
        .map(|position| STATUS_EFFECT_NAMES[position].1)
}

#[cfg(test)]
mod tests {
    use super::{STATUS_EFFECT_NAMES, status_effect_name};

    #[test]
    fn the_table_is_sorted_and_unique() {
        assert!(STATUS_EFFECT_NAMES.windows(2).all(|window| window[0].0 < window[1].0));
    }

    #[test]
    fn every_name_is_a_clean_ascii_label() {
        for (status_index, name) in STATUS_EFFECT_NAMES {
            assert!(!name.trim().is_empty(), "status {status_index} has an empty name");
            assert!(name.is_ascii(), "status {status_index} name is not ASCII: {name:?}");
            assert!(name.chars().any(|character| character.is_ascii_alphabetic()));
            assert!(!name.contains('#'));
        }
    }

    #[test]
    fn known_statuses_are_named() {
        assert_eq!(status_effect_name(0), Some("Provoke"));
        assert_eq!(status_effect_name(2), Some("Two-Hand Quicken"));
        assert_eq!(status_effect_name(10), Some("Blessing"));
        assert_eq!(status_effect_name(875), Some("Stone Curse"));
        assert_eq!(status_effect_name(883), Some("Poison"));
        assert_eq!(status_effect_name(30_000), None);
    }
}
