//! Generated English display names for the client status effect indices.
//!
//! The buff bar renders a name for every active status effect. The indices are
//! the `EFST_*` ids that the map server sends in
//! `ZC_MSG_STATE_CHANGE3`/`ZC_EFST_SET_ENTER`; the names are the English titles
//! of the client's `stateiconinfo.lub` entries:
//!
//! * index map: rAthena `src/map/status.hpp` (`enum efst_type`) at `665fe2291`,
//!   the enum the 2019 map server uses to fill the packets (client
//!   `efstids.lub` uses the same ids apart from one enum entry that drifted
//!   between the data and server versions, which is why the server enum is the
//!   source of truth here),
//! * names: `data\luafiles514\lua files\stateicon\stateiconinfo.lub` from
//!   `CondaRO.grf` (`StateIconList[EFST_IDs.<name>].descript[1][1]`), matched
//!   to the server enum by the symbolic `EFST_*` name so a drifted numeric id
//!   can never pick the wrong name.
//!
//! Entries whose title is missing, a `%s` format placeholder, longer than 32
//! characters (those are description sentences, not names) or contains
//! Korean/other non-ASCII text are **not** listed: the caller falls back to the
//! generic `Status effect` name, so a status name can never turn into a square
//! glyph or a mojibake string.
//!
//! Regenerate with the read-only GRF reader of `tools/text_encoding_audit.py`
//! (see the workstream report) and the server enum; the table is sorted by
//! status index.

