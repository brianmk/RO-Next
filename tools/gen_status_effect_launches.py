#!/usr/bin/env python3
"""Generate the status/skill -> official effect launch table.

Input:
  * tools/data/status_effect_launches_facts.json (the official switches, see
    ./tools/extract_status_effect_launches.py),
  * tools/data/status_facts.json (the status ids must exist in the port's
    status table),
  * ro-next/src/world/effect/port/registry*.rs (every launched effect must be
    a ported body, i.e. `EffectId::<Variant>` must exist in the registry).

Output: ro-next/archive/data/client/status_effect_launches.ron

Usage:
    ./tools/gen_status_effect_launches.py
    ./tools/gen_status_effect_launches.py --check
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FACTS = REPO / "tools/data/status_effect_launches_facts.json"
STATUS_FACTS = REPO / "tools/data/status_facts.json"
PORT = REPO / "ro-next/src/world/effect/port"
OUTPUT = REPO / "ro-next/archive/data/client/status_effect_launches.ron"

#: Official launches whose visual the port already produces through another
#: system. The launch channel must not spawn them again: status 87/235 carry a
#: persistent `PersistentGlow` aura built from the same `super1..5.bmp` frames
#: the official `EF_STEELBODY` fan uses (`status_effects.ron` /
#: `tools/data/status_effect_custom.ron`).
ALREADY_REPRESENTED = {
    ("EFST_STEELBODY", "EF_STEELBODY"): "EF_STEELBODY (254) is already the status-87 persistent aura row of status_effects.ron",
    ("EFST_DBARRIER", "EF_STEELBODY"): "EF_STEELBODY (254) is already the status-235 persistent aura row of status_effects.ron",
}

HEADER = """// Status/skill -> official effect launches for RO-Next.
//
// Generated by `tools/gen_status_effect_launches.py`; do not edit by hand.
// Regenerate: `./tools/gen_status_effect_launches.py`
// Check:      `./tools/gen_status_effect_launches.py --check`
//
// `statuses` maps an `EFST_*` status id to the effects the official status
// path launches. The official mechanism has two halves that launch the same
// rows:
//   * `CGameActor::SendMsg`, `case AM_STATUS_CHANGE:` (`GameObject.cpp:2535-4398`)
//     launches the effect on every status change, and
//   * `CPlayer::ReapplySkillEffects` (`Player.cpp:3180-3850`) re-launches it
//     when the client rebuilds the actor (map entry, map property change),
//     i.e. when the status list is re-sent.
// Every (re-)application therefore spawns the row again: `relaunch: true` when
// the official case first deletes the previous instance
// (`while (this->HasId(EF_...))`, `GameObject.cpp:2686-2688`) and launches a
// fresh one; `relaunch: false` for the guarded `if (!HasId(...))` rows that
// keep the running instance.
//
// `skills` maps a skill id to the effects `CGameMode::ApplyActorSkillState`
// (`GameModePackets.cpp:12868-12897`) launches when a cast starts. The function
// is called from `CGameMode::NotifySkillCasting` at `GameModePackets.cpp:12968`,
// after `SetState` and the monster action, and only for casts with
// `delay != 0` (the `delay == 0` early return is `:12940-12942`).
//
// Every effect id is the official `RagEffectID` numeric value and must be a
// ported body (`world/effect/port/registry*.rs`); the spawn path builds a
// `PortedEffectHolder` through `PortedVisual`. The `source` line of a row names
// the exact decompiled lines and the official effect names.
(
    provenance: "Official status/skill effect launches: CGameActor::SendMsg case AM_STATUS_CHANGE and CPlayer::ReapplySkillEffects (rodecomp GameObject.cpp/Player.cpp) plus CGameMode::ApplyActorSkillState (GameModePackets.cpp)",
    version: 1,
    statuses: [
"""

FOOTER = """    ],
    skills: [
"""


def rust_variant(effect: str) -> str:
    """`EF_SU_STOOP` -> `SuStoop`, the `EffectId` variant name."""
    return "".join(part.capitalize() for part in effect.split("_")[1:])


def ported_variants() -> set[str]:
    variants: set[str] = set()
    for path in sorted(PORT.glob("registry*.rs")):
        variants.update(re.findall(r"EffectId::([A-Za-z0-9_]+)", path.read_text(encoding="utf-8")))
    if not variants:
        raise SystemExit(f"no EffectId variants found under {PORT}")
    return variants


def escaped(source: str) -> str:
    return source.replace("\\", "\\\\").replace('"', '\\"')


def render() -> str:
    if not FACTS.exists():
        raise SystemExit(f"missing facts file: {FACTS}; run ./tools/extract_status_effect_launches.py")

    facts = json.loads(FACTS.read_text(encoding="utf-8"))
    known_statuses = {int(row["id"]) for row in json.loads(STATUS_FACTS.read_text(encoding="utf-8"))["statuses"]}
    ported = ported_variants()

    def check_effect(name: str, effect_id: int) -> str:
        variant = rust_variant(name)
        if variant not in ported:
            raise SystemExit(f"{name} ({effect_id}) is not ported: no EffectId::{variant} in the registry")
        return variant

    lines = [HEADER]
    status_rows = 0
    for status in facts["statuses"]:
        status_name = status["status"]
        status_id = int(status["status_id"])
        if status_id not in known_statuses:
            raise SystemExit(f"{status_name}: status id {status_id} has no row in the status table")

        applied = []
        for effect in status["effects"]:
            variant = check_effect(effect["effect"], int(effect["effect_id"]))
            exclusion = ALREADY_REPRESENTED.get((status_name, effect["effect"]))
            if exclusion is None:
                applied.append(effect)
            else:
                lines.append(
                    f"        // {status_name}: {effect['effect']} ({effect['effect_id']}, EffectId::{variant}) is not "
                    f"launched here - {exclusion}.\n"
                )

        if not applied:
            raise SystemExit(f"{status_name}: every official launch is already represented; remove the trigger")

        effects = ", ".join(str(int(effect["effect_id"])) for effect in applied)
        apply_line = applied[0]["apply_line"]
        apply_range = status["apply_range"]
        reapply_lines = sorted({line for effect in applied for line in effect["reapply_lines"]})
        reapply = ", ".join(f"Player.cpp:{line}" for line in reapply_lines)
        names = " + ".join(effect["effect"] for effect in applied)
        relaunch = "true" if status["deletes_before_launch"] else "false"
        relaunch_note = (
            "the official case deletes the previous instance and launches again"
            if status["deletes_before_launch"]
            else "the official case only launches when the effect is absent"
        )
        source = (
            f"official AM_STATUS_CHANGE {status_name} -> {names} "
            f"(GameObject.cpp:{apply_range[0]}-{apply_range[1]}, LaunchEffect at :{apply_line}); "
            f"re-applied by CPlayer::ReapplySkillEffects ({reapply}); {relaunch_note}"
        )
        lines.append(
            f"        // {status_name} ({status_id}) -> {names}: {relaunch_note}.\n"
            "        (\n"
            f"            id: {status_id},\n"
            f"            effects: [{effects}],\n"
            f"            relaunch: {relaunch},\n"
            f'            source: "{escaped(source)}",\n'
            "        ),\n"
        )
        status_rows += 1

    lines.append(FOOTER)
    skill_rows = 0
    for skill in facts["skills"]:
        skill_name = skill["skill"]
        skill_id = int(skill["skill_id"])
        check_effect(skill["effect"], int(skill["effect_id"]))
        source = (
            f"official CGameMode::ApplyActorSkillState {skill_name} -> {skill['effect']} "
            f"(GameModePackets.cpp:{skill['line']}, reached from CGameMode::NotifySkillCasting :12968 for delay != 0)"
        )
        lines.append(
            f"        // {skill_name} ({skill_id}) -> {skill['effect']} ({skill['effect_id']}) on cast start.\n"
            "        (\n"
            f"            id: {skill_id},\n"
            f"            effects: [{int(skill['effect_id'])}],\n"
            f'            source: "{escaped(source)}",\n'
            "        ),\n"
        )
        skill_rows += 1
    lines.append("    ],\n)\n")

    print(f"rows: {status_rows} statuses, {skill_rows} skills", file=sys.stderr)
    return "".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    rendered = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != rendered:
            print(f"{OUTPUT} is out of date; run ./tools/gen_status_effect_launches.py", file=sys.stderr)
            raise SystemExit(1)
        print(f"{OUTPUT} is up to date")
        return

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
