#!/usr/bin/env python3
"""Render the rodecomp-derived skill-effect overlay data file.

Input : `tools/rodecomp_skill_facts.json` (committed facts extracted from the
        official client decompilation `github.com/rodecomp/rodecomp`; see
        `notes/rodecomp-skill-status-aura-audit.md` for the method).
Output: `tools/skill_effects_rodecomp.ron`, merged by `tools/gen_skill_effects.py`
        after the official rows (a row replaces the descriptor of its
        (skill, phase) pair).

The rows exist for skills whose effect the previous data pipeline could not
resolve: the official client plays them from hard-coded C++ (no data asset layer
the EffectTable extractor could see). Only skills where the decompiled C++
switch and the 2019-era effect table agree on the effect id are included.

Usage:
    ./tools/gen_rodecomp_overlay.py            # regenerate the data file
    ./tools/gen_rodecomp_overlay.py --check    # fail if out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_FACTS = REPO / "tools/rodecomp_skill_facts.json"
DEFAULT_OUTPUT = REPO / "tools/skill_effects_rodecomp.ron"

ENUM_FIELDS = {"anchor", "blend", "kind", "phase"}
FLOAT_FIELDS = {
    "scale",
    "size",
    "size_end",
    "spread",
    "height",
    "bottom_radius",
    "top_radius",
    "rotation_speed",
    "alpha",
    "light_intensity",
    "offset",
    "tint",
}


def num(value: float) -> str:
    text = f"{float(value):.4f}".rstrip("0")
    if text.endswith("."):
        text += "0"
    return text


def ron_value(key: str, value: object) -> str:
    if isinstance(value, str):
        if key in ENUM_FIELDS:
            return value
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (tuple, list)):
        return "(" + ", ".join(ron_value("", item) for item in value) + ")" if key == "tint" else "[" + ", ".join(ron_value("", item) for item in value) + "]"
    if isinstance(value, float):
        return num(value)
    return str(value)


def write_layer(layer: dict) -> str:
    parts = [f"kind: {layer['kind']}"]
    for key in (
        "anchor",
        "attached_entity",
        "head",
        "vertical",
        "file",
        "files",
        "frames",
        "frame_ms",
        "primitive",
        "offset",
        "scale",
        "size",
        "size_end",
        "duration_ms",
        "delay_ms",
        "hold_ms",
        "fade_ms",
        "count",
        "spread",
        "height",
        "bottom_radius",
        "top_radius",
        "rotation_speed",
        "grow",
        "alpha",
        "tint",
        "blend",
        "wav",
        "light",
        "light_intensity",
    ):
        if key not in layer or layer[key] is None:
            continue
        value = layer[key]
        if key in ("size", "size_end", "scale", "spread", "height", "bottom_radius", "top_radius", "rotation_speed", "alpha", "light_intensity") and isinstance(value, (int, float)):
            parts.append(f"{key}: {num(value)}")
        elif key == "offset" and isinstance(value, (list, tuple)):
            parts.append("offset: (" + ", ".join(num(item) for item in value) + ")")
        elif key == "tint" and isinstance(value, (list, tuple)):
            parts.append("tint: (" + ", ".join(num(item) for item in value) + ")")
        else:
            parts.append(f"{key}: {ron_value(key, value)}")
    return "(" + ", ".join(parts) + ")"


def render(facts: dict) -> str:
    skills = sorted(facts["skills"], key=lambda entry: int(entry["skill"]))
    counts = len(skills), sum(len(entry["layers"]) for entry in skills)
    lines = [
        "// Skill effect rows derived from the official client decompilation (rodecomp).",
        "//",
        "// Generated by `tools/gen_rodecomp_overlay.py` from `tools/rodecomp_skill_facts.json`;",
        "// do not edit by hand. Regenerate with: `./tools/gen_rodecomp_overlay.py`",
        "// Drift check: `./tools/gen_rodecomp_overlay.py --check`",
        "//",
        "// Rows either add a descriptor for a skill whose effect the official client plays from",
        "// (`CGameMode::ReceiveSkillUse` / `CSession::PlaySkillEffect`), with assets taken",
        "// from the effect implementation (`CRagEffect::*` primitives). Only skills where",
        "// the decompiled code and the 2019-era effect table agree on the effect id are",
        "// included. See `notes/rodecomp-skill-status-aura-audit.md`.",
        f"// {counts[0]} skills, {counts[1]} layers.",
        "(",
        '    provenance: "rodecomp-derived rows for official hard-coded skill effects",',
        "    effects: [",
    ]
    phase_order = {"Ground": 0, "Cast": 1, "Success": 2, "Release": 3, "Hit": 4, "Caster": 5}
    for entry in skills:
        grouped: dict[str, list[dict]] = {}
        for layer in entry["layers"]:
            phase = layer.get("phase", "Success")
            grouped.setdefault(phase, []).append({key: value for key, value in layer.items() if key != "phase"})
        mode = entry.get("mode", "new")
        lines.append(
            f"        // skill {entry['skill']} {entry['name']}: official effect {entry['effect_ids']}"
            + (" - appended official layers" if mode == "append" else "")
        )
        for phase in sorted(grouped, key=lambda name: phase_order.get(name, 99)):
            lines.append(f"        (skill: {entry['skill']}, phase: {phase}, layers: [")
            for layer in grouped[phase]:
                lines.append("            " + write_layer(layer) + ",")
            lines.append("        ]),")
    lines += ["    ],", ")", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--facts", default=str(DEFAULT_FACTS))
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    facts_path = Path(args.facts)
    if not facts_path.is_file():
        raise SystemExit(f"missing facts file: {facts_path}")
    facts = json.loads(facts_path.read_text(encoding="utf-8"))
    content = render(facts)
    output = Path(args.output)
    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else ""
        if current != content:
            print(f"{output} is out of date (run ./tools/gen_rodecomp_overlay.py)", file=sys.stderr)
            return 1
        print(f"{output} is up to date ({len(facts['skills'])} skills)")
        return 0
    output.write_text(content, encoding="utf-8")
    print(f"wrote {output} ({len(facts['skills'])} skills, {sum(len(entry['layers']) for entry in facts['skills'])} layers)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
