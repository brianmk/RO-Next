_GRF_CACHE: dict[str, Grf] = {}


def archive_chain(game_dir: Path | None, archive_dir: Path | None) -> list[tuple[str, Path]]:
    """Client file sources, highest priority first.

    Mirrors `GameFileLoader::add_archive`: a loose `archive/` folder overrides
    every GRF, then `palettes.grf`, `CondaRO.grf` and `data.grf`.
    """
    chain: list[tuple[str, Path]] = []
    if archive_dir and archive_dir.is_dir():
        chain.append(("archive/", archive_dir))
    for name in ("palettes.grf", "CondaRO.grf", "data.grf"):
        path = game_dir / name if game_dir else None
        if path and path.is_file():
            chain.append((name, path))
    return chain


def grf_key(path: str) -> str:
    """Convert a Unicode client path to the raw-byte key the GRF table uses.

    The 2019 GRFs store localized file names as EUC-KR bytes; the read-only
    GRF reader keeps them as latin-1 strings. ASCII paths are unchanged.
    """
    out: list[str] = []
    for character in path:
        if ord(character) < 0x80:
            out.append(character)
            continue
        try:
            out.append(character.encode("euc-kr").decode("latin-1"))
        except (UnicodeEncodeError, UnicodeDecodeError):
            out.append(character)
    return "".join(out).lower()


def client_file(chain: list[tuple[str, Path]], path: str) -> tuple[str, bytes] | tuple[None, None]:
    """Read `path` from the first archive that contains it."""
    for name, location in chain:
        if location.is_dir():
            candidate = location.joinpath(*path.replace("\\", "/").split("/"))
            if candidate.is_file():
                return name, candidate.read_bytes()
            continue
        grf = _GRF_CACHE.get(str(location))
        if grf is None:
            grf = Grf(str(location))
            _GRF_CACHE[str(location)] = grf
        if not grf.contains(grf_key(path)):
            continue
        return name, grf.read(grf_key(path))
    return None, None


def client_file_exists(chain: list[tuple[str, Path]], path: str) -> bool:
    for name, location in chain:
        if location.is_dir():
            candidate = location.joinpath(*path.replace("\\", "/").split("/"))
            if candidate.is_file():
                return True
            continue
        grf = _GRF_CACHE.get(str(location))
        if grf is None:
            grf = Grf(str(location))
            _GRF_CACHE[str(location)] = grf
        if grf.contains(grf_key(path)):
            return True
    return False


