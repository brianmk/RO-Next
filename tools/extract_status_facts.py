def decode_js_byte_string(literal: str) -> str:
    """Decode a roBrowser JS string of escaped EUC-KR bytes into Unicode."""
    try:
        raw = literal.encode("utf-8").decode("unicode_escape").encode("latin-1")
    except (UnicodeDecodeError, UnicodeEncodeError):
        return literal
    try:
        return raw.decode("euc-kr")
    except UnicodeDecodeError:
        return raw.decode("latin-1")


def vendor_robrowser(status_info_js: str, status_const_js: str) -> dict[str, object]:
    """Extract the facts of roBrowserLegacy's `StatusInfo.js` / `StatusConst.js`.

    Only facts are extracted (numeric ids, symbolic names, icon file names,
    English titles, title colours); no JavaScript code is copied.
    """
    constants = {match.group(1): int(match.group(2)) for match in re.finditer(r"(\w+):\s*(-?\d+)\s*,", status_const_js)}
    entries: list[dict[str, object]] = []
    for block in re.finditer(r"StatusInfo\[SC\.(\w+)\]\s*=\s*\{(.*?)\n\};", status_info_js, re.S):
        symbol, body = block.group(1), block.group(2)
        icon_match = re.search(r"icon:\s*'((?:[^'\\]|\\.)*)'", body)
        icon = decode_js_byte_string(icon_match.group(1)) if icon_match else None
        title = None
        category = None
        description: list[str] = []
        # The `descript` array may be written on one line, so scan the whole
        # block for its bracket-delimited string entries.
        for entry in _JS_ENTRY.findall(body):
            value = decode_js_byte_string(entry[0])
            colour = entry[1]
            if title is None:
                title = value
                category = _CATEGORY_BY_COLOUR.get(colour) if colour else None
                continue
            if value.startswith("%s"):
                continue
            description.append(value)
        entries.append(
            {
                "sc": symbol,
                "sc_id": constants.get(symbol),
                "icon": icon,
                "name": title,
                "category": category,
                "description": description,
            }
        )
    if not entries:
        raise ExtractError("roBrowser StatusInfo.js contained no StatusInfo entries")
    entries.sort(key=lambda entry: (entry["sc_id"] if entry["sc_id"] is not None else 1 << 30, entry["sc"]))
    return {
        "provenance": {
            "source": "roBrowserLegacy src/DB/Status/StatusInfo.js + src/DB/Status/StatusConst.js (GPL-3.0 reverse-engineering of the official client's hard-coded classic status table); only facts are vendored",
            "url": "https://github.com/MrAntares/roBrowserLegacy",
            "commit": None,
            "files": {
                "StatusInfo.js": {"sha256": sha256_bytes(status_info_js.encode("utf-8")), "bytes": len(status_info_js.encode("utf-8"))},
                "StatusConst.js": {"sha256": sha256_bytes(status_const_js.encode("utf-8")), "bytes": len(status_const_js.encode("utf-8"))},
            },
        },
        "entries": entries,
    }


