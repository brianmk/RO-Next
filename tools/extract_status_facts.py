class ExtractError(RuntimeError):
    """A source file did not have the expected shape."""


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def normalize_symbol(value: str) -> str:
    """Uppercase identifier without separators, for symbol matching.

    The server enum (`EFST_INC_AGI`), the rAthena status database
    (`Inc_Agi`) and the reverse-engineered client table (`SC.INC_AGI`) spell
    the same status slightly differently; dropping separators gives one
    comparable key without touching the status names.
    """
    return re.sub(r"[^A-Z0-9]", "", value.upper())


def decode_lub_string(value: str) -> str:
    """Decode a Lua string that was read from the GRF as latin-1.

    The 2019 Lua sources are a mix of ASCII and EUC-KR byte strings; reading
    the file as latin-1 keeps every byte and this function turns the byte
    sequence into a real Unicode string (filename or Korean title). ASCII
    passes through unchanged.
    """
    try:
        return value.encode("latin-1").decode("euc-kr")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return value


def safe_status_name(name: str | None) -> bool:
    """Whether a client title is a usable one-line English status name.

    This mirrors the filter of the table this lane replaces: titles that are
    format placeholders, description sentences (longer than 32 characters),
    Korean-only strings or otherwise not plain ASCII would render as square
    glyphs or wrap badly in the buff bar, so those statuses keep the generic
    fallback name instead.
    """
    if not name:
        return False
    name = name.strip()
    if not name or len(name) > 32:
        return False
    if not name.isascii():
        return False
    # A bare `%s`/`%d` is a format placeholder, not a name; a percent sign
    # inside a real title ("Weight over 50%") is fine.
    if re.search(r"%[a-zA-Z]", name) or "#" in name:
        return False
    return any(character.isalpha() for character in name)


