def render_json(document: dict[str, object]) -> str:
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the committed facts file is out of date")
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT), help="facts JSON output path")
    parser.add_argument("--custom", default=str(DEFAULT_CUSTOM), help="curated overlay (names/icons/value labels/auras)")
    parser.add_argument("--robrowser-facts", default=str(DEFAULT_ROBROWSER), help="vendored roBrowserLegacy status facts")
    parser.add_argument("--robrowser-commit", default=None, help="upstream commit recorded in the facts provenance")
    parser.add_argument("--server-root", default=str(DEFAULT_SERVER_ROOT), help="rAthena tree with src/map and db/pre-re")
    parser.add_argument("--game-dir", default=str(DEFAULT_GAME_DIR), help="client directory with the GRF archives")
    parser.add_argument("--archive-dir", default=str(DEFAULT_ARCHIVE_DIR), help="loose client archive folder (highest priority)")
    parser.add_argument("--lub-dir", default=None, help="read the three .lub files from this directory instead of the GRFs")
    parser.add_argument("--vendor-robrowser", nargs=2, metavar=("STATUSINFO_JS", "STATUSCONST_JS"), help="extract the vendored roBrowser facts and exit")
    parser.add_argument("--write-robrowser-facts", default=str(DEFAULT_ROBROWSER), help="output path of --vendor-robrowser")
    args = parser.parse_args()

    if args.vendor_robrowser:
        status_info_path = Path(args.vendor_robrowser[0])
        status_const_path = Path(args.vendor_robrowser[1])
        status_info = status_info_path.read_text(encoding="utf-8")
        status_const = status_const_path.read_text(encoding="utf-8")
        document = vendor_robrowser(status_info, status_const)
        provenance = document["provenance"]
        assert isinstance(provenance, dict)
        provenance["commit"] = args.robrowser_commit
        provenance["url"] = "https://github.com/MrAntares/roBrowserLegacy"
        # Hash the exact bytes that were vendored (not the re-encoded text).
        provenance["files"] = {
            path.name: {"sha256": sha256_file(path), "bytes": path.stat().st_size}
            for path in (status_info_path, status_const_path)
        }
        output = Path(args.write_robrowser_facts)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(render_json(document), encoding="utf-8")
        entries = document["entries"]
        assert isinstance(entries, list)
        print(f"{output}: {len(entries)} roBrowser status entries")
        return 0

    facts = extract_status_facts(
        server_root=Path(args.server_root),
        game_dir=Path(args.game_dir) if args.game_dir else None,
        archive_dir=Path(args.archive_dir) if args.archive_dir else None,
        lub_dir=Path(args.lub_dir) if args.lub_dir else None,
        robrowser_facts_path=Path(args.robrowser_facts),
        custom_path=Path(args.custom),
        robrowser_commit=args.robrowser_commit,
    )
    content = render_json(facts)
    output = Path(args.output)
    statuses = facts["statuses"]
    assert isinstance(statuses, list)

    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else ""
        if current != content:
            print(f"error: {output} is out of date; run ./tools/extract_status_facts.py", file=sys.stderr)
            return 1
        print(f"{output} is up to date ({len(statuses)} statuses)")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"{output}: {len(statuses)} statuses")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
