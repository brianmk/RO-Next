M64 = 0xFFFFFFFFFFFFFFFF


def _feistel(right, key):
    expanded = _expand(right)
    xored = expanded ^ key
    return _pbox_permute(_sbox_substitute(xored))


def _sbox_substitute(value):
    out = 0
    for index, sbox in enumerate(S_BOXES):
        out |= sbox[(value >> (58 - index * 6)) & 0x3F] << (60 - index * 4)
    return out & M64


def _delta_swap(a, delta, mask):
    b = (a ^ (a >> delta)) & mask
    return (a ^ b ^ (b << delta)) & M64


def _fp(message):
    message = _delta_swap(message, 24, 0x000000FF000000FF)
    message = _delta_swap(message, 24, 0x00000000FF00FF00)
    message = _delta_swap(message, 36, 0x000000000F0F0F0F)
    message = _delta_swap(message, 18, 0x0000333300003333)
    return _delta_swap(message, 9, 0x0055005500550055)


def _ip(message):
    message = _delta_swap(message, 9, 0x0055005500550055)
    message = _delta_swap(message, 18, 0x0000333300003333)
    message = _delta_swap(message, 36, 0x000000000F0F0F0F)
    message = _delta_swap(message, 24, 0x00000000FF00FF00)
    return _delta_swap(message, 24, 0x000000FF000000FF)


def _expand(block):
    b1 = (block << 31) & 0x8000000000000000
    b2 = (block >> 1) & 0x7C00000000000000
    b3 = (block >> 3) & 0x03F0000000000000
    b4 = (block >> 5) & 0x000FC00000000000
    b5 = (block >> 7) & 0x00003F0000000000
    b6 = (block >> 9) & 0x000000FC00000000
    b7 = (block >> 11) & 0x00000003F0000000
    b8 = (block >> 13) & 0x000000000FC00000
    b9 = (block >> 15) & 0x00000000003E0000
    b10 = (block >> 47) & 0x0000000000010000
    return b1 | b2 | b3 | b4 | b5 | b6 | b7 | b8 | b9 | b10


def _pbox_permute(block):
    block = ((block << 44) | (block >> 20)) & M64
    b1 = (block & 0x0000000000200000) << 32
    b2 = (block & 0x0000000000480000) << 13
    b3 = (block & 0x0000088000000000) << 12
    b4 = (block & 0x0000002020120000) << 25
    b5 = (block & 0x0000000442000000) << 14
    b6 = (block & 0x0000000001800000) << 37
    b7 = (block & 0x0000000004000000) << 24
    b8 = ((block & 0x0000020280015000) * 0x0000020080800083) & M64 & 0x02000A6400000000
    b9 = ((((block << 29) | (block >> 35)) & M64) & 0x01001400000000AA) * 0x0000210210008081 & M64 & 0x0902C01200000000
    b10 = ((block & 0x0000000910040000) * 0x0000000C04000020) & M64 & 0x8410010000000000
    return (b1 | b2 | b3 | b4 | b5 | b6 | b7 | b8 | b9 | b10) & M64


def decode_des_block(block):
    block = _ip(block)
    block = _round(block, 0)
    block = ((block << 32) | (block >> 32)) & M64
    return _fp(block)


def _round(value, key):
    left = value & (0xFFFFFFFF << 32)
    right = (value << 32) & M64
    return (right | ((_feistel(right, key) ^ left) >> 32)) & M64


_SHUFFLE = [3, 4, 6, 0, 1, 2, 5]
_FLIP = {
    0x00: 0x2B, 0x2B: 0x00, 0x01: 0x68, 0x68: 0x01,
    0x48: 0x77, 0x77: 0x48, 0x60: 0xFF, 0xFF: 0x60,
    0x6C: 0x80, 0x80: 0x6C, 0xB9: 0xC0, 0xC0: 0xB9,
    0xEB: 0xFE, 0xFE: 0xEB,
}


def _scramble(block):
    copy = bytes(block)
    for index, position in enumerate(_SHUFFLE):
        block[index] = copy[position]
    block[7] = _FLIP.get(copy[7], copy[7])


def _decrypt_blocks(data, only_header, cycle):
    non_des = 0
    for number, start in enumerate(range(0, len(data), 8)):
        block = data[start:start + 8]
        if number < 0x14 or (not only_header and cycle and number % cycle == 0):
            value = decode_des_block(int.from_bytes(bytes(block), "big"))
            data[start:start + 8] = value.to_bytes(8, "big")
        elif not only_header:
            if non_des == 7:
                _scramble(block)
                data[start:start + 8] = block
                non_des = 0
            non_des += 1


def decrypt_grf_file(flags, compressed_size, data):
    if flags & 0x02:
        digits = len(str(compressed_size)) if compressed_size else 1
        cycle = 3 if digits < 3 else digits + 1 if digits < 5 else digits + 9 if digits < 7 else digits + 15
        only_header = False
    elif flags & 0x04:
        only_header, cycle = True, 0
    else:
        return data
    data = bytearray(data)
    if len(data) % 8 == 0:
        _decrypt_blocks(data, only_header, cycle)
    else:
        full = (len(data) // 8) * 8
        if full:
            head = bytearray(data[:full])
            _decrypt_blocks(head, only_header, cycle)
            data[:full] = head
        tail = bytearray(8)
        tail[: len(data) - full] = data[full:]
        _decrypt_blocks(tail, only_header, cycle)
        data[full:] = tail[: len(data) - full]
    return bytes(data)


class Grf:
    def __init__(self, path):
        self.path = path
        self.entries = {}
        with open(path, "rb") as handle:
            header = handle.read(GRF_HEADER_SIZE)
            if not header.startswith(b"Master of Magic"):
                raise SystemExit(f"not a GRF file: {path}")
            table_offset, reserved, file_count, version = struct.unpack("<IIII", header[30:46])
            if version != 0x200:
                raise SystemExit(f"unsupported GRF version {version:#x}: {path}")
            handle.seek(GRF_HEADER_SIZE + table_offset)
            compressed_size, _uncompressed_size = struct.unpack("<II", handle.read(8))
            table = zlib.decompress(handle.read(compressed_size))
        offset = 0
        for _ in range(file_count - reserved - 7):
            end = table.index(b"\0", offset)
            name = table[offset:end].decode("latin-1").lower()
            offset = end + 1
            comp, aligned, uncomp, flags, entry_offset = struct.unpack("<IIIBI", table[offset:offset + 17])
            offset += 17
            self.entries[name] = (comp, aligned, uncomp, flags, entry_offset)

    def contains(self, name):
        return name.lower() in self.entries

    def read(self, name):
        comp, aligned, _uncomp, flags, offset = self.entries[name.lower()]
        with open(self.path, "rb") as handle:
            handle.seek(GRF_HEADER_SIZE + offset)
            data = handle.read(aligned)
        return zlib.decompress(decrypt_grf_file(flags, comp, data))


class RonError(ValueError):
    pass


def strip_comments(text: str) -> str:
    out: list[str] = []
    index = 0
    in_string = False
    while index < len(text):
        character = text[index]
        if in_string:
            out.append(character)
            if character == "\\" and index + 1 < len(text):
                out.append(text[index + 1])
                index += 2
                continue
            if character == '"':
                in_string = False
            index += 1
            continue

        if character == '"':
            in_string = True
            out.append(character)
            index += 1
            continue

        if character == "/" and index + 1 < len(text) and text[index + 1] == "/":
            while index < len(text) and text[index] != "\n":
                index += 1
            continue

        out.append(character)
        index += 1

    return "".join(out)


class RonReader:
    def __init__(self, text: str) -> None:
        self.text = strip_comments(text)
        self.index = 0

    def error(self, message: str) -> RonError:
        line = self.text.count("\n", 0, self.index) + 1
        return RonError(f"line {line}: {message}")

    def skip_whitespace(self) -> None:
        while self.index < len(self.text) and self.text[self.index].isspace():
            self.index += 1

    def peek(self) -> str:
        self.skip_whitespace()
        if self.index >= len(self.text):
            raise self.error("unexpected end of file")
        return self.text[self.index]

    def expect(self, character: str) -> None:
        if self.peek() != character:
            raise self.error(f"expected {character!r}, got {self.text[self.index]!r}")
        self.index += 1

    def read_identifier(self) -> str:
        self.skip_whitespace()
        start = self.index
        while self.index < len(self.text) and (self.text[self.index].isalnum() or self.text[self.index] in "_-"):
            self.index += 1
        if start == self.index:
            raise self.error("expected an identifier")
        return self.text[start : self.index]

    def read_string(self) -> str:
        self.expect('"')
        value: list[str] = []
        while True:
            if self.index >= len(self.text):
                raise self.error("unterminated string")
            character = self.text[self.index]
            self.index += 1
            if character == '"':
                return "".join(value)
            if character == "\\":
                if self.index >= len(self.text):
                    raise self.error("unterminated escape")
                escaped = self.text[self.index]
                self.index += 1
                mapping = {"n": "\n", "t": "\t", "r": "\r", "0": "\0"}
                value.append(mapping.get(escaped, escaped))
                continue
            value.append(character)

    def read_bare(self) -> object:
        self.skip_whitespace()
        start = self.index
        while self.index < len(self.text) and self.text[self.index] not in ",)] \t\r\n":
            self.index += 1
        token = self.text[start : self.index]
        if token == "true":
            return True
        if token == "false":
            return False
        if re.fullmatch(r"-?\d+", token):
            return int(token)
        if re.fullmatch(r"-?(\d+\.\d*|\.\d+|\d+)([eE][-+]?\d+)?", token):
            return float(token)
        return token

    def read_paren(self) -> object:
        """Read a map or a tuple, whichever starts after the opening paren.

        The data files use tuples for vectors/colors (`(0.0, 12.0, 0.0)`) and
        maps for records (`(skill: 1, variant: Hit, ...)`); both share the `(`
        delimiter, so a short lookahead decides which one it is.
        """
        self.expect("(")
        self.skip_whitespace()
        start = self.index
        is_map = False
        if self.index < len(self.text) and (self.text[self.index].isalpha() or self.text[self.index] == "_"):
            while self.index < len(self.text) and (self.text[self.index].isalnum() or self.text[self.index] in "_-"):
                self.index += 1
            while self.index < len(self.text) and self.text[self.index].isspace():
                self.index += 1
            is_map = self.index < len(self.text) and self.text[self.index] == ":"
        self.index = start

        if not is_map:
            values: list[object] = []
            while True:
                if self.peek() == ")":
                    self.index += 1
                    return tuple(values)
                values.append(self.read_value())
                if self.peek() == ",":
                    self.index += 1
                    continue
                if self.peek() == ")":
                    self.index += 1
                    return tuple(values)
                raise self.error("expected ',' or ')' in tuple")

        result: dict[str, object] = {}
        while True:
            if self.peek() == ")":
                self.index += 1
                return result
            key = self.read_identifier()
            self.expect(":")
            result[key] = self.read_value()
            if self.peek() == ",":
                self.index += 1
                continue
            if self.peek() == ")":
                self.index += 1
                return result
            raise self.error("expected ',' or ')' in map")

    def read_value(self) -> object:
        character = self.peek()
        if character == "(":
            return self.read_paren()
        if character == "[":
            return self.read_list()
        if character == '"':
            return self.read_string()
        return self.read_bare()

    def read_list(self) -> list[object]:
        self.expect("[")
        result: list[object] = []
        while True:
            if self.peek() == "]":
                self.index += 1
                return result
            result.append(self.read_value())
            if self.peek() == ",":
                self.index += 1
                continue
            if self.peek() == "]":
                self.index += 1
                return result
            raise self.error("expected ',' or ']' in list")


def read_ron(path: Path) -> dict[str, object]:
    return RonReader(path.read_text(encoding="utf-8")).read_paren()  # type: ignore[return-value]



