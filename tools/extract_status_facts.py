_VALUE_FORMATS = ("Element", "Percent", "Number", "Id")
_AURA_KINDS = ("PersistentGlow",)


def _number(value: object, context: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ExtractError(f"{context}: expected a number, got {value!r}")
    return float(value)


def _string(value: object, context: str) -> str:
    if not isinstance(value, str) or not value:
        raise ExtractError(f"{context}: expected a non-empty string, got {value!r}")
    return value


def _colour(value: object, context: str) -> list[float]:
    if not isinstance(value, tuple) or len(value) != 3:
        raise ExtractError(f"{context}: expected an (r, g, b) tuple, got {value!r}")
    return [_number(component, context) for component in value]


def read_custom_overlay(path: Path) -> dict[str, object]:
    """Read the curated overlay and normalise it for the facts document."""
    document = read_ron(path)
    if not isinstance(document, dict):
        raise ExtractError(f"{path}: the overlay must be a map")

    names: dict[int, str] = {}
    for entry in document.get("names", []):
        assert isinstance(entry, dict)
        status_id = int(entry["id"])
        names[status_id] = _string(entry["name"], f"custom name {status_id}")

    icons: dict[int, str] = {}
    for entry in document.get("icons", []):
        assert isinstance(entry, dict)
        status_id = int(entry["id"])
        icon = _string(entry["icon"], f"custom icon {status_id}")
        if not icon.lower().endswith(".tga"):
            raise ExtractError(f"custom icon {status_id}: status icons must be .tga files, got {icon!r}")
        icons[status_id] = icon

    categories: dict[int, dict[str, str]] = {}
    for entry in document.get("categories", []):
        assert isinstance(entry, dict)
        status_id = int(entry["id"])
        category = entry.get("category")
        if category not in ("Buff", "Debuff", "Toggle", "System"):
            raise ExtractError(f"custom category {status_id}: unknown category {category!r}")
        categories[status_id] = {"category": str(category), "source": _string(entry.get("source"), f"custom category {status_id}")}

    value_labels: dict[int, list[dict[str, object]]] = {}
    for entry in document.get("value_labels", []):
        assert isinstance(entry, dict)
        status_id = int(entry["id"])
        labels: list[dict[str, object]] = []
        for label in entry.get("labels", []):
            assert isinstance(label, dict)
            slot = int(label["slot"])
            if slot not in (1, 2, 3):
                raise ExtractError(f"custom value label {status_id}: slot {slot} is outside 1..3")
            fmt = label.get("format")
            if fmt not in _VALUE_FORMATS:
                raise ExtractError(f"custom value label {status_id}: unknown format {fmt!r}")
            labels.append({"slot": slot, "label": _string(label["label"], f"custom value label {status_id}"), "format": fmt})
        if not labels:
            raise ExtractError(f"custom value label {status_id}: no labels")
        value_labels[status_id] = labels

    auras: dict[int, dict[str, object]] = {}
    for entry in document.get("auras", []):
        assert isinstance(entry, dict)
        ids = [int(value) for value in entry.get("ids", [])]
        if not ids:
            raise ExtractError("custom aura without status ids")
        kind = entry.get("kind")
        if kind not in _AURA_KINDS:
            raise ExtractError(f"custom aura {ids}: unknown kind {kind!r}")
        body_frames = [_string(frame, f"custom aura {ids} body frame") for frame in entry.get("body_frames", [])]
        if not body_frames:
            raise ExtractError(f"custom aura {ids}: no body frames")

        def texture(key: str) -> str:
            value = _string(entry.get(key), f"custom aura {ids}.{key}")
            if not value.lower().endswith((".tga", ".bmp")):
                raise ExtractError(f"custom aura {ids}.{key}: expected a .tga/.bmp texture, got {value!r}")
            return value

        aura = {
            "kind": kind,
            "source": _string(entry.get("source"), f"custom aura {ids}.source"),
            "textures": {
                "ground": texture("ground_texture"),
                "ring": texture("ring_texture"),
                "body_frames": body_frames,
                "body_glow": texture("body_glow_texture"),
            },
            "tint": {
                "ground": _colour(entry.get("ground_color"), f"custom aura {ids}.ground_color"),
                "body": _colour(entry.get("body_color"), f"custom aura {ids}.body_color"),
                "glow": _colour(entry.get("glow_color"), f"custom aura {ids}.glow_color"),
            },
            "radii": {
                "ground": _number(entry.get("ground_radius"), f"custom aura {ids}.ground_radius"),
                "ring": _number(entry.get("ring_radius"), f"custom aura {ids}.ring_radius"),
                "body": _number(entry.get("body_size"), f"custom aura {ids}.body_size"),
                "body_glow": _number(entry.get("body_glow_size"), f"custom aura {ids}.body_glow_size"),
            },
            "timing": {
                "body_frame_rate": _number(entry.get("body_frame_rate"), f"custom aura {ids}.body_frame_rate"),
                "ring_rotation_speed": _number(entry.get("ring_rotation_speed"), f"custom aura {ids}.ring_rotation_speed"),
                "body_rotation_speed": _number(entry.get("body_rotation_speed"), f"custom aura {ids}.body_rotation_speed"),
                "body_camera_offset": _number(entry.get("body_camera_offset"), f"custom aura {ids}.body_camera_offset"),
                "pulse_speed": _number(entry.get("pulse_speed"), f"custom aura {ids}.pulse_speed"),
                "pulse_amount": _number(entry.get("pulse_amount"), f"custom aura {ids}.pulse_amount"),
            },
            "alpha": {
                "ground": _number(entry.get("ground_alpha"), f"custom aura {ids}.ground_alpha"),
                "ring": _number(entry.get("ring_alpha"), f"custom aura {ids}.ring_alpha"),
                "body": _number(entry.get("body_alpha"), f"custom aura {ids}.body_alpha"),
                "body_glow": _number(entry.get("body_glow_alpha"), f"custom aura {ids}.body_glow_alpha"),
            },
            "height": _number(entry.get("body_height"), f"custom aura {ids}.body_height"),
        }
        for status_id in ids:
            if status_id in auras:
                raise ExtractError(f"custom aura {status_id}: defined twice")
            auras[status_id] = aura

    return {
        "names": names,
        "icons": icons,
        "categories": categories,
        "value_labels": value_labels,
        "auras": auras,
        "counts": {
            "names": len(names),
            "icons": len(icons),
            "categories": len(categories),
            "value_labels": len(value_labels),
            "auras": len(auras),
        },
    }


