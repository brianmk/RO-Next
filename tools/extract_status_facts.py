def parse_cpp_enum(source: str, declaration: str, first_value: int = 0) -> list[tuple[str, int]]:
    """Parse a C++ enum body into an ordered `(symbol, id)` list."""
    start = source.find(declaration)
    if start < 0:
        raise ExtractError(f"enum declaration not found: {declaration}")
    brace = source.find("{", start)
    if brace < 0:
        raise ExtractError(f"enum body not found: {declaration}")
    end = source.find("\n};", brace)
    if end < 0:
        raise ExtractError(f"unterminated enum: {declaration}")

    entries: list[tuple[str, int]] = []
    next_value = first_value
    for raw_line in source[brace + 1 : end].splitlines():
        line = raw_line.split("//", 1)[0].strip().rstrip(",").strip()
        if not line:
            continue
        match = re.match(r"([A-Za-z_]\w*)\s*(?:=\s*(-?\d+))?$", line)
        if not match:
            continue
        if match.group(2) is not None:
            next_value = int(match.group(2))
        entries.append((match.group(1), next_value))
        next_value += 1
    return entries


def parse_element_names(map_hpp: str) -> list[tuple[int, str]]:
    """Element ids (0..9) and their English names, from `enum e_element`."""
    elements: list[tuple[int, str]] = []
    for symbol, element_id in parse_cpp_enum(map_hpp, "enum e_element", first_value=-1):
        if element_id < 0 or element_id > 9:
            continue
        elements.append((element_id, symbol[len("ELE_") :].title()))
    if len(elements) != 10:
        raise ExtractError(f"expected the 10 rAthena elements, got {len(elements)}")
    return elements


def parse_status_yml(text: str) -> list[dict[str, object]]:
    """Parse the rAthena `db/pre-re/status.yml` status change database.

    Only the fields the client presentation uses are kept (`Status`, `Icon`,
    `DurationLookup`, `MinDuration`, `Flags`, `CalcFlags`); the scripts and
    battle flags are server gameplay data and are intentionally not extracted.
    """
    entries: list[dict[str, object]] = []
    current: dict[str, object] | None = None
    section: str | None = None

    for raw_line in text.splitlines():
        status_match = re.match(r"  - Status:\s*(\w+)\s*$", raw_line)
        if status_match:
            current = {
                "status": status_match.group(1),
                "icon": None,
                "duration_lookup": None,
                "min_duration": None,
                "flags": [],
                "calc_flags": [],
            }
            entries.append(current)
            section = None
            continue

        if current is None:
            continue

        # A new top-level key of the entry (four spaces).
        key_match = re.match(r"    ([A-Za-z_]\w*):\s*(.*)$", raw_line)
        if key_match:
            key, value = key_match.group(1), key_match.group(2).strip()
            section = key if value == "" else None
            if key == "Icon":
                current["icon"] = value
            elif key == "DurationLookup":
                current["duration_lookup"] = value
            elif key == "MinDuration" and value.isdigit():
                current["min_duration"] = int(value)
            continue

        # A `true` switch below a section header (six spaces).
        switch_match = re.match(r"      ([A-Za-z_]\w*):\s*(true|false)\s*$", raw_line)
        if switch_match and section in ("Flags", "CalcFlags"):
            if switch_match.group(2) == "true":
                field = "flags" if section == "Flags" else "calc_flags"
                values = current[field]
                assert isinstance(values, list)
                values.append(switch_match.group(1))

    if not entries:
        raise ExtractError("db/pre-re/status.yml contained no status entries")
    return entries


def parse_lub_assignments(text: str, pattern: str) -> list[tuple[str, str]]:
    """All `(symbol, string value)` matches of a Lua assignment pattern."""
    return [(match.group(1), match.group(2)) for match in re.finditer(pattern, text, re.S)]


def parse_efstids_lub(text: str) -> dict[str, int]:
    """The client's own `EFST_* -> id` table (`efstids.lub`)."""
    ids: dict[str, int] = {}
    for match in re.finditer(r"(EFST_\w+)\s*=\s*(-?\d+)\s*,", text):
        ids[match.group(1)] = int(match.group(2))
    if not ids:
        raise ExtractError("efstids.lub contained no EFST ids")
    return ids


_CATEGORY_BY_COLOUR = {
    "COLOR_TITLE_BUFF": "Buff",
    "COLOR_TITLE_DEBUFF": "Debuff",
    "COLOR_TITLE_TOGGLE": "Toggle",
    "COLOR_TITLE_SYSTEM": "System",
    "COLOR_SYSTEM": "System",
}

_LUA_ENTRY = re.compile(r"\{\s*\"((?:[^\"\\]|\\.)*)\"\s*(?:,\s*([A-Z_]+))?\s*,?\s*\}", re.S)
_JS_ENTRY = re.compile(r"\[\s*'((?:[^'\\]|\\.)*)'\s*(?:,\s*([A-Z_]+))?\s*,?\s*\]", re.S)


def parse_stateiconinfo_lub(text: str) -> dict[str, dict[str, object]]:
    """Parse `stateiconinfo.lub` into `EFST symbol -> title/category/description`."""
    result: dict[str, dict[str, object]] = {}
    blocks = re.findall(r"StateIconList\[EFST_IDs\.(\w+)\]\s*=\s*\{(.*?)\n\}", text, re.S)
    for symbol, body in blocks:
        have_time_limit = re.search(r"haveTimeLimit\s*=\s*(\d+)", body)
        pos_time_limit = re.search(r"posTimeLimitStr\s*=\s*(\d+)", body)
        # Only the `descript` table contains brace-delimited string entries.
        entries = _LUA_ENTRY.findall(body)

        title = None
        category = None
        description: list[str] = []
        seen_title = False
        for raw_value, colour in entries:
            value = decode_lub_string(raw_value.replace('\\"', '"'))
            if not seen_title:
                title = value
                category = _CATEGORY_BY_COLOUR.get(colour) if colour else None
                seen_title = True
                continue
            # `{ "%s", COLOR_TIME }` is the remaining-time placeholder, not a
            # text line; everything before it is the name, after it the body.
            if value.startswith("%s") or value == "%s":
                continue
            description.append(value)

        result[symbol] = {
            "name": title,
            "category": category,
            "have_time_limit": bool(have_time_limit and int(have_time_limit.group(1))),
            "pos_time_limit": int(pos_time_limit.group(1)) if pos_time_limit else None,
            "description": description,
        }
    if not result:
        raise ExtractError("stateiconinfo.lub contained no StateIconList entries")
    return result


def parse_stateiconimginfo_lub(text: str) -> dict[str, dict[str, str]]:
    """Parse `stateiconimginfo.lub` into `EFST symbol -> icon file (+ priority)`."""
    result: dict[str, dict[str, str]] = {}
    priority = "unknown"
    for line in text.splitlines():
        priority_match = re.search(r"\[PRIORITY_(GOLD|RED|BLUE|GREEN|WHITE)\]", line)
        if priority_match:
            priority = priority_match.group(1).lower()
            continue
        entry_match = re.search(r"\[EFST_IDs\.(\w+)\]\s*=\s*\"([^\"]+)\"", line)
        if entry_match:
            result[entry_match.group(1)] = {
                "icon": decode_lub_string(entry_match.group(2)),
                "priority": priority,
            }
    if not result:
        raise ExtractError("stateiconimginfo.lub contained no StateIconImgList entries")
    return result


