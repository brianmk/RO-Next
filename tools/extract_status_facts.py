#!/usr/bin/env python3
"""Extract the facts behind the data-driven status-effect subsystem.

The client no longer keeps hand-written status name/icon/element/aura tables in
Rust: `korangar/archive/data/client/status_effects.ron` is generated from the
committed facts file produced by this script (see `tools/gen_status_effects.py`
for the second half of the pipeline).

This script is the *extraction* half. It reads the real server/client sources,
merges them into one deterministic JSON document and writes

    tools/status_facts.json

Sources (all outside the client tree, read-only):

* rAthena map server (CondaRO 2019 tree):
  * `src/map/status.hpp` - `enum efst_type` (the ids the map server sends in
    `ZC_MSG_STATE_CHANGE3`/`ZC_EFST_SET_ENTER`) and `enum sc_type`,
  * `src/map/map.hpp` - `enum e_element` (values sent for weapon enchant),
  * `db/pre-re/status.yml` - status names, display icon (`Icon`),
    `DurationLookup`, `MinDuration`, `Flags` (`DisplayPc`, `DisplayNpc`,
    `Debuff`, `SendVal1..3`, ...) and `CalcFlags`.
* Official 2019 client Lua tables, read from the GRF archive chain
  (`archive/` folder > `palettes.grf` > `CondaRO.grf` > `data.grf`, i.e. the
  same priority the client's `GameFileLoader` uses):
  * `data\\luafiles514\\lua files\\stateicon\\stateiconinfo.lub` - English
    titles, title colours (buff/debuff/toggle/system category), descriptions,
    `haveTimeLimit`/`posTimeLimitStr`,
  * `data\\luafiles514\\lua files\\stateicon\\stateiconimginfo.lub` - explicit
    status icon image names of newer statuses (priority colour groups),
  * `data\\luafiles514\\lua files\\stateicon\\efstids.lub` - the client's
    `EFST_* -> id` table (used to record client/server id drift).
* `tools/status_info_robrowser.json` - vendored facts of roBrowserLegacy's
  `src/DB/Status/StatusInfo.js` (the reverse-engineered official hard-coded
  classic status icon/title table) with URL/commit/file hashes as provenance.
  Regenerate it from the raw JavaScript with `--vendor-robrowser`.
* `tools/status_effect_custom.ron` - the small curated overlay: English names
  of client-only statuses, icon overrides for the generic element weapon
  property icons, value-label semantics for the `SendVal*` statuses, the
  persistent aura specs (Assumptio moved out of `world/effect/status_aura.rs`
  and four documented procedural buff glows) and the element name table.

The output document records the provenance of every source (path + SHA-256, and
for the vendored roBrowser facts the upstream URL and commit), the parsed
tables, the merged per-status facts and the client/server id drift.

Usage (from the repository root):

    ./tools/extract_status_facts.py \\
        --server-root /home/phantom/popeng-hotspots/condaro \\
        --game-dir ../client/game
    ./tools/extract_status_facts.py --check           # fail if out of date
    ./tools/extract_status_facts.py --vendor-robrowser \\
        /tmp/StatusInfo.js /tmp/StatusConst.js \\
        --write-robrowser-facts tools/status_info_robrowser.json

The client's runtime data file is generated by
`tools/gen_status_effects.py`; that generator and its `--check` mode run on the
committed facts JSON only, so CI does not need the game data or the server tree.
"""

