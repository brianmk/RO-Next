def _read_server_file(server_root: Path, relative: str) -> str:
    path = server_root / relative
    if not path.is_file():
        raise ExtractError(f"missing rAthena source file: {path}")
    return path.read_text(encoding="utf-8", errors="replace")


def _read_client_lub(chain: list[tuple[str, Path]], lub_dir: Path | None, path: str) -> tuple[str, bytes]:
    if lub_dir is not None:
        candidate = lub_dir / path.replace("\\", "/").split("/")[-1]
        if not candidate.is_file():
            raise ExtractError(f"missing Lua file: {candidate}")
        return str(candidate), candidate.read_bytes()
    archive, data = client_file(chain, path)
    if data is None:
        raise ExtractError(f"Lua file not found in the client archives: {path}")
    assert archive is not None
    return archive, data


def extract_status_facts(
    server_root: Path,
    game_dir: Path | None,
    archive_dir: Path | None,
    lub_dir: Path | None,
    robrowser_facts_path: Path,
    custom_path: Path,
    robrowser_commit: str | None,
) -> dict[str, object]:
    """Read every source, merge the status facts and return the facts document."""
    status_hpp_text = _read_server_file(server_root, STATUS_HPP)
    map_hpp_text = _read_server_file(server_root, MAP_HPP)
    status_yml_text = _read_server_file(server_root, STATUS_YML)

    chain = archive_chain(game_dir, archive_dir)
    client_sources: dict[str, dict[str, object]] = {}
    lub_text: dict[str, str] = {}
    for key, path in (("stateiconinfo", LUB_STATEICONINFO), ("stateiconimginfo", LUB_STATEICONIMGINFO), ("efstids", LUB_EFSTIDS)):
        archive, data = _read_client_lub(chain, lub_dir, path)
        client_sources[key] = {"path": path, "archive": archive, "bytes": len(data), "sha256": sha256_bytes(data)}
        lub_text[key] = data.decode("latin-1")

    efst_enum = parse_cpp_enum(status_hpp_text, "enum efst_type", first_value=0)
    sc_enum = parse_cpp_enum(status_hpp_text, "enum sc_type", first_value=-1)
    elements = parse_element_names(map_hpp_text)
    status_yml = parse_status_yml(status_yml_text)
    client_state_info = parse_stateiconinfo_lub(lub_text["stateiconinfo"])
    client_icons_raw = parse_stateiconimginfo_lub(lub_text["stateiconimginfo"])
    client_efst_ids = parse_efstids_lub(lub_text["efstids"])

    if not robrowser_facts_path.is_file():
        raise ExtractError(f"missing vendored roBrowser facts: {robrowser_facts_path}")
    robrowser_document = json.loads(robrowser_facts_path.read_text(encoding="utf-8"))
    robrowser_entries = robrowser_document.get("entries", [])
    if not robrowser_entries:
        raise ExtractError(f"{robrowser_facts_path} contains no roBrowser entries")

    custom = read_custom_overlay(custom_path)

    efst_by_name = {name: status_id for name, status_id in efst_enum}
    efst_by_id = {status_id: name for name, status_id in efst_enum}
    sc_by_norm = {normalize_symbol(symbol[3:]): symbol for symbol, _ in sc_enum}

    # Status database entries are linked to the packet ids through their
    # explicit display icon (the `Icon` field is the client's EFST id).
    yml_by_icon: dict[str, dict[str, object]] = {}
    for entry in status_yml:
        icon = entry["icon"]
        if isinstance(icon, str) and icon != "" and icon in efst_by_name:
            yml_by_icon.setdefault(icon, entry)

    # roBrowser facts are keyed by the client's own status-change symbols; the
    # symbol (not the drifted number) links them to the server EFST ids.
    efst_by_norm: dict[str, str] = {}
    ambiguous: set[str] = set()
    for symbol, _ in efst_enum:
        key = normalize_symbol(symbol[5:])
        if key in efst_by_norm:
            ambiguous.add(key)
        efst_by_norm[key] = symbol
    robrowser_icons: dict[int, dict[str, str]] = {}
    for entry in robrowser_entries:
        icon = entry.get("icon")
        if not icon:
            continue
        key = normalize_symbol(str(entry.get("sc", "")))
        symbol = efst_by_norm.get(key)
        if symbol is None or key in ambiguous:
            continue
        robrowser_icons[efst_by_name[symbol]] = {"icon": icon, "sc": str(entry["sc"]), "name": entry.get("name"), "category": entry.get("category")}

    def icon_exists(icon: str) -> bool:
        return client_file_exists(chain, STATUS_ICON_DIRECTORY + "\\" + icon)

    dropped_icons: list[dict[str, object]] = []
    custom_names: dict[int, str] = custom["names"]  # type: ignore[assignment]
    custom_icons: dict[int, str] = custom["icons"]  # type: ignore[assignment]
    custom_categories: dict[int, dict[str, str]] = custom["categories"]  # type: ignore[assignment]
    custom_value_labels: dict[int, list[dict[str, object]]] = custom["value_labels"]  # type: ignore[assignment]
    custom_auras: dict[int, dict[str, object]] = custom["auras"]  # type: ignore[assignment]

    for status_id in list(custom_names) + list(custom_icons) + list(custom_categories) + list(custom_value_labels) + list(custom_auras):
        if status_id not in efst_by_id:
            raise ExtractError(f"curated overlay references status {status_id}, which is not in the server efst_type enum")

    status_rows: list[dict[str, object]] = []
    for status_id in sorted(efst_by_id):
        if status_id < 0:
            continue
        symbol = efst_by_id[status_id]
        info = client_state_info.get(symbol)
        yml_entry = yml_by_icon.get(symbol)
        flags = yml_entry["flags"] if yml_entry else []
        assert isinstance(flags, list)

        name: str | None = None
        name_source: str | None = None
        if info and safe_status_name(info["name"]):  # type: ignore[arg-type]
            name = str(info["name"])
            name_source = "client-stateiconinfo.lub"
        elif status_id in custom_names:
            name = custom_names[status_id]
            name_source = "custom"

        icon: str | None = None
        icon_source: str | None = None
        if status_id in custom_icons:
            icon = custom_icons[status_id]
            icon_source = "custom"
        elif symbol in client_icons_raw:
            candidate = client_icons_raw[symbol]["icon"]
            if icon_exists(candidate):
                icon = candidate
                icon_source = "stateiconimginfo.lub"
            else:
                dropped_icons.append({"id": status_id, "icon": candidate, "source": "stateiconimginfo.lub"})
        elif status_id in robrowser_icons:
            candidate = robrowser_icons[status_id]["icon"]
            if icon_exists(candidate):
                icon = candidate
                icon_source = "robrowser-statusinfo"
            else:
                dropped_icons.append({"id": status_id, "icon": candidate, "source": "robrowser-statusinfo"})

        category = None
        category_source = None
        if info and info["category"]:
            category = info["category"]
            category_source = "client-stateiconinfo.lub"
        elif status_id in custom_categories:
            category = custom_categories[status_id]["category"]
            category_source = "custom"
        elif yml_entry:
            category = "Debuff" if "Debuff" in flags else "Buff"
            category_source = "pre-re/status.yml Debuff flag"
        else:
            category = "Buff"
            category_source = "default"

        value_labels = custom_value_labels.get(status_id)
        aura = custom_auras.get(status_id)
        if aura is not None:
            textures = aura["textures"]
            assert isinstance(textures, dict)
            aura_textures = [textures["ground"], textures["ring"], textures["body_glow"], *textures["body_frames"]]
            for texture in aura_textures:
                assert isinstance(texture, str)
                effect_path = "data\\texture\\" + texture
                if not client_file_exists(chain, effect_path):
                    raise ExtractError(f"aura texture of status {status_id} does not exist in the client data: {texture}")

        if not (name or icon or value_labels or aura):
            continue

        status_yml_name = yml_entry["status"] if yml_entry else None
        sc_symbol = None
        if isinstance(status_yml_name, str):
            sc_symbol = sc_by_norm.get(normalize_symbol(status_yml_name))

        row: dict[str, object] = {
            "id": status_id,
            "efst": symbol,
            "sc": sc_symbol,
            "client_efst_id": client_efst_ids.get(symbol),
            "name": name,
            "name_source": name_source,
            "icon": icon,
            "icon_source": icon_source,
            "category": category,
            "category_source": category_source,
            "status_yml": status_yml_name,
            "display_pc": "DisplayPc" in flags,
            "display_npc": "DisplayNpc" in flags,
            "debuff": "Debuff" in flags,
            "send_values": [index for index in (1, 2, 3) if f"SendVal{index}" in flags],
            "status_flags": sorted(flags),
            "calc_flags": sorted(yml_entry["calc_flags"]) if yml_entry else [],
            "duration_lookup": yml_entry["duration_lookup"] if yml_entry else None,
            "min_duration_in_milliseconds": yml_entry["min_duration"] if yml_entry else None,
            "have_time_limit": bool(info["have_time_limit"]) if info else False,
            "value_labels": value_labels,
            "refresh": "Replace",
            "stack": "Single",
            "aura": aura,
        }
        if row["client_efst_id"] == status_id:
            row["client_efst_id"] = None
        if row["aura"] is None:
            del row["aura"]
        if row["value_labels"] is None:
            del row["value_labels"]
        status_rows.append(row)

    provenance = {
        "generated_by": "tools/extract_status_facts.py",
        "schema": FACTS_SCHEMA,
        "description": "Status-effect facts merged from the rAthena server sources, the official 2019 client Lua tables, the reverse-engineered classic status table and the curated overlay. The client data file `korangar/archive/data/client/status_effects.ron` is generated from this document by `tools/gen_status_effects.py`.",
        "server": {
            "tree": str(server_root),
            "files": {
                relative: {"bytes": len(_read_server_file(server_root, relative).encode()), "sha256": sha256_bytes(_read_server_file(server_root, relative).encode())}
                for relative in (STATUS_HPP, MAP_HPP, STATUS_YML)
            },
        },
        "client": {
            "archives": [{"name": name, "path": str(location)} for name, location in chain],
            "lub_files": client_sources,
        },
        "robrowser": {
            "facts_file": str(robrowser_facts_path.relative_to(REPO)) if robrowser_facts_path.is_relative_to(REPO) else str(robrowser_facts_path),
            "facts_sha256": sha256_file(robrowser_facts_path),
            "source": robrowser_document.get("provenance", {}).get("source"),
            "commit": robrowser_commit or robrowser_document.get("provenance", {}).get("commit"),
            "entries": len(robrowser_entries),
        },
        "custom": {
            "file": str(custom_path.relative_to(REPO)) if custom_path.is_relative_to(REPO) else str(custom_path),
            "sha256": sha256_file(custom_path),
            "counts": custom["counts"],
        },
        "counts": {
            "efst_enum": len(efst_enum),
            "sc_enum": len(sc_enum),
            "status_yml": len(status_yml),
            "client_state_info": len(client_state_info),
            "client_icons": len(client_icons_raw),
            "robrowser_icons": len(robrowser_icons),
            "merged_statuses": len(status_rows),
            "dropped_icons": len(dropped_icons),
            "values": sum(1 for row in status_rows if "value_labels" in row),
            "auras": sum(1 for row in status_rows if "aura" in row),
        },
        "dropped_icons": dropped_icons,
    }

    return {
        "schema": FACTS_SCHEMA,
        "provenance": provenance,
        "elements": [{"id": element_id, "name": name} for element_id, name in elements],
        "efst_enum": [{"id": status_id, "name": name} for name, status_id in efst_enum],
        "sc_enum": [{"id": status_id, "name": name} for name, status_id in sc_enum],
        "status_yml": status_yml,
        "client_state_info": [
            {
                "efst": symbol,
                "id": efst_by_name.get(symbol),
                "name": info["name"],
                "category": info["category"],
                "have_time_limit": info["have_time_limit"],
                "pos_time_limit": info["pos_time_limit"],
            }
            for symbol, info in sorted(client_state_info.items(), key=lambda item: efst_by_name.get(item[0], 1 << 30))
        ],
        "client_icons": [
            {
                "efst": symbol,
                "id": efst_by_name.get(symbol),
                "icon": info["icon"],
                "priority": info["priority"],
            }
            for symbol, info in sorted(client_icons_raw.items(), key=lambda item: efst_by_name.get(item[0], 1 << 30))
        ],
        "robrowser_icons": [
            {
                "id": status_id,
                "efst": efst_by_id[status_id],
                "sc": value["sc"],
                "icon": value["icon"],
                "name": value["name"],
                "category": value["category"],
            }
            for status_id, value in sorted(robrowser_icons.items())
        ],
        "statuses": status_rows,
    }


