#!/usr/bin/env python3
"""Generate the hard-coded (decompilation) skill effect fragment.

The 2019 GRF `SKILL_EFFECT_INFO_LIST` gives 43 skills an official effect id but
the roBrowserLegacy effect-table dump has no layer facts for those ids: the
visuals live in the client executable. This generator turns the facts extracted
from the `rodecomp` decompilation (`tools/rodecomp_effect_layers.json`) into the
same fragment schema the official-table lane uses, so the pipeline merge
(`tools/gen_skill_effects.py`) can consume it:

    tools/skill_effects_rodecomp_hardcoded.ron

Inputs:

* `tools/rodecomp_effect_layers.json` - effect id -> layer facts (official table
  schema: `type`, `file`, `duplicate`, colours, sizes, `duration`, ...) plus the
  source line numbers of the implementation and the explicit rows for skills the
  2019 table lists without an effect id; `provenance`/`scope`/`skipped_*` keep
  the gap auditable.
* `tools/grf2019_skill_facts.json` - which `SkillEffect` field of which skill
  references each effect id (it decides the phase and the anchor).
* the CondaRO GRF archives - every `.str`/`.spr`/`.act`/texture is validated.

The layer conversion is delegated to `tools/gen_skill_effect_layers.py`
(`build_layer`): sizes in official effect units, `same` anchor rules, same
whitelists, same coalescing. The output therefore stays byte-for-byte compatible
with the shared fragment reader in `tools/gen_skill_effects.py`.

Usage:
    ./tools/gen_rodecomp_effect_layers.py            # regenerate the fragment
    ./tools/gen_rodecomp_effect_layers.py --check    # fail if out of date
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_FACTS = REPO / "tools/rodecomp_effect_layers.json"
DEFAULT_GRF2019 = REPO / "tools/grf2019_skill_facts.json"
DEFAULT_GAME_DIR = "/home/phantom/Games/ragnarok/CondaRO-linux/client/game"
DEFAULT_STR_WHITELIST = REPO / "tools/windows_client_effect_whitelist.txt"
DEFAULT_SPR_WHITELIST = REPO / "tools/windows_client_spr_whitelist.txt"
DEFAULT_OUTPUT = REPO / "tools/skill_effects_rodecomp_hardcoded.ron"

PROVENANCE = (
    "hard-coded skill effects of the CondaRO 2019 client, extracted from the rodecomp decompilation "
    "(CRagEffect switch cases and dedicated CEffect classes) and converted with the official layer rules"
)

#: 2019 GRF `SkillEffect` kind -> the field name the layer generator knows.
GRF2019_FIELD = {
    "caster": "successEffectIdOnCaster",
    "target": "successEffectIdOnTarget",
    "ground": "groundEffectId",
    "begin": "beginCastEffectId",
}

HEADER_TEMPLATE = [
    "// Hard-coded (C++ implemented) skill effect rows from the client decompilation.",
    "//",
    "// Generated by `tools/gen_rodecomp_effect_layers.py` from",
    "// `tools/rodecomp_effect_layers.json`; do not edit by hand.",
    "// Regenerate with: `./tools/gen_rodecomp_effect_layers.py`",
    "// Drift check:      `./tools/gen_rodecomp_effect_layers.py --check`",
    "//",
    "// These skills have an official effect id in the 2019 GRF SKILL_EFFECT_INFO_LIST",
    "// but no effect-table layer facts: the client implements the visuals in C++",
    "// (`CRagEffect::OnProcess*` switches and the `CEffect` subclasses registered in",
    "// `EffectLists::RegisterAllocators`). The fact file records the implementation",
    "// source lines; the layers are converted with the same rules as the",
    "// official-table fragment (`tools/gen_skill_effect_layers.py`).",
    "//",
    "// Consumed by `tools/gen_skill_effects.py --rodecomp-hardcoded`.",
]


def load_layer_module():
    spec = importlib.util.spec_from_file_location("gen_skill_effect_layers", REPO / "tools/gen_skill_effect_layers.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def skill_facts(scope: list[int], grf2019: dict) -> dict:
    """Build the `SkillEffect` field -> effect ids facts for the scoped skills."""
    facts: dict = {"skills": {}}
    for skill_id in scope:
        entry = grf2019.get(str(skill_id))
        if not entry:
            continue
        fields = []
        for kind, effect_ids in entry.get("effects", {}).items():
            if kind in GRF2019_FIELD and effect_ids:
                fields.append({"field": GRF2019_FIELD[kind], "effects": list(effect_ids)})
        if fields:
            facts["skills"][skill_id] = fields
    return facts


def explained_effect_ids(payload: dict) -> set[int]:
    return {int(key) for key in payload.get("effects", {})} | {int(key) for key in payload.get("skipped_effect_ids", {})}


def build_rows(gs, payload: dict, grf2019: dict, assets, whitelists) -> tuple[list[dict], dict]:
    """Expand the effect-id facts into (skill, phase, layers) rows."""
    scope = [int(skill_id) for skill_id in payload["scope"]["skills"]]
    facts = skill_facts(scope, grf2019)
    layers_facts = {"effects": {str(key): {"layers": entry["layers"]} for key, entry in payload["effects"].items()}}
    rows, stats = gs.build(facts, layers_facts, assets, whitelists, {"actions": {}}, {"skills": {}}, None)

    # The 2019 table lists a few skills without an effect id; their visuals are
    # spawned from the skill-unit/status code, so the fact file spells them out.
    rows_by_key = {(row["skill"], row["phase"]): row for row in rows}
    dropped: dict[str, list[str]] = defaultdict(list)
    unmapped: Counter[str] = Counter()
    for skill_text, spec in sorted(payload.get("skills", {}).items(), key=lambda item: int(item[0])):
        skill = int(skill_text)
        for row in spec.get("rows", []):
            phase = row["phase"]
            hint = row.get("hint", phase)
            context = f"skill {skill} {phase}"
            built: list[dict] = []
            for entry in row.get("layers", []):
                if entry.get("kind") == "BodyFlash":
                    # A body flash has no asset: the schema renders it from the
                    # entity tint plus hold/fade, so the fact is passed through.
                    layer = {key: value for key, value in entry.items() if key != "raw"}
                    if layer.get("tint") is not None and not isinstance(layer["tint"], tuple):
                        layer["tint"] = tuple(layer["tint"])
                    built.append(layer)
                    continue
                layer = gs.build_layer(entry, phase, hint, assets, whitelists, dropped, unmapped, context)
                if layer is None:
                    continue
                built.extend(layer["multi"] if "multi" in layer else [layer])
            if not built:
                continue
            key = (skill, phase)
            target = rows_by_key.get(key)
            if target is None:
                target = {"skill": skill, "phase": phase, "layers": []}
                rows_by_key[key] = target
            target["layers"].extend(built)

    ordered = [row for row in rows_by_key.values() if row["layers"]]
    for row in ordered:
        row["layers"] = gs.coalesce_layers(row["layers"])
    ordered.sort(key=lambda row: (row["skill"], gs.PHASE_ORDER.index(row["phase"])))

    # Every effect id the scoped skills reference must be either mapped or
    # explicitly skipped; anything else is a fact gap, not something to hide.
    known = explained_effect_ids(payload)
    unknown: list[int] = []
    for fields in facts["skills"].values():
        for field in fields:
            for effect_id in field["effects"]:
                if int(effect_id) not in known and int(effect_id) != 0:
                    unknown.append(int(effect_id))
    if unknown:
        raise SystemExit(f"effect ids referenced by the scoped skills but not covered by the facts: {sorted(set(unknown))}")

    # Same for skills: every scoped skill must yield a row or be documented.
    covered = {row["skill"] for row in ordered}
    skipped = {int(key) for key in payload.get("skipped_skills", {})}
    silently_missing = [
        skill
        for skill in scope
        if skill not in covered and skill not in skipped and str(skill) not in payload.get("skills", {})
    ]
    if silently_missing:
        raise SystemExit(f"scoped skills without rows or a skipped_skills reason: {silently_missing}")

    stats["unmapped_parameters"] = dict(sorted(unmapped.items()))
    stats["explicit_dropped"] = {reason: values for reason, values in sorted(dropped.items()) if values}
    return ordered, stats


def header_for(payload: dict, rows: list[dict], stats: dict) -> list[str]:
    lines = list(HEADER_TEMPLATE)
    layers = sum(len(row["layers"]) for row in rows)
    lines.append("//")
    lines.append(f"// {len({row['skill'] for row in rows})} skills, {len(rows)} phases, {layers} layers.")
    skipped_effects = payload.get("skipped_effect_ids", {})
    if skipped_effects:
        lines.append("//")
        lines.append("// Effect ids without a file layer (kept out instead of inventing visuals):")
        for effect_id, entry in sorted(skipped_effects.items(), key=lambda item: int(item[0])):
            if isinstance(entry, dict):
                lines.append(f"//   {effect_id} {entry.get('name', '')}: {entry.get('reason', '')}")
            else:
                lines.append(f"//   {effect_id}: {entry}")
    skipped_skills = payload.get("skipped_skills", {})
    if skipped_skills:
        lines.append("//")
        lines.append("// Skills without a fixed visual:")
        for skill_id, entry in sorted(skipped_skills.items(), key=lambda item: int(item[0])):
            if isinstance(entry, dict):
                lines.append(f"//   {skill_id} {entry.get('name', '')}: {entry.get('reason', '')}")
            else:
                lines.append(f"//   {skill_id}: {entry}")
    dropped = stats.get("dropped", {}).get("unknown_effect", [])
    if dropped:
        lines.append("//")
        lines.append("// Effect ids the client handles but with no fixed asset (dropped by the shared builder):")
        for value in dropped:
            lines.append(f"//   {value}")
    return lines


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--facts", default=str(DEFAULT_FACTS))
    parser.add_argument("--grf2019", default=str(DEFAULT_GRF2019))
    parser.add_argument("--game-dir", default=DEFAULT_GAME_DIR)
    parser.add_argument("--str-whitelist", default=str(DEFAULT_STR_WHITELIST))
    parser.add_argument("--spr-whitelist", default=str(DEFAULT_SPR_WHITELIST))
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--check", action="store_true", help="fail if the committed fragment is out of date")
    args = parser.parse_args()

    facts_path = Path(args.facts)
    if not facts_path.is_file():
        raise SystemExit(f"missing facts file: {facts_path}")
    grf2019_path = Path(args.grf2019)
    if not grf2019_path.is_file():
        raise SystemExit(f"missing 2019 GRF facts file: {grf2019_path}")
    game_dir = Path(args.game_dir)
    if not game_dir.is_dir():
        raise SystemExit(f"game directory with GRF archives not found: {game_dir}")

    payload = json.loads(facts_path.read_text(encoding="utf-8"))
    grf2019 = json.loads(grf2019_path.read_text(encoding="utf-8"))["skills"]

    gs = load_layer_module()
    assets = gs.Assets.collect(game_dir)
    if not assets.str_files or not assets.sprites or not assets.textures:
        raise SystemExit(f"no effect assets found in the archives under {game_dir}")
    whitelists = (
        gs.load_str_whitelist(Path(args.str_whitelist)),
        gs.load_spr_whitelist(Path(args.spr_whitelist)),
    )

    rows, stats = build_rows(gs, payload, grf2019, assets, whitelists)

    # Defensive validation of every emitted asset (never trust the resolver).
    for row in rows:
        context = f"skill {row['skill']} {row['phase']}"
        for layer in row["layers"]:
            if layer["kind"] == "Str":
                if layer["file"].lower() not in assets.str_files:
                    raise SystemExit(f"{context}: .str not in archives: {layer['file']}")
            elif layer["kind"] == "Spr":
                for stem in layer["files"]:
                    if f"{stem.lower()}.spr" not in assets.sprites or f"{stem.lower()}.act" not in assets.actions:
                        raise SystemExit(f"{context}: sprite pair not in archives: {stem}")
            elif layer["kind"] in ("Texture", "Cylinder", "Primitive"):
                if layer["file"].lower() not in assets.textures:
                    raise SystemExit(f"{context}: texture not in archives: {layer['file']}")
            if "wav" in layer and layer["wav"].lower() not in assets.wavs:
                raise SystemExit(f"{context}: wav not in archives: {layer['wav']}")

    content = gs.render_ron(rows, PROVENANCE, header=header_for(payload, rows, stats))
    output = Path(args.output)

    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else ""
        if current != content:
            print(f"error: {output} is out of date; run ./tools/gen_rodecomp_effect_layers.py", file=sys.stderr)
            return 1
        print(f"up to date: {len(rows)} phases, {sum(len(row['layers']) for row in rows)} layers")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"{output}: {len(rows)} phases, {sum(len(row['layers']) for row in rows)} layers, {len({row['skill'] for row in rows})} skills")
    for reason, values in stats.get("dropped", {}).items():
        for value in values:
            print(f"dropped ({reason}): {value}")
    for reason, values in stats.get("explicit_dropped", {}).items():
        for value in values:
            print(f"dropped ({reason}): {value}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
