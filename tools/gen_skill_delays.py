#!/usr/bin/env python3
"""Generate the per-skill delay table used by the client.

The committed table (`korangar/src/world/library/skill_delays.rs`) is generated
from the **real** rAthena `db/pre-re/skill_db.yml` of the CondaRO server at the
pinned packet version (20190605). It carries the timing values of every skill:
cast time, fixed cast time, after-cast act delay, after-cast walk delay and
cooldown, for every skill level.

The client otherwise only learns a cast time from the server's `ZC_USESKILL_ACK`
(0x0B1A) packet; these values are used as a fallback for the cast bar/animation
duration and to pace actions with the per-skill after-cast act delay. Server
packets stay authoritative whenever they are available.

Usage:
    ./tools/gen_skill_delays.py                     # regenerate the committed file
    ./tools/gen_skill_delays.py --check             # fail if the file is out of date
    ./tools/gen_skill_delays.py --ssh myhost --server-root /home/phantom/rathena
    ./tools/gen_skill_delays.py --local /path/to/rathena

Only read-only commands are run against the server tree.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

DEFAULT_SSH = "rathena"
DEFAULT_SERVER_ROOT = "/home/phantom/rathena"
SKILL_DB = "db/pre-re/skill_db.yml"
DEFAULT_OUTPUT = Path("korangar/src/world/library/skill_delays.rs")
PACKETVER = 20190605

# rAthena yml keys -> generated Rust field name.
DELAY_FIELDS = [
    ("CastTime", "cast_ms"),
    ("FixedCastTime", "fixed_cast_ms"),
    ("AfterCastActDelay", "aftercast_act_ms"),
    ("AfterCastWalkDelay", "aftercast_walk_ms"),
    ("Cooldown", "cooldown_ms"),
]


def fetch_skill_db(ssh_host: str | None, server_root: str, local: str | None) -> str:
    path = f"{server_root}/{SKILL_DB}" if local is None else f"{local}/{SKILL_DB}"
    if ssh_host is None:
        return Path(path).read_text()
    result = subprocess.run(["ssh", ssh_host, "cat", path], capture_output=True, text=True, check=True)
    return result.stdout


def per_level(value, max_level: int) -> list[int]:
    """Expand a yml timing value into one number per skill level."""
    if value is None:
        return [0] * max_level
    if isinstance(value, int):
        # rAthena uses -1 for "no fixed cast"; clamp negative values to zero.
        return [max(value, 0)] * max_level

    levels = [0] * max_level
    previous = 0
    for entry in value:
        level = int(entry["Level"])
        time = max(int(entry.get("Time", entry.get("Cooldown", 0)) or 0), 0)
        # rAthena lists are sparse for some skills; use the last known value for
        # levels between two entries and for levels before the first entry.
        start = max(level - 1, 0)
        for index in range(start, max_level):
            levels[index] = time
        previous = time
    # Levels before the first explicit entry keep the first entry's value (the
    # game treats the value of the lowest listed level as the default).
    first_level = int(value[0]["Level"])
    first_time = int(value[0].get("Time", value[0].get("Cooldown", 0)) or 0)
    for index in range(min(first_level - 1, max_level)):
        levels[index] = first_time
    del previous
    return levels


def parse_skills(yml_text: str) -> list[tuple[int, list[dict[str, int]]]]:
    import yaml

    document = yaml.safe_load(yml_text)
    rows = document["Body"]
    skills: list[tuple[int, list[dict[str, int]]]] = []

    for skill in rows:
        skill_id = int(skill["Id"])
        max_level = int(skill.get("MaxLevel", 1))
        columns = [per_level(skill.get(key), max_level) for key, _ in DELAY_FIELDS]
        levels = []
        for level in range(max_level):
            values = {field: columns[i][level] for i, (_, field) in enumerate(DELAY_FIELDS)}
            levels.append(values)
        if any(any(values.values()) for values in levels):
            skills.append((skill_id, levels))

    skills.sort(key=lambda row: row[0])
    return skills


def format_rust(skills: list[tuple[int, list[dict[str, int]]]]) -> str:
    out = []
    out.append("//! Per-skill timing table generated from the rAthena server data.")
    out.append("//!")
    out.append("//! @generated by `tools/gen_skill_delays.py` from")
    out.append(f"//! rAthena `{SKILL_DB}` (PACKETVER {PACKETVER}). Do not edit manually;")
    out.append("//! re-run the generator instead (`--check` in CI detects drift).")
    out.append("//!")
    out.append("//! Skills with all-zero delays are omitted. The index of a level in the")
    out.append("//! per-skill slice is `level - 1`; requests above the maximum level use the")
    out.append("//! last entry.")
    out.append("")
    out.append("use ragnarok_packets::SkillId;")
    out.append("")
    out.append("/// Timing values of one skill level, in milliseconds.")
    out.append("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]")
    out.append("pub struct SkillDelays {")
    out.append("    /// Base cast time (`CastTime`).")
    out.append("    pub cast_ms: u32,")
    out.append("    /// Fixed (unreducible) cast time (`FixedCastTime`).")
    out.append("    pub fixed_cast_ms: u32,")
    out.append("    /// Delay before the next action/cast is accepted (`AfterCastActDelay`).")
    out.append("    pub aftercast_act_ms: u32,")
    out.append("    /// Delay before movement is accepted (`AfterCastWalkDelay`).")
    out.append("    pub aftercast_walk_ms: u32,")
    out.append("    /// Skill cooldown (`Cooldown`).")
    out.append("    pub cooldown_ms: u32,")
    out.append("}")
    out.append("")
    out.append("impl SkillDelays {")
    out.append("    /// Effective cast time: base cast time plus the fixed (unreducible) part.")
    out.append("    pub fn total_cast_ms(&self) -> u32 {")
    out.append("        self.cast_ms.saturating_add(self.fixed_cast_ms)")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("/// All skill levels of one skill.")
    out.append("#[derive(Clone, Copy, Debug)]")
    out.append("pub struct SkillDelayRow {")
    out.append("    pub skill_id: u16,")
    out.append("    pub levels: &'static [SkillDelays],")
    out.append("}")
    out.append("")
    out.append("/// One entry per skill with a non-zero delay, sorted by skill id.")
    out.append("#[rustfmt::skip]")
    out.append("pub static SKILL_DELAYS: &[SkillDelayRow] = &[")
    for skill_id, levels in skills:
        entries = ", ".join(
            f"SkillDelays {{ cast_ms: {l['cast_ms']}, fixed_cast_ms: {l['fixed_cast_ms']}, "
            f"aftercast_act_ms: {l['aftercast_act_ms']}, aftercast_walk_ms: {l['aftercast_walk_ms']}, cooldown_ms: {l['cooldown_ms']} }}"
            for l in levels
        )
        out.append(f"    SkillDelayRow {{ skill_id: {skill_id}, levels: &[{entries}] }},")
    out.append("];")
    out.append("")
    out.append("/// Look up the delays of a skill at the given level.")
    out.append("///")
    out.append("/// Returns `None` for skills without any server-side delay (or skills that")
    out.append("/// are not in the server data at all); callers fall back to their defaults.")
    out.append("pub fn skill_delays(skill_id: SkillId, level: u16) -> Option<&'static SkillDelays> {")
    out.append("    let index = SKILL_DELAYS.binary_search_by_key(&skill_id.0, |row| row.skill_id).ok()?;")
    out.append("    let levels = SKILL_DELAYS[index].levels;")
    out.append("    let level_index = usize::from(level).saturating_sub(1);")
    out.append("    levels.get(level_index).or_else(|| levels.last())")
    out.append("}")
    out.append("")
    out.append("#[cfg(test)]")
    out.append("mod tests {")
    out.append("    use ragnarok_packets::SkillId;")
    out.append("")
    out.append("    use super::{SKILL_DELAYS, skill_delays};")
    out.append("")
    out.append("    #[test]")
    out.append("    fn table_is_sorted_and_non_empty() {")
    out.append("        assert!(!SKILL_DELAYS.is_empty());")
    out.append("        assert!(SKILL_DELAYS.windows(2).all(|pair| pair[0].skill_id < pair[1].skill_id));")
    out.append("        assert!(SKILL_DELAYS.iter().all(|row| !row.levels.is_empty()));")
    out.append("    }")
    out.append("")
    out.append("    #[test]")
    out.append("    fn known_skills_have_their_delays() {")
    out.append("        // AL_HEAL (28): 1000 ms after-cast act delay, no cast time.")
    out.append("        let heal = skill_delays(SkillId(28), 1).expect(\"AL_HEAL should be in the table\");")
    out.append("        assert_eq!(heal.aftercast_act_ms, 1000);")
    out.append("        assert_eq!(heal.total_cast_ms(), 0);")
    out.append("")
    out.append("        // AL_INCAGI (29) has a 1000 ms cast time.")
    out.append("        let incagi = skill_delays(SkillId(29), 10).expect(\"AL_INCAGI should be in the table\");")
    out.append("        assert_eq!(incagi.cast_ms, 1000);")
    out.append("        assert_eq!(incagi.total_cast_ms(), 1000);")
    out.append("")
    out.append("        // MG_FIREBOLT (19) scales its cast time with the skill level.")
    out.append("        let bolt_1 = skill_delays(SkillId(19), 1).expect(\"MG_FIREBOLT should be in the table\");")
    out.append("        let bolt_10 = skill_delays(SkillId(19), 10).expect(\"MG_FIREBOLT should be in the table\");")
    out.append("        assert!(bolt_10.cast_ms > bolt_1.cast_ms);")
    out.append("    }")
    out.append("")
    out.append("    #[test]")
    out.append("    fn unknown_skills_and_levels_fall_back_safely() {")
    out.append("        assert!(skill_delays(SkillId(65_000), 1).is_none());")
    out.append("        // A level above the maximum uses the last entry instead of panicking.")
    out.append("        let heal_high = skill_delays(SkillId(28), 99).expect(\"AL_HEAL should be in the table\");")
    out.append("        let heal_max = skill_delays(SkillId(28), 10).expect(\"AL_HEAL should be in the table\");")
    out.append("        assert_eq!(heal_high, heal_max);")
    out.append("    }")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ssh", default=DEFAULT_SSH, help="ssh host with the rAthena tree (default: rathena)")
    parser.add_argument("--server-root", default=DEFAULT_SERVER_ROOT, help="rAthena tree on the ssh host")
    parser.add_argument("--local", default=None, help="use a local rAthena tree instead of ssh")
    parser.add_argument("--output", default=DEFAULT_OUTPUT, type=Path)
    parser.add_argument("--check", action="store_true", help="only verify that the committed file is up to date")
    args = parser.parse_args()

    skills = parse_skills(fetch_skill_db(args.ssh, args.server_root, args.local))
    generated = format_rust(skills)

    if args.check:
        try:
            current = args.output.read_text()
        except FileNotFoundError:
            print(f"{args.output} does not exist; run the generator", file=sys.stderr)
            return 1

        if current != generated:
            print(f"{args.output} is out of date; run tools/gen_skill_delays.py", file=sys.stderr)
            return 1

        print(f"{args.output} is up to date", file=sys.stderr)
        return 0

    args.output.write_text(generated)
    print(f"wrote {args.output} ({len(skills)} skills)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
