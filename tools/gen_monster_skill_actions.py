#!/usr/bin/env python3
"""Generate the client's official monster skill -> ACT action table.

The official client keeps `data\\MonsterSkillInfo.xml`, keyed by the monster's
lower-cased job name and skill id. `CSession::GetMonsterSkillInfo`
(`Source/Contents/Monster/MonsterXmlActions.cpp:43`) returns an `action` and a
`loopType`; the callers play it with
`SetAction(action * 8 - 8, 1, loopType == 0)` (`GameModePackets.cpp:12958`,
`:18371`). The facts are extracted by `tools/extract_monster_skill_motions.py`
into `tools/data/monster_skill_motions.json`; this generator turns them into
the data file the client loads through the regular `GameFileLoader`:

    ro-next/archive/data/client/monster_skill_actions.ron

The file is embedded with `include_str!` as the compiled fallback, so the data
file and the client cannot drift apart. A server can override the mapping
without rebuilding the client, like the player `skill_actions.ron` table.

Usage:
    ./tools/gen_monster_skill_actions.py            # regenerate the data file
    ./tools/gen_monster_skill_actions.py --check    # fail if the file is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

DEFAULT_FACTS = Path("tools/data/monster_skill_motions.json")
DEFAULT_OUTPUT = Path("ro-next/archive/data/client/monster_skill_actions.ron")

#: The client stores the ACT action index as `u8`; the XML values are 1..=9.
MAX_ACTION_INDEX = 255


def load_rows(path: Path) -> list[tuple[str, int, int, bool]]:
    payload = json.loads(path.read_text())
    rows: list[tuple[str, int, int, bool]] = []
    for entry in payload["entries"]:
        monster = str(entry["monster"]).lower()
        skill = int(entry["skill"])
        action_index = int(entry["action_index"])
        looping = bool(entry["looping"])
        if not monster or any(char.isspace() for char in monster):
            raise SystemExit(f"invalid monster name {monster!r}")
        if not 0 <= skill <= 0xFFFF:
            raise SystemExit(f"monster {monster}: skill id {skill} does not fit u16")
        if not 0 <= action_index <= MAX_ACTION_INDEX:
            raise SystemExit(f"monster {monster} skill {skill}: action index {action_index} is out of range")
        rows.append((monster, skill, action_index, looping))
    rows.sort()
    return rows


def ron_string(value: str) -> str:
    """Quote a RON string (the provenance contains a Windows path)."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(rows: list[tuple[str, int, int, bool]], provenance: dict) -> str:
    lines = [
        "// Official monster skill -> ACT action mapping for the client.",
        "//",
        "// Generated by `tools/gen_monster_skill_actions.py`; do not edit by hand.",
        "// Regenerate with: `./tools/gen_monster_skill_actions.py`",
        "// Drift check:      `./tools/gen_monster_skill_actions.py --check`",
        "//",
        "// Facts: `tools/data/monster_skill_motions.json`, extracted from the",
        "// official client's `data\\MonsterSkillInfo.xml` (data.grf) by",
        "// `tools/extract_monster_skill_motions.py`. The official",
        "// `CSession::GetMonsterSkillInfo` (`MonsterXmlActions.cpp:43`) looks the",
        "// row up by the monster's lower-cased job name and the skill id;",
        "// `CGameMode::NotifySkillCasting` (`GameModePackets.cpp:12958`) and",
        "// `CGameMode::ReceiveSkillUse` (`GameModePackets.cpp:18371`) then call",
        "// `SetAction(action * 8 - 8, 1, loopType == 0)`.",
        "//",
        "// Format: (monster, skill, action, looping). `action` is the ACT action",
        "// index (the official `action - 1`); `loop` is true when the official",
        "// `loopType` is non-zero (MT_LOOP) and false for a one-shot action",
        "// (MT_ONETIME, `loopType == 0`).",
        "//",
        "// The file is loaded at runtime through the normal client file loader, so a",
        "// server can override it without rebuilding the client; the compiled Rust",
        "// table is only the fallback for missing files.",
        "(",
        f'    provenance: {ron_string(provenance["source"])},',
        "    actions: [",
    ]
    for monster, skill, action_index, looping in rows:
        lines.append(
            f'        (monster: "{monster}", skill: {skill}, action: Action({action_index}), looping: {str(looping).lower()}),'
        )
    lines.extend(["    ],", ")", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--facts", default=str(DEFAULT_FACTS))
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--check", action="store_true", help="fail if the committed data file is out of date")
    args = parser.parse_args()

    facts_path = Path(args.facts)
    payload = json.loads(facts_path.read_text())
    rows = load_rows(facts_path)
    content = render(rows, payload["provenance"])
    output = Path(args.output)

    if args.check:
        current = output.read_text() if output.is_file() else ""
        if current != content:
            print(f"error: {output} is out of date; run ./tools/gen_monster_skill_actions.py", file=sys.stderr)
            return 1
        print(f"{output} is up to date ({len(rows)} entries)")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content)
    looping = sum(1 for _monster, _skill, _action, loop in rows if loop)
    print(f"{output}: {len(rows)} entries ({looping} looping, {len(rows) - looping} one-shot)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
