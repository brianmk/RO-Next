#!/usr/bin/env python3
"""Find classic learnable skills whose rustnarok effect definitions contain a
distinct asset (STR/SPR/ring/part/ground) that our skill-effect table does not
cover yet.

Inputs (committed, no game files needed):
  * tools/rustnarok_effects_facts.json — pinned rustnarok effect table.
  * tools/rathena_pre_re_learnable_skills.json — learnable Pre-Re skills.

Output: docs/rustnarok-skill-effect-candidates.json. The list is deliberately
conservative: effects that only contain generic hit/cast primitives (ids 0-3,
12, 16) and no asset are skipped — those add no visual over our generic cast
circle. Every candidate must still be archive-verified before it is ported.

Usage:
    ./tools/rustnarok_skill_effect_candidates.py
    ./tools/rustnarok_skill_effect_candidates.py --check
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / 'tools/rustnarok_effects_facts.json'
LEARNABLE = ROOT / 'tools/rathena_pre_re_learnable_skills.json'
EFFECTS = ROOT / 'korangar/archive/data/client/skill_effects.ron'
OUTPUT = ROOT / 'docs/rustnarok-skill-effect-candidates.json'

ASSET_PREFIXES = ('str', 'part', 'ring', 'spr', 'ground', 'unit', 'area', 'trap', 'rsm')
GENERIC_EFFECT_IDS = {0, 1, 2, 3, 12, 16}


def current_effect_skills() -> set[int]:
    text = EFFECTS.read_text()
    return {int(match) for match in re.findall(r'skill:\s*(\d+)', text)}


def asset_files(definitions: list[dict]) -> list[str]:
    found: set[str] = set()
    for definition in definitions:
        kind = definition.get('kind', '')
        if not kind.startswith(ASSET_PREFIXES):
            continue
        text = definition.get('text', '')
        for field in text.split(';'):
            if '=' not in field:
                continue
            key, value = field.split('=', 1)
            if key in {'file', 'textureName', 'spriteName'} and value and value != 'none':
                found.add(value)
    return sorted(found)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='fail when the candidate file is stale')
    args = parser.parse_args()

    facts = json.loads(FACTS.read_text())
    learnable = json.loads(LEARNABLE.read_text())['skills']
    known = current_effect_skills()

    by_skill: dict[int, list[dict]] = {}
    for effect in facts['effects']:
        if effect['id'] in GENERIC_EFFECT_IDS:
            continue
        files = asset_files(effect.get('definitions', []))
        if not files:
            continue
        for skill in effect.get('skills', []):
            if skill in known or str(skill) not in learnable:
                continue
            by_skill.setdefault(skill, []).append({
                'effect_id': effect['id'],
                'files': files,
                'definition_count': len(effect.get('definitions', [])),
            })

    candidates = [
        {
            'skill': skill,
            'description': learnable[str(skill)].get('description', ''),
            'effects': sorted(by_skill[skill], key=lambda row: row['effect_id']),
        }
        for skill in sorted(by_skill)
    ]

    payload = {
        'rustnarok_commit': facts.get('commit'),
        'provenance': 'Generated by tools/rustnarok_skill_effect_candidates.py from the pinned rustnarok facts and the learnable Pre-Re skill dump.',
        'candidate_count': len(candidates),
        'candidates': candidates,
    }
    serialized = json.dumps(payload, indent=2, ensure_ascii=False) + '\n'

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != serialized:
            print(f'{OUTPUT.relative_to(ROOT)} is stale; regenerate it', file=sys.stderr)
            return 1
        print(f'{OUTPUT.relative_to(ROOT)} is up to date ({len(candidates)} candidates)')
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(serialized)
    print(f'{OUTPUT.relative_to(ROOT)}: {len(candidates)} classic candidates with a distinct rustnarok asset')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
