#!/usr/bin/env python3
"""Extract the committed alias facts (`tools/alias_facts.json`) for the client.

The client keeps three alias tables that used to be generated by untracked
scripts and hand-patched when they drifted (e.g. the Assumptio icon):

* job id -> job whose client skill tree to use when the job's own tree is empty
  (`world/library/job_alias.rs`),
* monster job id -> verified existing monster/npc sprite
  (`world/library/monster_sprite_alias.rs`),
* skill id -> verified existing skill icon (`world/library/skill_icon_alias.rs`).

All three are *content data derived from the client data set*: they list the
exact `data\\sprite\\...` files that exist in the CondaRO archives for ids whose
canonical identity/icon file is missing from the partially trimmed data set.
This extractor rebuilds them deterministically from the authoritative sources
so the committed facts can be re-derived, checked in CI and audited:

  rAthena server tree (default `--ssh rathena --server-root /home/phantom/rathena`):
    src/common/mmo.hpp               enum e_job (server job ids/names)
    db/pre-re/mob_db.yml             pre-renewal monster ids + Aegis names
    db/re/mob_db.yml                 renewal mob db (see `MOB_DB_SUPPLEMENT`)
    db/pre-re/skill_tree.yml         server job skill-tree inheritance
    db/re/skill_tree.yml             (same, renewal; used for 4th/expanded jobs)

  CondaRO client archives (data.grf, CondaRO.grf, palettes.grf):
    data\\luafiles514\\lua files\\datainfo\\jobidentity.lub       JTtbl job identities
    data\\luafiles514\\lua files\\skillinfoz\\jobinheritlist.lub  JOBID + inherit lists
    data\\luafiles514\\lua files\\skillinfoz\\skilltreeview.lub   client skill trees
    data\\luafiles514\\lua files\\skillinfoz\\skillid.lub         SKID name -> id
    data\\luafiles514\\lua files\\skillinfoz\\skillinfolist.lub   skill -> icon file name
    the GRF file tables (sprite/icon existence probe)

The generated facts file contains the *verified result* of the resolution
algorithms plus the provenance (server HEAD, per-file SHA-256, archive SHA-256,
client table SHA-256) and per-row resolution methods, so `tools/gen_aliases.py`
can render the runtime RON table and `tools/test_gen_aliases.py` can prove
parity with the tables that were removed from Rust.

Usage:
    python3 tools/extract_alias_facts.py --ssh rathena --server-root /home/phantom/rathena
    python3 tools/extract_alias_facts.py --local /home/phantom/popeng-hotspots/condaro
    python3 tools/extract_alias_facts.py --help

Re-running the extractor against the same server tree/archives produces a
byte-identical `tools/alias_facts.json` (all iteration orders are explicit).
"""
