def parse_mob_db(text: str) -> list[tuple[int, str]]:
    """`- Id:` / `AegisName:` rows of an rAthena `mob_db.yml` (no PyYAML needed)."""
    rows: list[tuple[int, str]] = []
    current_id: int | None = None
    for raw_line in text.splitlines():
        id_match = re.match(r"^  - Id: (\d+)\s*$", raw_line)
        if id_match is not None:
            current_id = int(id_match.group(1))
            continue
        name_match = re.match(r"^    AegisName: ([A-Za-z0-9_]+)\s*$", raw_line)
        if name_match is not None and current_id is not None:
            rows.append((current_id, name_match.group(1)))
            current_id = None
    return rows


def parse_skill_trees(text: str) -> dict[str, dict]:
    """Job inheritance of an rAthena `skill_tree.yml` (only the `Inherit` lists)."""
    trees: dict[str, dict] = {}
    current: dict | None = None
    for raw_line in text.splitlines():
        job_match = re.match(r"^  - Job: ([A-Za-z0-9_]+)\s*$", raw_line)
        if job_match is not None:
            current = {"inherit": []}
            trees[job_match.group(1)] = current
            continue
        if current is not None:
            inherit_match = re.match(r"^      ([A-Za-z0-9_]+): true\s*$", raw_line)
            if inherit_match is not None:
                current["inherit"].append(inherit_match.group(1))
    return trees


def collect_server(ssh_host: str | None, server_root: str, local: str | None) -> dict:
    sources = {key: read_server_file(ssh_host, server_root, local, path) for key, path in SERVER_FILES.items()}
    files = {}
    for key, path in SERVER_FILES.items():
        payload = sources[key].encode("utf-8")
        files[path] = {"sha256": sha256_bytes(payload), "bytes": len(payload)}

    jobs = job_facts.parse_job_enum(sources["job_enum"])
    pre_re_trees = parse_skill_trees(sources["skill_tree_pre_re"])
    re_trees = parse_skill_trees(sources["skill_tree_re"])
    trees_by_key = {("pre_re", name): value for name, value in pre_re_trees.items()}
    for name, value in re_trees.items():
        trees_by_key.setdefault(("re", name), value)

    mob_db = parse_mob_db(sources["mob_db"])
    mob_db_renewal = dict(parse_mob_db(sources["mob_db_renewal"]))
    if not mob_db:
        raise SystemExit(f"could not parse any mob from {SERVER_FILES['mob_db']}")
    supplement = []
    known = {job_id for job_id, _ in mob_db}
    for job_id in MOB_DB_SUPPLEMENT:
        if job_id in known:
            continue
        aegis_name = mob_db_renewal.get(job_id)
        if aegis_name is None:
            raise SystemExit(
                f"mob {job_id} is in neither {SERVER_FILES['mob_db']} nor the renewal database; "
                "update MOB_DB_SUPPLEMENT"
            )
        supplement.append((job_id, aegis_name))
    mob_db.extend(supplement)
    mob_db.sort()
    if len({job_id for job_id, _ in mob_db}) != len(mob_db):
        raise SystemExit("duplicate mob id in the mob database")

    head = job_facts.fetch_server_head(ssh_host, server_root, local)
    return {
        "provenance": {"source": DEFAULT_SERVER_SOURCE, "head": head, "files": files},
        "jobs": [
            {"id": job_id, "name": job_name}
            for job_id, job_name in jobs
            if job_id not in SENTINEL_JOBS
        ],
        "mobs": [{"id": job_id, "aegis_name": aegis_name} for job_id, aegis_name in mob_db],
        "mobs_from_renewal_supplement": [
            {"id": job_id, "aegis_name": aegis_name} for job_id, aegis_name in supplement
        ],
        "skill_trees": {name: value for (kind, name), value in trees_by_key.items()},
    }


