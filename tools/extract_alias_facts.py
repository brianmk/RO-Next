def parse_monster_identities(data: bytes) -> dict[int, list[str]]:
    """Job id -> identity variants, mirroring the client `JTtbl` table cleaning."""
    by_id: dict[int, list[str]] = {}
    for key, job_id in job_facts.lua_table_rows(data):
        name = key.split(".")[-1]
        if not name.startswith("JT"):
            continue
        identity = job_facts.clean_identity_name(name).replace("CHONCHON", "chocho").lower()
        by_id.setdefault(int(job_id), [])
        if identity not in by_id[int(job_id)]:
            by_id[int(job_id)].append(identity)
    if not by_id:
        raise SystemExit(f"could not parse any job identity from {JOB_IDENTITY_PATH}")
    return by_id


def parse_client_job_tables(data: bytes) -> dict[str, dict]:
    """Tables of `jobinheritlist.lub` (Lua 5.1 bytecode).

    Returns `{"jobid": {name: id}, "inherit": {id: id}, "inherit2": {id: id}}`.
    The dump is a flat constructor sequence (`NEWTABLE`/`SETTABLE`/`SETGLOBAL`)
    without control flow, so the instruction emulation is exact.
    """
    code, constants = job_facts.lua_chunk(data)
    registers: dict[int, tuple] = {}
    table_entries: dict[int, list] = {}
    table_names: dict[int, bytes] = {}
    table_id = 0

    def read_register_or_constant(field: int) -> tuple | None:
        if field & 0x100:
            index = field & 0xFF
            return ("constant", constants[index]) if index < len(constants) else ("constant", None)
        return registers.get(field)

    for instruction in code:
        opcode = instruction & 0x3F
        a = (instruction >> 6) & 0xFF
        c = (instruction >> 14) & 0x1FF
        b = (instruction >> 23) & 0x1FF
        bx = (instruction >> 14) & 0x3FFFF

        if opcode == 1:  # LOADK
            registers[a] = ("constant", constants[bx])
        elif opcode == 5:  # GETGLOBAL
            registers[a] = ("global", constants[bx])
        elif opcode == 10:  # NEWTABLE
            table_id += 1
            table_entries[table_id] = []
            registers[a] = ("table", table_id)
        elif opcode == 6:  # GETTABLE
            base = read_register_or_constant(b)
            key = read_register_or_constant(c)
            if base is not None and base[0] == "global" and key is not None and key[0] == "constant":
                registers[a] = (base[1], key[1])
            else:
                registers[a] = ("other", None)
        elif opcode == 9:  # SETTABLE
            base = registers.get(a)
            key = read_register_or_constant(b)
            value = read_register_or_constant(c)
            if base is not None and base[0] == "table":
                table_entries[base[1]].append((key, value))
        elif opcode == 7:  # SETGLOBAL
            base = registers.get(a)
            if base is not None and base[0] == "table":
                table_names[base[1]] = constants[bx]

    named = {table_names[identifier]: table_entries[identifier] for identifier in table_names}
    for required in (b"JOBID", b"JOB_INHERIT_LIST", b"JOB_INHERIT_LIST2"):
        if required not in named:
            raise SystemExit(f"{JOB_INHERIT_LIST_PATH}: missing table {required!r} (format change?)")

    job_ids: dict[str, int] = {}
    for key, value in named[b"JOBID"]:
        if key is not None and value is not None and key[0] == "constant" and value[0] == "constant":
            if isinstance(value[1], float) and value[1].is_integer():
                job_ids[key[1].decode("latin-1")] = int(value[1])

    def inheritance_pairs(name: bytes) -> dict[int, int]:
        pairs: dict[int, int] = {}
        for key, value in named[name]:
            if key is None or value is None:
                continue
            # `setmetatable` calls after the constructors reuse the registers, so
            # only the `[JOBID.X] = JOBID.Y` rows are inheritance entries.
            if key[0] != b"JOBID" or value[0] != b"JOBID":
                continue
            pairs[job_ids[key[1].decode("latin-1")]] = job_ids[value[1].decode("latin-1")]
        minimum = 100 if name == b"JOB_INHERIT_LIST" else 10
        if len(pairs) < minimum:
            raise SystemExit(f"{JOB_INHERIT_LIST_PATH}: parsed only {len(pairs)} rows of {name!r}")
        return pairs

    return {
        "jobid": job_ids,
        "inherit": inheritance_pairs(b"JOB_INHERIT_LIST"),
        "inherit2": inheritance_pairs(b"JOB_INHERIT_LIST2"),
    }


